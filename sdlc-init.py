def do_bundle(out: Path) -> int:
    """Emit a single self-contained script with templates base64-embedded."""
    src = Path(__file__).resolve().read_text(encoding="utf-8")
    names = TEMPLATE_FILES + EXTRA_TEMPLATE_FILES
    emb = {name: base64.b64encode(load_template(name).encode("utf-8")).decode("ascii")
           for name in names}
    literal = "_EMBEDDED: dict[str, str] = " + json.dumps(emb, indent=0) + "\n"
    new_src, n = re.subn(r"^_EMBEDDED: dict\[str, str\] = \{\}\s*$", literal, src, count=1, flags=re.M)
    if n != 1:
        sys.exit("error: could not locate _EMBEDDED placeholder to bundle")
    write_lf(out, new_src)
    print(f"Wrote self-contained bundle -> {out} ({len(names)} templates embedded).")
    return 0


def do_dump_templates(dest: Path) -> int:
    names = TEMPLATE_FILES + EXTRA_TEMPLATE_FILES
    for name in names:
        write_lf(dest / name, load_template(name))
    print(f"Wrote {len(names)} templates -> {dest}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Install the portable SDLC harness into a repo.")
    ap.add_argument("--target", default=".", help="target repo root (default: current dir)")
    ap.add_argument("--workspace", metavar="TOML",
                    help="install for a multi-component workspace described by a filled-in "
                         "sdlc-workspace.toml (see sdlc_templates/workspace.example.toml). "
                         "Supplies WHICH components exist; --target still says where the "
                         "harness config is written")
    ap.add_argument("--tools", default="auto",
                    help="comma list of tools, 'auto' (detect), or 'all'")
    ap.add_argument("--force", action="store_true", help="overwrite an edited .sdlc/profile.yml")
    ap.add_argument("--claude-extras", action="store_true",
                    help="also install the Claude Code layer: reviewer subagents, a scoped "
                         "permission allowlist, and automation hooks")
    ap.add_argument("--dry-run", action="store_true", help="show planned writes, change nothing")
    ap.add_argument("--bundle", metavar="OUT", help="emit a single self-contained script and exit")
    ap.add_argument("--dump-templates", metavar="DIR", help="write embedded templates to DIR and exit")
    args = ap.parse_args(argv)

    if args.bundle:
        return do_bundle(Path(args.bundle))
    if args.dump_templates:
        return do_dump_templates(Path(args.dump_templates))

    root = Path(args.target).resolve()
    if not root.is_dir():
        sys.exit(f"error: target is not a directory: {root}")
    if not (root / ".git").exists() and not args.workspace:
        print(f"warning: {root} has no .git - per-row commits & rollback will be unavailable.")

    workspace = None
    if args.workspace:
        # A workspace config that cannot be trusted must not produce a half-right
        # component list, so every failure in here is fatal and prints as a message
        # rather than a traceback — the developer wrote this file, and a stack trace
        # blames the harness for their typo.
        try:
            workspace = read_workspace(Path(args.workspace))
        except WorkspaceError as exc:
            sys.exit(f"error: {exc}")

    if args.tools == "auto":
        tools = detect_tools(root)
    elif args.tools == "all":
        tools = ALL_TOOLS
    else:
        tools = [t.strip() for t in args.tools.split(",") if t.strip()]
        if "claude" not in tools:
            tools.insert(0, "claude")
        bad = [t for t in tools if t not in ALL_TOOLS]
        if bad:
            sys.exit(f"error: unknown tool(s): {', '.join(bad)} (valid: {', '.join(ALL_TOOLS)})")

    try:
        return install(root, tools, force=args.force, dry_run=args.dry_run,
                       claude_extras=args.claude_extras, workspace=workspace)
    except WorkspaceError as exc:
        sys.exit(f"error: {exc}")


if __name__ == "__main__":
    raise SystemExit(main())
