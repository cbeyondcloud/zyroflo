#: The two cadence flags, spelled ONCE and handed to both `add_argument` and the
#: refusals that offer them. They were spelled twice, and the refusals' copies drifted:
#: a blocked install printed `--publish-snapshot` and `--replay`, flags this parser has
#: never had, so the one command standing between the adopter and what they wanted
#: answered `error: unrecognized arguments` at exit 2. That is the class of items 134
#: and 156 - a document handing over a command nobody can run - arriving in the one
#: message a person is certain to act on. A constant is not ceremony here: it is the
#: only version of this that a rename cannot break silently.
FLAG_SNAPSHOT_CADENCE = "--snapshot-cadence"
FLAG_CORPUS_REPLAY = "--corpus-replay"


def workspace_rel_for_job(root: Path, workspace: Path) -> str | None:
    """Where a scheduled job that checks out `root` would find `workspace` — or
    None when it would not find it there at all.

    Both cadence workflows check out exactly two trees: this repository at
    `$GITHUB_WORKSPACE`, and the harness beneath it at `.sdlc-harness-ci`. There
    is nothing above `$GITHUB_WORKSPACE`, so a `../` in this value is a file the
    runner cannot open on any run, forever.

    `os.path.relpath` raises ValueError across Windows drives, which would be an
    unhandled traceback out of a guard whose whole contract is that a bad layout
    produces a message. A different drive is also, exactly, a location outside
    the checkout - so it is the same answer, not a special case.
    """
    try:
        rel = os.path.relpath(Path(workspace).resolve(), root.resolve())
    except ValueError:
        return None
    rel = rel.replace("\\", "/")
    return None if _escapes_root(rel) else rel


def no_workspace_in_checkout_reason(root: Path, workspace: Path,
                                    flag: str, cadence: str) -> str | None:
    """Why a job cannot name this workspace file, or None when it can.

    The same question `_ws_globs` already asks of every include glob, asked of the
    one path this installer writes into a workflow - and answered by the same
    predicate, because two implementations of *does this escape the root* is what
    let this one ship.

    The remedy has to survive being FOLLOWED. `read_workspace` resolves `root`
    relative to the workspace file, so 'move the file under the repo' on its own
    silently re-points `root` at wherever the file landed - narrowing a workspace
    with no error, and an empty one reads exactly like a clean one. So the remedy
    names the `root` value to set, not only the file to move.
    """
    if workspace_rel_for_job(root, workspace) is not None:
        return None
    return (f"{flag} needs a workspace file INSIDE the repository the job checks "
            f"out. The workflow checks out this repository and the harness and "
            f"nothing else, so `{Path(workspace).name}` - which sits outside "
            f"{root} - names a path no runner can open, and a job that fails "
            f"{cadence} is how a real check gets switched off. Put the file at the "
            f"top of {root} and set its `root` to \".\" (or a subdirectory of "
            f"{root} that holds your components), then re-run this. `root` is "
            f"resolved relative to the workspace file, so moving the file with "
            f"`root` left as-is silently re-points it at wherever the file landed - "
            f"narrowing your workspace with no error - and the job checks out only "
            f"{root}, so `root` has to name {root} or something inside it.")


def no_snapshot_job_reason(root: Path, workspace: Path | None,
                           harness: Path | None = None) -> str | None:
    """Why this install ships no weekly snapshot, or None when it does.

    The same three conditions the replay job needs, and for the same reasons -
    stated here rather than shared, because a future divergence between the two
    jobs would otherwise be silent. What differs is the last one's wording: this
    job BUILDS, so a workspace it cannot name is a job that fails every week.
    """
    if not (root / ".github").is_dir():
        return f"{root} has no .github/ - the snapshot is a GitHub Actions workflow"
    if not harness_repo_slug(harness):
        return ("this harness clone has no github.com `origin`, so the workflow "
                "has no repository to check the harness out FROM - and a URL "
                "written into the template would name one machine's fork in "
                "every repository this installer touches")
    if workspace is None:
        return (f"{FLAG_SNAPSHOT_CADENCE} needs a workspace file: the build has to "
                "know which components to extract, and a job that cannot name one "
                "would fail every week")
    return no_workspace_in_checkout_reason(
        root, workspace, FLAG_SNAPSHOT_CADENCE, "every week")


