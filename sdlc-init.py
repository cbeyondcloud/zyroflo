# ── file ops ──────────────────────────────────────────────────────────────────
def _read(path: Path) -> str | None:
    if not path.exists():
        return None
    return path.read_text(encoding="utf-8")


def _norm(s: str) -> str:
    return s.replace("\r\n", "\n").strip("\n")


class BlockMarkerError(Exception):
    """The harness-owned markers in a shared file are unbalanced."""


def merge_block(existing: str | None, block_body: str) -> str:
    """Replace the harness-owned block in a file the user also writes in.

    Refuses to guess when the markers are unbalanced, because "replace everything between
    BEGIN and END" is only safe when there is exactly one of each, in order. The real
    failure: a file with a BEGIN but no END fell through to the append branch, leaving two
    BEGINs and one END; the next run then took the FIRST BEGIN and the ONLY END and deleted
    everything between them — including every line the user had written in between. Silent
    data loss in the file the user is most likely to have edited by hand.
    """
    block = f"{BLOCK_BEGIN}\n\n{block_body}\n\n{BLOCK_END}\n"
    if existing is None:
        return block
    begins, ends = existing.count(BLOCK_BEGIN), existing.count(BLOCK_END)
    if begins == 0 and ends == 0:
        sep = "" if existing.endswith("\n") else "\n"
        return existing + sep + "\n" + block
    b, e = existing.find(BLOCK_BEGIN), existing.find(BLOCK_END)
    if begins != 1 or ends != 1 or e < b:
        raise BlockMarkerError(
            f"unbalanced harness markers ({begins}x BEGIN, {ends}x END"
            f"{', END before BEGIN' if 0 <= e < b else ''}). Refusing to edit this file: "
            f"replacing between mismatched markers would delete your own text. "
            f"Repair the markers by hand — keep exactly one '{BLOCK_BEGIN}' followed by one "
            f"'{BLOCK_END}' — then re-run."
        )
    return existing[:b] + block + existing[e + len(BLOCK_END):].lstrip("\n")


def plan_op(root: Path, rel: str, new_content: str, *, kind: str = "file", preserve: bool = False):
    """Compute a pending write. Returns dict(path, rel, status, content) or None if unchanged."""
    path = root / rel
    existing = _read(path)
    if kind == "block":
        try:
            final = merge_block(existing, new_content)
        except BlockMarkerError as exc:
            # Skip this one file rather than aborting: the rest of the install is still
            # correct, and the user needs the specific file named to repair it.
            return {"rel": rel, "status": "blocked", "path": path, "content": None,
                    "reason": str(exc)}
    elif preserve and existing is not None:
        if _norm(existing) == _norm(new_content):
            return {"rel": rel, "status": "unchanged", "path": path, "content": None}
        # user-edited profile: never clobber — stage alongside
        return {"rel": rel + ".new", "status": "preserved", "path": root / (rel + ".new"), "content": new_content}
    else:
        final = new_content
    if existing is None:
        status = "create"
    elif _norm(existing) == _norm(final):
        return {"rel": rel, "status": "unchanged", "path": path, "content": None}
    else:
        status = "update"
    return {"rel": rel, "status": status, "path": path, "content": final}


def write_lf(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


# ── optional Claude Code power layer (--claude-extras) ─────────────────────────
#: Commands that run whatever you hand them. `Bash(<tok>:*)` on any of these is a blanket
#: grant, not a scoped one.
INTERPRETERS = {"powershell", "pwsh", "cmd", "bash", "sh", "zsh", "dash", "ksh", "fish",
                "python", "python3", "py", "node", "deno", "bun", "ruby", "perl", "php",
                "env", "sudo", "npx", "pnpm", "yarn", "npm", "uv", "uvx", "docker", "wsl"}


def wrapper_permission(command: str) -> str | None:
    """Narrowest `Bash(...)` rule that still lets a repo's own check-in script run.

    Taking the first token is right for `./checkin.sh "{message}"` and catastrophic for
    `powershell -File ./checkin.ps1 "{message}"`: it yields `Bash(powershell:*)`, which
    lets an agent run `powershell -Command "git push"` straight through the deny_raw_git
    wall this function exists to build. So an interpreter is scoped by the whole command
    prefix up to the first placeholder, and a bare interpreter with nothing left to scope
    earns no rule at all — the agent gets a permission prompt, which is the safe direction.
    """
    # Strip the quote that opened the placeholder: `... ./checkin.ps1 "{message}"` leaves a
    # dangling `"` that would become part of the permission rule and match nothing.
    prefix = command.split("{")[0].strip().rstrip("\"'").strip()
    if not prefix:
        return None
    tokens = prefix.split()
    head = tokens[0]
    if Path(head).name.lower().removesuffix(".exe") not in INTERPRETERS:
        return f"Bash({head}:*)"
    return f"Bash({prefix}:*)" if len(tokens) > 1 else None


def build_settings(profile: dict, existing: dict | None) -> dict:
    """Merge a conservative permission allowlist + harness hooks into settings.json.

    Allows exactly the profile's test/coverage/lint/build binaries and the safe, local git
    the harness needs; denies destructive ops. Never clobbers existing settings keys.
    """
    allow = set()
    keys = ("test_command", "coverage_command", "lint_command", "build_command")
    # A multi-component profile keeps its commands per component and leaves the top
    # level blank, so reading only the top level would produce an allowlist that
    # permits none of the workspace's actual build tools — an install that looks
    # configured and prompts on every command.
    sources = [profile] + list(profile.get("components") or [])
    for source in sources:
        for key in keys:
            rule = wrapper_permission(str(source.get(key, "")).strip())
            if rule:
                allow.add(rule)
    vcs = profile.get("vcs") or {}
    safe_git = ["git status", "git diff", "git log", "git show", "git branch", "git rev-parse",
                "git checkout -b", "git switch", "git stash"]
    if not vcs.get("deny_raw_git"):
        safe_git += ["git add", "git commit", "git worktree"]
    for g in safe_git:
        allow.add(f"Bash({g}:*)")
    deny = {"Bash(git push --force:*)", "Bash(git push --force-with-lease:*)",
            "Bash(git reset --hard:*)", "Bash(git clean -f:*)", "Bash(rm -rf:*)"}
    if vcs.get("deny_raw_git"):
        # Raw git would reach the wrong remote / drop a second git dir - the repo's own
        # script is the only sanctioned path, so allow that binary and wall off the rest.
        deny |= {"Bash(git push:*)", "Bash(git commit:*)", "Bash(git worktree:*)"}
        for wrapper in (vcs.get("commit_command"), vcs.get("push_command")):
            rule = wrapper_permission((wrapper or "").strip())
            if rule:
                allow.add(rule)

    settings = dict(existing or {})
    perms = dict(settings.get("permissions", {}))
    perms["allow"] = sorted(set(perms.get("allow", [])) | allow)
    perms["deny"] = sorted(set(perms.get("deny", [])) | deny)
    settings["permissions"] = perms

    hooks = dict(settings.get("hooks", {}))
    autolint = {"matcher": "Edit|Write", "hooks": [{"type": "command",
                "command": 'python "$CLAUDE_PROJECT_DIR/.claude/hooks/sdlc-autolint.py"'}]}
    session = {"hooks": [{"type": "command",
               "command": 'python "$CLAUDE_PROJECT_DIR/.claude/hooks/sdlc-session-start.py"'}]}
    post = list(hooks.get("PostToolUse", []))
    if not any("sdlc-autolint" in json.dumps(h) for h in post):
        post.append(autolint)
    hooks["PostToolUse"] = post
    start = list(hooks.get("SessionStart", []))
    if not any("sdlc-session-start" in json.dumps(h) for h in start):
        start.append(session)
    hooks["SessionStart"] = start
    settings["hooks"] = hooks
    return settings


def claude_extras_ops(root: Path, profile: dict) -> list[dict]:
    """plan_ops for the optional Claude layer: subagents, hook scripts, settings.json, pointer."""
    ops = [plan_op(root, f".claude/{name}", load_template(name)) for name in EXTRA_TEMPLATE_FILES]

    existing = None
    sp = root / ".claude" / "settings.json"
    if sp.exists():
        try:
            existing = json.loads(sp.read_text(encoding="utf-8"))
        except Exception:
            existing = None  # unparseable -> overwrite with a clean merged file
    merged = build_settings(profile, existing)
    ops.append(plan_op(root, ".claude/settings.json", json.dumps(merged, indent=2) + "\n"))

    pointer = ("## SDLC workflow (harness)\n\n"
               "For any bug fix or feature, run the SDLC harness rather than ad-hoc edits:\n"
               "`/sdlc <task>` (or \"follow the sdlc workflow for: <task>\"). It reads "
               "`.sdlc/profile.yml` and walks 10 phases with two human approval gates; resume an "
               "interrupted run with `/sdlc resume`.")
    ops.append(plan_op(root, "CLAUDE.md", pointer, kind="block"))
    if (root / "AGENTS.md").exists():
        ops.append(plan_op(root, "AGENTS.md", pointer, kind="block"))
    return ops


# ── main install ──────────────────────────────────────────────────────────────
def workspace_profile(components: list[dict]) -> dict:
    """Top-level profile values for a multi-component install.

    The commands are deliberately BLANK. Every component carries its own, and a single
    top-level `test_command` for a workspace that has no single build is a claim the
    harness cannot honour — it would run one component's suite and report it as the
    workspace's.

    `deny_raw_git` is the union, not the intersection: if any component forbids raw git,
    the fallback forbids it too. Under-restricting is the direction that lets an agent
    push through a wall some component put up on purpose.
    """
    stacks = {c.get("stack", "unknown") for c in components}
    denied = sorted(c["name"] for c in components if (c.get("vcs") or {}).get("deny_raw_git"))
    return {
        "stack": stacks.pop() if len(stacks) == 1 else "mixed",
        "test_command": "", "coverage_command": "", "lint_command": "",
        "build_command": "", "deploy_command": "",
        "coverage_threshold": 90,
        "vcs": {
            "commit_command": "", "push_command": "", "deny_raw_git": bool(denied),
            "notes": ("raw git is denied by default because " + ", ".join(denied) +
                      " forbid it; per-component vcs blocks carry the specifics")
                     if denied else "",
        },
        "components": components,
    }


def _report_workspace(ws: dict, report: dict) -> list[str]:
    """Print what discovery found; return the findings to print with the other notes.

    Every note here is something the developer cannot see from the config file alone
    and would otherwise meet much later, as behaviour.
    """
    components = report["components"]
    print(f"  workspace      : {ws['root']}")
    print(f"  components     : {len(components)} "
          f"({'estate' if len(components) > 1 else 'repo'} scope, "
          f"gate_profile {'team' if len(components) > 1 else 'solo'})")
    for c in components:
        role = "" if c["role"] == DEFAULT_ROLE else f"  [{c['role']}]"
        print(f"    - {c['name']:<24} {c['stack']:<14} {c['path']}{role}")

    notes: list[str] = []
    if report["skipped"]:
        notes.append(
            f"{len(report['skipped'])} director"
            f"{'y' if len(report['skipped']) == 1 else 'ies'} under the workspace root had "
            f"no .git and are not components: {', '.join(report['skipped'][:8])}"
            f"{' ...' if len(report['skipped']) > 8 else ''}")
    shallow = [c["name"] for c in components if c["shallow"]]
    if shallow:
        # Reported, never filtered: a shallow clone is readable but un-diffable, so half
        # the harness works on it. That is a finding, not a reason to hide it.
        notes.append(
            f"shallow clone(s): {', '.join(shallow)}. Readable but un-diffable, so impact "
            f"and changed-file coverage over their history will be wrong. Run "
            f"`git fetch --unshallow` in each before relying on those.")
    if not ws["name"]:
        notes.append(
            "`name` is blank in your workspace file, so the leak guard has no workspace "
            "term to protect. Set it, then run `python tools/tests/ban.py "
            "--from-workspace <file>` to seed the ban list.")
    return notes


def install(root: Path, tools: list[str], force: bool, dry_run: bool,
            claude_extras: bool = False, workspace: dict | None = None) -> int:
    skill_meta, skill_body = parse_frontmatter(load_template("SKILL.md"))
    description = skill_meta.get("description", "Run the full SDLC for a bug fix or feature.")
    report: dict | None = None
    if workspace is None:
        profile = detect_stack(root)
        profile["vcs"] = detect_vcs(root)
    else:
        # `--workspace` supplies the CONTENT (which components exist); `--target` still
        # supplies the LOCATION. The harness points AT the workspace through this config
        # and keeps zero footprint inside the components themselves.
        report = discover_components(workspace)
        profile = workspace_profile(report["components"])

    ops: list[dict] = []
    # Shared harness data (.sdlc/)
    ops.append(plan_op(root, ".sdlc/profile.yml", render_profile(profile, tools),
                       preserve=not force))
    ops.append(plan_op(root, ".sdlc/review-rubric.md", load_template("review-rubric.md")))
    ops.append(plan_op(root, ".sdlc/plan-template.md", load_template("plan-template.md")))
    ops.append(plan_op(root, ".sdlc/plans/.gitkeep", ""))
    # Per-tool entry points
    for tool in tools:
        for rel, content, kind in tool_files(tool, skill_body, description):
            ops.append(plan_op(root, rel, content, kind=kind))
    # Optional Claude Code power layer
    extras_skipped = claude_extras and "claude" not in tools
    if claude_extras and "claude" in tools:
        ops.extend(claude_extras_ops(root, profile))

    # Report + execute
    print(f"SDLC harness -> {root}")
    ws_notes: list[str] = []
    if report is not None:
        ws_notes = _report_workspace(workspace, report)
    else:
        print(f"  stack detected : {profile['stack']}")
        print(f"  test command   : {profile['test_command'] or '(none - edit .sdlc/profile.yml)'}")
    print(f"  tools          : {', '.join(tools)}")
    _vcs = profile["vcs"]
    print(f"  vcs            : {_vcs['commit_command'] or 'git (default)'}"
          f"{'  [raw git DENIED]' if _vcs['deny_raw_git'] else ''}")
    print(f"  claude extras  : {'on' if (claude_extras and not extras_skipped) else 'off'}")
    print("  files:")
    changed = 0
    for op in ops:
        mark = {"create": "+ create", "update": "~ update", "unchanged": "= unchanged",
                "preserved": "! preserved (edited -> wrote .new)",
                "blocked": "x BLOCKED (markers unbalanced)"}[op["status"]]
        print(f"    {mark:<38} {op['rel']}")
        if op["status"] not in ("unchanged", "blocked"):
            changed += 1
            if not dry_run:
                write_lf(op["path"], op["content"])

    for op in (o for o in ops if o["status"] == "blocked"):
        print(f"\n  NOTE: {op['rel']} was left untouched — {op['reason']}")

    for note in ws_notes:
        print(f"\n  NOTE: {note}")

    if profile["stack"] == "unknown":
        print("\n  NOTE: stack not recognised - .sdlc/profile.yml has blank commands; fill them in before running /sdlc.")
    if profile["vcs"]["deny_raw_git"] and not profile["vcs"]["commit_command"]:
        print("\n  NOTE: raw git is unsafe here (" + profile["vcs"]["notes"].split(" - ")[0] +
              ") but no check-in script was found. Set vcs.commit_command in .sdlc/profile.yml"
              " before running /sdlc, or the harness will stop and ask.")
    if any(op["status"] == "preserved" for op in ops):
        print("\n  NOTE: your edited .sdlc/profile.yml was kept; the new version is at .sdlc/profile.yml.new (diff & merge, or re-run with --force).")
    if extras_skipped:
        print("\n  NOTE: --claude-extras ignored (Claude Code is not in the tool set).")

    if dry_run:
        print(f"\n[dry-run] {changed} file(s) would change. Nothing written.")
        return 0

    print(f"\nDone. {changed} file(s) written.")
    if claude_extras and not extras_skipped:
        print("Claude extras: subagents + auto-lint/session hooks + a scoped permission allowlist"
              " were installed (settings.json merged, not clobbered).")
    elif "claude" in tools:
        print("Tip: add --claude-extras for reviewer subagents, a no-prompt permission allowlist,"
              " and automation hooks (Claude Code only).")
    print("Next: open this repo in an AI coding tool and run  /sdlc <your bug or feature>")
    print("      (or 'follow the sdlc workflow for: <task>' in tools without slash commands).")
    return 0


