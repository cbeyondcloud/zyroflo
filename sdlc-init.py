# Populated only in a bundled copy (see --bundle). Maps template filename -> base64 body.
_EMBEDDED: dict[str, str] = {}


# ── template loading ──────────────────────────────────────────────────────────
def _template_dir() -> Path:
    return Path(__file__).resolve().parent / "sdlc_templates"


def load_template(name: str) -> str:
    """Prefer the editable sibling file; fall back to an embedded (bundled) copy."""
    p = _template_dir() / name
    if p.exists():
        return p.read_text(encoding="utf-8")
    if name in _EMBEDDED:
        return base64.b64decode(_EMBEDDED[name]).decode("utf-8")
    sys.exit(f"error: template '{name}' not found (no sdlc_templates/ dir and no embedded copy)")


#: The functions that CONSUME the bundled set rather than name templates: their own
#: `load_template(name)` iterates the derived set and must not be read as a source.
_BUNDLE_SINK_FUNCS = frozenset({"do_bundle", "do_dump_templates"})


def _loaded_template_names(source: str | None = None) -> list[str]:
    """Every template name `load_template` can be asked for, DERIVED from this
    module's own call sites so the bundled set cannot drift out of step with them.

    It reads the AST: the template name is a `load_template` call's first POSITIONAL
    argument OR its `name=` keyword, taken when that is a string literal or a
    module-level list constant iterated to feed it (`for n in EXTRA_TEMPLATE_FILES`).
    `do_bundle` / `do_dump_templates` consume the result, so their own calls are not
    counted. Every other shape is UNRESOLVED and refused here, at bundle-build time,
    rather than shipping a bundle that silently omits a template: a computed argument,
    `**kwargs`, and any BARE reference to `load_template` (an alias, a functools.partial,
    a lookup in a container) that could load a name this text cannot see.

    A syntax-tree read approximates what the program DOES by what it SAYS, so it is
    blind to some spellings by construction -- string-form lookups such as
    `getattr(mod, "load_template")` are a Constant, not a Name, and are not caught.
    That axis is covered by a check of a different KIND: a test spawns the installer
    with every flag and asserts none fails template-not-found (test_drop_in_fanout).

    The bug this closes: snapshot-publish.yml and corpus-replay.yml are loaded on
    demand (snapshot_job_ops / replay_job_ops) but sat in neither hand-kept bundle
    list, so a bundle embedded 11 of 13 and died at the adopter's first
    --snapshot-cadence / --corpus-replay. A hand-kept list drifted twice; a derived
    set cannot.
    """
    if source is None:
        source = Path(__file__).resolve().read_text(encoding="utf-8")
    tree = ast.parse(source)
    const_lists: dict[str, list[str]] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.List):
            elts = node.value.elts
            strs = [e.value for e in elts
                    if isinstance(e, ast.Constant) and isinstance(e.value, str)]
            if elts and len(strs) == len(elts):
                for tgt in node.targets:
                    if isinstance(tgt, ast.Name):
                        const_lists[tgt.id] = strs

    names: list[str] = []
    unresolved: list[str] = []

    class _Collector(ast.NodeVisitor):
        def __init__(self) -> None:
            self.func: list[str] = []            # enclosing def name stack
            self.bound: dict[str, str] = {}      # loop var -> const-list name

        def visit_FunctionDef(self, node):
            self.func.append(node.name)
            self.generic_visit(node)
            self.func.pop()

        visit_AsyncFunctionDef = visit_FunctionDef

        def _scoped(self, generators, body):
            added = []
            for g in generators:
                if (isinstance(g.target, ast.Name)
                        and isinstance(g.iter, ast.Name)
                        and g.iter.id in const_lists):
                    self.bound[g.target.id] = g.iter.id
                    added.append(g.target.id)
            body()
            for a in added:
                self.bound.pop(a, None)

        def visit_ListComp(self, node):
            self._scoped(node.generators, lambda: self.generic_visit(node))

        visit_SetComp = visit_ListComp
        visit_GeneratorExp = visit_ListComp
        visit_DictComp = visit_ListComp

        def visit_For(self, node):
            gens = [node] if isinstance(node.target, ast.Name) else []
            self._scoped(gens, lambda: self.generic_visit(node))

        def _name_from(self, arg):
            """Template names an argument node resolves to, or None if it cannot."""
            if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
                return [arg.value]
            if isinstance(arg, ast.Name) and arg.id in self.bound:
                return list(const_lists[self.bound[arg.id]])
            return None

        def visit_Call(self, node):
            if isinstance(node.func, ast.Name) and node.func.id == "load_template":
                # the name is the first POSITIONAL argument or the `name=` keyword
                arg = node.args[0] if node.args else next(
                    (kw.value for kw in node.keywords if kw.arg == "name"), None)
                resolved = self._name_from(arg) if arg is not None else None
                if resolved is not None:
                    names.extend(resolved)
                elif not (self.func and self.func[-1] in _BUNDLE_SINK_FUNCS):
                    unresolved.append("unresolvable load_template(...) argument")
                # visit the ARGUMENTS (never the callee, which is a legitimate call)
                # so a bare load_template reference nested in an argument is still seen
                for a in node.args:
                    self.visit(a)
                for kw in node.keywords:
                    self.visit(kw.value)
                return
            self.generic_visit(node)

        def visit_Name(self, node):
            # A load_template NAME reached here is never a callee -- those are handled
            # above and their callee is not visited -- so it is a BARE reference: an
            # alias (`f = load_template`), a functools.partial, an element of a list.
            # It could load anything at run time, so it is refused, not guessed.
            if node.id == "load_template":
                unresolved.append("bare reference to load_template")

    _Collector().visit(tree)
    if unresolved:
        sys.exit("error: load_template is used in a way the bundler cannot resolve to "
                 "a template name (" + "; ".join(sorted(set(unresolved))) + ") -- call "
                 "it with a string literal or a module-level list constant, positionally "
                 "or as name=..., or teach _loaded_template_names() the new shape.")
    seen: dict[str, None] = {}
    for n in names:
        seen.setdefault(n, None)
    return list(seen)


def parse_frontmatter(text: str) -> tuple[dict, str]:
    """Split a leading '---' YAML frontmatter block from the body. Minimal parser."""
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    raw = text[3:end].strip()
    body = text[end + 4:].lstrip("\n")
    meta: dict[str, str] = {}
    for line in raw.splitlines():
        if ":" in line:
            k, _, v = line.partition(":")
            meta[k.strip()] = v.strip()
    return meta, body


# ── detection ─────────────────────────────────────────────────────────────────
def _exists(root: Path, *names: str) -> bool:
    return any((root / n).exists() for n in names)


#: Directories the marker scan never descends into. This MIRRORS
#: `tools/graph/core/lib/repo_walk.DEFAULT_EXCLUDES` and deliberately does not import it:
#: this file is stdlib-only by gate and that module is not. Bounded duplication is the
#: price of the zero-dependency install path — the same trade `workspace_report.STACK_PROBES`
#: makes against this table, and it is pinned the same way, by a contract test.
_SCAN_EXCLUDES = frozenset({
    ".git", ".svn", ".hg", "node_modules", "target", "build", "dist", "out",
    ".venv", "venv", "__pycache__", ".pytest_cache", ".mypy_cache",
    ".idea", ".vscode", "vendor", "coverage", ".next", ".nuxt", "bin", "obj",
    ".dart_tool", ".sdlc-worktrees",
})

#: How deep the marker scan looks. Build manifests sit at the root or a level or two down
#: (`services/orders/pom.xml`, `packages/web/package.json`); past that the walk costs more
#: and finds nothing new. **Bounded and stated, rather than unbounded and invisible** — the
#: previous implementation walked the ENTIRE tree, unpruned, on every non-Python repository,
#: because `**/test_*.py` sat in an `or` chain and was evaluated whenever the cheap root
#: checks missed.
_SCAN_MAX_DEPTH = 3

#: Build manifests, in the order that breaks a tie between equally-graded evidence.
#: A manifest is **strong** evidence: a repository declaring how it is built is the closest
#: thing to a statement of intent that a scanner can read. `(stack, exact names, suffixes)`.
_STRONG_MARKERS: tuple[tuple[str, tuple[str, ...], tuple[str, ...]], ...] = (
    ("python", ("pyproject.toml", "setup.py", "setup.cfg", "pytest.ini", "tox.ini"), ()),
    ("javascript", ("package.json",), ()),
    ("go", ("go.mod",), ()),
    ("rust", ("Cargo.toml",), ()),
    ("java-maven", ("pom.xml",), ()),
    ("java-gradle", ("build.gradle", "build.gradle.kts"), ()),
    ("dotnet", (), (".sln", ".csproj")),
    ("ruby", ("Gemfile",), (".gemspec",)),
    ("cpp-cmake", ("CMakeLists.txt",), ()),
)

_STACK_ORDER = {stack: i for i, (stack, _, _) in enumerate(_STRONG_MARKERS)}


def _strong_stacks(name: str) -> tuple[str, ...]:
    return tuple(stack for stack, names, suffixes in _STRONG_MARKERS
                 if name in names or any(name.endswith(s) for s in suffixes))


def _weak_stacks(name: str) -> tuple[str, ...]:
    """Files that appear in repositories of every language and name a stack only when
    nothing stronger does.

    **This is the distinction whose absence was the defect.** A root `requirements.txt` is
    routinely a docs build, a pre-commit config or a CI helper script inside a repository
    with no Python in it at all, and `test_*.py` anywhere in a large tree says almost
    nothing about what the repository IS. Both used to claim a repository outright, ahead
    of every build manifest, because they sat first in a first-match chain.

    A bare `tests/` DIRECTORY is deliberately no longer evidence of anything: the
    convention is universal across languages, and any `test_*.py` actually inside it is
    found by the walk on its own merits.
    """
    if name in ("requirements.txt", "conftest.py"):
        return ("python",)
    if name.startswith("test_") and name.endswith(".py"):
        return ("python",)
    return ()


#: The reparse tags of the two Windows links the scan neither enters nor counts - a symlink
#: and a junction (mount point) - as `repo_walk` has them since T592. Only these: a cloud-files
#: placeholder is a reparse point too, and a real directory (T606). By value where `stat` lacks
#: the names, as it does off Windows; the values are the Windows SDK's own.
_LINK_TAGS = (getattr(stat, "IO_REPARSE_TAG_SYMLINK", 0xA000000C),
              getattr(stat, "IO_REPARSE_TAG_MOUNT_POINT", 0xA0000003))


def _is_link(path: Path) -> bool:
    """A symlink or a Windows junction, read without following it: by its mode, or by its
    reparse tag. Every reparse point was read as a link, so a real directory a cloud-files
    client marks as a placeholder was never entered and its units went uncounted (T606,
    decision 37)."""
    try:
        st = os.lstat(path)
    except OSError:
        return False
    return stat.S_ISLNK(st.st_mode) or getattr(st, "st_reparse_tag", 0) in _LINK_TAGS


def _scan_markers(root: Path, max_depth: int = _SCAN_MAX_DEPTH) -> dict[str, dict]:
    """One pruned walk collecting every marker the tree carries, `max_depth` levels
    deep: the stated `_SCAN_MAX_DEPTH`, unless a caller asks for more (`build_units`
    counts units with no bound, T569). A directory that is a link - a symlink or a
    Windows junction - is not entered: with no bound, a link back up the tree counted
    every unit once per level (review B12-3). `os.walk` leaves a symlink alone too, but
    enters a junction; this walk enters neither (B12-16), and since T592 neither does
    `repo_walk`'s fallback - both know the two by reparse tag, and any other reparse point,
    a cloud-files placeholder among them, is a directory like any other (T606). A unit
    reached only through a link - a project outside the repository, linked into it - is
    therefore not counted (B12-17, T597).

    Returns `{stack: {"strong_depth": int|None, "count": int, "dirs": set[str]}}`, where
    `strong_depth` is the shallowest build manifest found for that stack and `None` means
    only weak evidence turned up, `count` is every marker found, weak ones included, and
    `dirs` is every directory holding one of the stack's build manifests. One walk rather
    than one per stack: the cost is paid once, and every stack is graded against the same
    evidence instead of the first match winning by position.
    """
    found: dict[str, dict] = {}

    def record(stack: str, depth: int, strong: bool, where: Path | None = None) -> None:
        entry = found.setdefault(stack, {"strong_depth": None, "count": 0,
                                         "dirs": set()})
        entry["count"] += 1
        if strong:
            prior = entry["strong_depth"]
            entry["strong_depth"] = depth if prior is None else min(prior, depth)
            # WHERE the manifests are, not just how many. A refusal that says
            # "17 build units" and cannot name one is a refusal nobody can act
            # on; `build_units` prints a sample of these. Every directory, not
            # only the sample (T515): the directories ARE the count, and a set
            # capped at the sample could never say how many it left out.
            if where is not None:
                entry["dirs"].add(where.as_posix())

    pending = [(root, 0)]
    while pending:
        directory, depth = pending.pop()
        try:
            entries = list(directory.iterdir())
        except OSError:
            continue                      # unreadable dir: skip it, never abort the scan
        for entry in entries:
            try:
                is_dir = entry.is_dir()
            except OSError:
                continue
            if is_dir:
                # Dot-directories are pruned wholesale. No build manifest this table knows
                # about lives in one, and descending them is how a bounded scan quietly
                # stops being bounded. A link is never entered (B12-3).
                if (depth < max_depth and entry.name not in _SCAN_EXCLUDES
                        and not entry.name.startswith(".") and not _is_link(entry)):
                    pending.append((entry, depth + 1))
                continue
            try:
                rel = directory.relative_to(root)
            except ValueError:              # pragma: no cover - root is the walk seed
                rel = Path(".")
            for stack in _strong_stacks(entry.name):
                record(stack, depth, True, rel)
            for stack in _weak_stacks(entry.name):
                record(stack, depth, False)
    return found


#: How many manifest directories a refusal names before it stops listing. Enough
#: to recognise the shape of the repository, short enough to read.
_UNIT_SAMPLE_CAP = 6


def _named_dirs(dirs: list[str]) -> str:
    """Directories as a refusal names them: the first `_UNIT_SAMPLE_CAP`, then how many more."""
    more = len(dirs) - _UNIT_SAMPLE_CAP
    return ", ".join(dirs[:_UNIT_SAMPLE_CAP]) + (f", and {more} more" if more > 0 else "")


#: T531's directory rule, the installer's own copy: this file imports nothing from `tools/`,
#: and `repo_walk.looks_like_test` is the original (`test_stack_detection` keeps the two
#: from drifting). Directory names that conventionally mean test code, matched case-folded;
#: `it` is not one - as a bare directory it is as often a package or a locale.
_TEST_DIRS = frozenset({"test", "tests", "testing", "spec", "specs", "e2e"})
#: A source set's name under `src/` for the layout that has them: these hold tests, and
#: `main` holds production code.
_TEST_SOURCE_SETS = frozenset({"test", "it"})
#: Directory names that conventionally hold example projects, matched case-folded (T597).
_EXAMPLE_DIRS = frozenset({"example", "examples", "sample", "samples"})


def _test_or_example(rel: str) -> bool:
    """Whether a unit directory - root-relative, `/`-separated - is test code or an example
    rather than a unit of the repository's own (T597). T531's rule for the directories a
    file sits in, with example trees counted as test directories are: below a `src/main/`
    source set a directory name is a package name; `src/test/` and `src/it/` are test
    source sets; a source set kept under a test or example directory is a fixture,
    `src/main/` included; elsewhere, any test or example directory on the path."""
    dirs = [part.lower() for part in rel.split("/") if part not in ("", ".")]
    conventional = _TEST_DIRS | _EXAMPLE_DIRS
    for i in range(len(dirs) - 1):
        if dirs[i] == "src":
            if any(d in conventional for d in dirs[:i]):
                return True
            if dirs[i + 1] == "main":
                return False
            if dirs[i + 1] in _TEST_SOURCE_SETS:
                return True
    return any(d in conventional for d in dirs)


def _unit_depth(rel: str) -> int:
    """How many directories below the root a unit sits: the root itself is 0."""
    return 0 if rel == "." else len(rel.split("/"))


def build_units(root: Path) -> dict:
    """Whether this repository is built from SEVERAL units, and where they are.

    A single-repository install declares no `components:`, and `policy.components`
    then synthesises one component rooted at `.` - the degenerate case of the
    same model, and correct for a repository that really is one build. For a
    repository that is not, it is a claim nobody made and nothing checks, and
    the field run measured what it costs twice over: P2 scoping produced a
    1,189-edge impact map because every path belonged to the one component, and
    P5's supply-chain gate inherited the WHOLE repository's dependencies and
    reported 102 blocking findings against a two-file change. **Neither was
    fixable once the run had started**, because the gates pin artifacts that
    name the model.

    So it is answered here, at the one moment somebody is looking. The signal is
    the repository's own declarations: build manifests BELOW the root (tier B,
    which `detect_stack` already reports in `stack_note`) and more than one of
    them. A manifest AT the root is a repository that builds as a whole,
    whatever else it contains, and is not this case.

    **A unit is a directory holding a build manifest** (T515), so `count` is how
    many there are. It used to be every marker the scan found: a root
    `requirements.txt`, any `conftest.py` and every `test_*.py` counted as units,
    and two manifests in one directory counted twice. The refusal printed that
    number, the recorded `--single-component` assertion carried it, and adding one
    test file made the record stale and the next plain run refuse. `markers` is that
    older count, kept for one purpose: explaining a record an older installer wrote,
    which is asked about rather than honoured, since it cannot say how many units the
    yes was about.

    **Test code and examples are not units (T597).** The count took in every directory
    holding a manifest of the stack - test fixtures and example projects included - so a
    repository with one real nested unit and a fixture was refused as several, and a
    recorded `units: N` moved whenever a fixture was added. A directory under a test or
    example tree, by `_test_or_example`, is left out, and named in `left_out` wherever the
    count is shown - never dropped. A stack whose every manifest is left out is passed over
    for the next ranked stack that holds a unit, so fixtures of one stack never hide the
    units of another. And when no stack within the stack scan's bound holds a unit, the
    walk with no bound ranks the tree, so units that all sit deeper are counted - several
    refused as nested units are, one named (`deep`) - rather than installed in silence.

    What this does not see, said rather than claimed: a test or example project in a
    directory the convention does not name (Go's `testdata/`, a `Foo.Tests/` beside
    `Foo/`, a bare `fixtures/`) is counted; a template project kept under `src/main/` is
    counted, since below it a directory name is a package name; and `detect_stack`
    still ranks its label by every manifest, fixtures included.
    """
    # T569: the stack is detected within `_SCAN_MAX_DEPTH` levels, a stated bound on a
    # heuristic; its units are COUNTED by a walk that bound does not stop, pruned the
    # same way, because the count is load-bearing - refused on, recorded as `units: N`
    # and reasoned about. `markers` stays the bounded scan's, as older installers read.
    bounded = _scan_markers(root)
    unbounded = _scan_markers(root, max_depth=sys.maxsize)

    def units_of(stack: str) -> tuple[list[str], list[str]]:
        found = sorted(unbounded.get(stack, {}).get("dirs", ()))
        return ([d for d in found if not _test_or_example(d)],
                [d for d in found if _test_or_example(d)])

    ranked = _rank(bounded)
    primary = next((stack for stack, _, _ in ranked if units_of(stack)[0]), None)
    if primary is None:
        ranked_deep = _rank(unbounded)
        primary = next((stack for stack, _, _ in ranked_deep if units_of(stack)[0]), None)
        ranked = ranked or ranked_deep
    if primary is None:
        if not ranked:
            return {"multi": False, "stack": "", "count": 0, "markers": 0, "dirs": [],
                    "left_out": [], "deep": False}
        primary = ranked[0][0]          # every manifest it has is test code or an example
    dirs, left_out = units_of(primary)
    # A manifest AT the root is one build, whatever lies below it; `.` is never left out.
    return {"multi": "." not in dirs and len(dirs) > 1, "stack": primary,
            "count": len(dirs), "markers": bounded.get(primary, {}).get("count", 0),
            "dirs": dirs, "left_out": left_out,
            "deep": bool(dirs) and min(map(_unit_depth, dirs)) > _SCAN_MAX_DEPTH}


def _rank(found: dict[str, dict]) -> list[tuple[str, str, int]]:
    """`_rank_stacks` over a scan already made (T597 ranks the walk with no bound too)."""
    ranked = []
    for stack, e in found.items():
        depth = e["strong_depth"]
        tier = "C" if depth is None else ("A" if depth == 0 else "B")
        ranked.append((stack, tier, e["count"]))
    ranked.sort(key=lambda r: ("ABC".index(r[1]), -r[2], _STACK_ORDER.get(r[0], 99)))
    return ranked


def _rank_stacks(root: Path) -> list[tuple[str, str, int]]:
    """Every stack the repository declares, strongest first, as `(stack, tier, count)`.

    Three tiers, so no numeric threshold has to be invented or defended:
    **A** a build manifest at the repository root · **B** the same manifest nested within
    the depth bound · **C** weak evidence only. Within a tier, more markers wins, and the
    declared order of `_STRONG_MARKERS` breaks a remaining tie — documented and stable,
    rather than the accident of chain position that this replaces.

    **Tier C never outranks A or B**, which alone fixes the case that opened this: ten
    `test_*.py` files beating four `pom.xml`.

    `count` is returned because the caller needs it to tell a rival from a passenger, and
    that distinction is where this could most easily overreach: a Python repository with a
    `package.json` for prettier has two claims at the root and is not ambiguous at all.
    **Strictly more of the repository's own declarations pointing one way is evidence; the
    same number pointing each way is a genuine tie** — and only the tie is unanswerable
    from inside the repository, which is the test for whether detection may decide.
    """
    return _rank(_scan_markers(root))


