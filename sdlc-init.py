    unwritten = sum(o.get("cause") == BLOCKED_UNWRITABLE for o in ops)

    # Record digests for preserve-capable files so the next run can tell an
    # adopter's edit from an installer-side value change (T382). Derived from
    # plan_op's own _preserve flag so the set has a single reader (T382 rd 5).
    preserve_rels = frozenset(
        op["rel"][:-len(".new")] if op["rel"].endswith(".new") else op["rel"]
        for op in ops if op.get("_preserve"))
    digest_write_error = None
    if not dry_run:
        updated_digests = dict(installed_digests)
        for op in ops:
            rel = op["rel"]
            status = op["status"]
            if status in ("create", "update") and rel in preserve_rels:
                # The installer wrote this content; record its digest.
                updated_digests[rel] = _content_digest(op["content"])
            elif status == "unchanged" and rel in preserve_rels:
                # File matches what the installer would write; record or refresh
                # the digest (needed on the first run with digest tracking, and
                # harmless on later ones — the value is the same).
                updated_digests[rel] = _content_digest(_read(op["path"]))
            # For "preserved", "outdated" and "unverified", the existing file
            # stays unchanged and its digest (if any) remains correct — do NOT
            # record the existing content's digest, or a hand-edited file would
            # be blessed as installer-written on the second re-run.
        digest_write_error = _write_installed_digests(
            root, updated_digests, preserve_rels)

    for op in (o for o in ops if o["status"] == "blocked"):
        # "left untouched" is true of a file that EXISTS. Three of the absent/damaged
        # causes are files this install never wrote, and telling an adopter their absent
        # workflow was left untouched sends them looking for it. The could-not-look cause
        # is a file that EXISTS (the read got past the existence check and failed on the
        # bytes), so its verb is FIXED rather than re-derived from Path.exists(), which
        # swallows an OSError into *was not written* - the on-disk file it describes.
        # A failed write's verb is fixed too (T517): the file may or may not exist,
        # and either way what the adopter needs to know is that the write failed.
        if op["cause"] == BLOCKED_UNREADABLE:
            verb = "could not be read"
        elif op["cause"] == BLOCKED_UNWRITABLE:
            verb = "could not be written"
        else:
            verb = "was left untouched" if op["path"].exists() else "was not written"
        print(f"\n  NOTE: {op['rel']} {verb} — {op['reason']}")

    # T566: a permission rule the merged settings carry that defeats a deny rule the
    # installed policy holds. The rule is the adopter's, so it is kept and said, never
    # removed or refused.
    for op in ops:
        for finding in grouped_findings(op.get("selfcheck", [])):
            print(f"\n  NOTE: {op['rel']}: {finding}. The rule is yours, so it was kept "
                  f"- narrow or remove it if that is not what you meant.")

    for note in ws_notes:
        print(f"\n  NOTE: {note}")

    if withheld_note:
        print(f"\n  NOTE: {withheld_note}")

    if single_component_note:
        # T244 round 2 (review W376 finding 2): the override must never be a
        # silence. Printed even though the file itself is `= unchanged` below —
        # that line alone cannot tell a reader "one build unit" from "many,
        # overridden by a record".
        print(f"\n  NOTE: {single_component_note}")

    if deep_note:
        print(f"\n  NOTE: {deep_note}.")

    if left_note:
        print(f"\n  NOTE: {left_note}.")

    if profile["stack"] == "unknown":
        print("\n  NOTE: stack not recognised - .sdlc/profile.yml has blank commands; fill them in before running /sdlc.")
    if profile["vcs"]["deny_raw_git"] and not profile["vcs"]["commit_command"]:
        print("\n  NOTE: raw git is unsafe here (" + profile["vcs"]["notes"].split(" - ")[0] +
              ") but no check-in script was found. Set vcs.commit_command in .sdlc/profile.yml"
              " before running /sdlc, or the harness will stop and ask.")
    # Named per file, not hardcoded: two files are preserve-capable now, and a NOTE that
    # always said profile.yml sent gitignore editors to diff a file that does not exist.
    # T581: each preserved-file NOTE names the remedy for THAT file, and what --force
    # would cost: it replaces every preserved file (profile.yml, policy.yml,
    # providers.toml, .sdlc/.gitignore, .sdlc/.gitattributes) and the edits in them.
    force_costs = ("--force would also replace every other preserved file, and the "
                   "edits and tightened floors in them")
    for op in (o for o in ops if o["status"] == "preserved"):
        base_rel = op["rel"][:-len(".new")]
        print(f"\n  NOTE: your edited {base_rel} was kept; the new version is at "
              f"{op['rel']}. Diff and merge it into yours, or move {op['rel']} over "
              f"{base_rel} to take the installer's version of this file alone - "
              f"{force_costs}.")
    if stale_root := stale_workspace_root_note(root, profile, ops):
        print(f"\n  NOTE: {stale_root}")
    # Batch-2 review F1b: the attributes protect runs committed FROM NOW ON. Runs already
    # committed keep the bytes git stored for them, which on a Windows clone can differ
    # from their pins only in line endings - so say where each such file will be named.
    # Not in a dry run, which writes nothing, and "already has run folders" rather than
    # "committed": the predicate is the tree on disk, not git (review G5).
    if not dry_run and any(o["rel"] == ".sdlc/.gitattributes" and o["status"] == "create"
                           for o in ops):
        runs = root / ".sdlc" / "runs"
        if runs.is_dir() and any(p.is_file() for p in runs.rglob("*")):
            print("\n  NOTE: .sdlc/.gitattributes is new here, and this repository already has "
                  "run folders. Any it committed before this file keep the bytes git stored "
                  "for them; if the merge check then reports a pin that changed only in its "
                  "line endings, it names the remedy for that file.")
    # T382: an installer-side value change is NOT the adopter's edit.
    for op in (o for o in ops if o["status"] == "outdated"):
        base_rel = op["rel"][:-len(".new")]
        print(f"\n  NOTE: {base_rel} was not edited since last install, but the "
              f"installer now computes different values; the new version is at "
              f"{op['rel']}. To accept them, move {op['rel']} over {base_rel} - this "
              f"file alone; {force_costs}.")
    # T382: no recorded digest — cannot tell who changed the file.
    for op in (o for o in ops if o["status"] == "unverified"):
        base_rel = op["rel"][:-len(".new")]
        print(f"\n  NOTE: {base_rel} differs from what the installer would write "
              f"and no recorded digest exists, so it cannot tell whether the "
              f"difference is yours or the installer's. The file was kept; "
              f"the installer's version is at {op['rel']} — compare the two "
              f"with diff. To accept the installer's version of this file alone, "
              f"move {op['rel']} over {base_rel}; {force_costs}.")
    if digest_write_error:
        print(f"\n  NOTE: {digest_write_error}. Future re-runs will not be able "
              f"to tell your edits from installer changes.")
    if extras_skipped:
        print("\n  NOTE: --claude-extras ignored (Claude Code is not in the tool set).")
    if no_commands:
        # Said out loud for the same reason the ledger NOTE below is: this run MEASURED
        # the absence, and an omission nobody is told about reads as a skill that forgot.
        print(f"\n  NOTE: the skill teaches no harness commands - {no_commands}. Work "
              f"the phases by hand, or clone the harness and re-run its sdlc-init.py "
              f"here to get paths that resolve.")
    if ledger_skipped:
        print(f"\n  NOTE: no CI ledger gate - {ledger_skipped}. Approvals are still "
              f"hash-chained and locally verifiable; nothing enforces them at merge.")
    else:
        print(f"\n  NOTE: the ledger gate is installed but not yet REQUIRED - GitHub "
              f"only enforces a check a branch protection rule names. See the header of "
              f"{LEDGER_WORKFLOW_REL}.")

    if dry_run:
        print(f"\n[dry-run] {changed} file(s) would change. Nothing written.")
        if estate and workspace is not None and report is not None:
            print("[dry-run] estate: would verify vendored binaries "
                  "(tools/third_party.py --verify)")
            print(estate_neo4j_row(harness_root(), os.environ))
            for row in estate_attach_rows(report, workspace["root"]):
                print(row)
        # The graph is the largest thing this command does. A dry run that lists four file
        # writes and never mentions it describes a different command than the real one.
        reason = no_chain_reason(root, enabled=graph, workspace=workspace, estate=estate)
        if reason:
            print(f"[dry-run] {NO_GRAPH}{reason}")
        elif estate and workspace is not None:
            print(f"[dry-run] graph: would build the workspace into {root / GRAPH_OUT}")
        else:
            print(f"[dry-run] graph: would build into {root / GRAPH_OUT}")
        if defer_graph and not reason:
            print("[dry-run] graph surfaces: the sdlc-graph skill/rules files and the "
                  "instruction-file graph section would be written after a successful "
                  "build, not before it")
        if not reason:
            print(f"[dry-run] mcp: would register {MCP_SERVER_NAME} in {MCP_CONFIG} "
                  f"once the graph exists")
        diagram_skip = no_pipeline_diagram_reason()
        print(f"[dry-run] pipeline: "
              + (f"no {PIPELINE_DIAGRAM_REL} - {diagram_skip}" if diagram_skip else
                 f"would draw {PIPELINE_DIAGRAM_REL} from the resolved pipeline, "
                 f"last, once the files and the graph above exist"))
        return 0

    print(f"\nDone. {changed} file(s) written"
          + (f"; {unwritten} could not be (named above)." if unwritten else "."))
    if unwritten and not changed and not any(o.get("touched") for o in ops):
        # Delta review R1-1: every write failed before it reached the disk, so nothing
        # was written at all - exit 1's meaning, not 4's "after others were". A write
        # that failed after its open DID reach the disk (R2-1), and is 4's.
        print(f"\n  Nothing was written: each of the {unwritten} file(s) this run had to "
              f"write failed after the check (each is named above), so nothing was "
              f"installed. Re-run once they can be written.")
        return 1
    if unwritten:
        # Batch-6 review B6-1: not a success. This ended at 0 under "Next: commit what
        # was just installed", having drawn the pipeline from a profile that was not
        # there. The scaffold has a hole in it, so nothing is built on it, and the exit
        # code says so: 1 would claim nothing was installed, 0 that all of it was.
        stay = (f" The {changed} written stay, and a re-run reports them unchanged."
                if changed else "")
        print(f"\n  The install is INCOMPLETE: {unwritten} file(s) above could not be "
              f"written, so nothing was built on it - no graph, no pipeline diagram, no "
              f"MCP registration. Re-run once each can be written.{stay}")
        return 4
    if estate and workspace is not None and report is not None:
        # Preflight before the build, so an environment finding is read in the minute
        # the build takes rather than scrolled away by it.
        print("\nestate preflight:")
        for row in estate_verify_rows(harness_root()):
            print(row)
        print(estate_neo4j_row(harness_root(), os.environ))
        for row in estate_attach_rows(report, workspace["root"]):
            print(row)
    # Before the tips, not after: a build can take minutes, and a sign-off line printed
    # above it would read as the end of the command.
    code = chain_graph_build(root, enabled=graph, workspace=workspace, estate=estate,
                             workspace_path=workspace_path, from_snapshot=from_snapshot)
    late_unwritten = 0
    # The deferred graph surfaces, now the build has had its turn. Written only if a
    # graph actually exists: `code == 0` also covers "honestly not built", which
    # teaches nothing, and a failed build must leave no instructions to nowhere.
    if defer_graph:
        if (root / GRAPH_OUT / "graph.jsonl").is_file():
            late = [o for o in surface_ops(root, tools, skill_body, description,
                                           with_graph=True, extras_on=extras_on)
                    if o["status"] not in ("unchanged", "blocked")]
            if late:
                print("\n  graph surfaces (written now the graph exists):")
                for op in late:
                    _write_op(op)
                    print(f"    {_mark(op):<38} {op['rel']}")
                # T517: planned after the check above, so a failure is only met here.
                for op in (o for o in late if o["status"] == "blocked"):
                    late_unwritten += 1
                    print(f"\n  NOTE: {op['rel']} could not be written — {op['reason']}")
        else:
            print("\n  NOTE: no graph was built, so nothing that teaches one was "
                  "written - no sdlc-graph skill/rules files, and no graph section in "
                  "the instruction files. Re-run once the build succeeds.")
    # T450c: the pipeline picture, drawn LAST, from the pipeline this install
    # actually left - the profile on disk and whatever graph the build produced.
    print("\n  pipeline diagram:")
    print(write_pipeline_diagram(root))
    # Registration is gated on the graph the entry would serve actually existing —
    # a server registered over nothing greets every session with a startup refusal.
    # Re-deriving the chain decision is the dry-run's own pattern; `code == 0` alone
    # would also cover "honestly not built", which writes no graph to serve.
    if (code == 0
            and no_chain_reason(root, enabled=graph, workspace=workspace,
                                estate=estate) is None
            and (root / GRAPH_OUT / "graph.jsonl").is_file()):
        print(register_mcp(root, harness_root(),
                           workspace_path=workspace_path if estate else None))
    if late_unwritten and code == 0:
        # B6-1, for the files written after the build: the same incomplete scaffold,
        # met later, and the same answer - no sign-off, and exit 4.
        print(f"\n  The install is INCOMPLETE: {late_unwritten} graph surface file(s) "
              f"above could not be written. Re-run once each can be written.")
        code = 4
    # The same logic in reverse on failure: sign-off tips printed BELOW "build FAILED"
    # would read as the end of the command, and the end of the command would read as
    # success. The failure message already says the scaffold is usable.
    if code == 0:
        if (claude_extras and not extras_skipped
                and any(o["rel"] == CLAUDE_SETTINGS_REL and o["status"] == "blocked"
                        for o in ops)):
            # T513: never claim a merge that did not happen. The file was left as the
            # adopter wrote it, and its NOTE says why.
            print(f"Claude extras: the subagents and hook scripts were installed, but "
                  f"{CLAUDE_SETTINGS_REL} was NOT merged (its NOTE above says why), so "
                  f"neither the permission allowlist nor the hooks are in effect.")
        elif claude_extras and not extras_skipped:
            print("Claude extras: subagents + auto-lint/session hooks + a scoped permission allowlist"
                  " were installed (settings.json merged, not clobbered).")
        elif "claude" in tools:
            print("Tip: add --claude-extras for reviewer subagents, a no-prompt permission allowlist,"
                  " and automation hooks (Claude Code only).")
        if withheld_note:
            # T582: never hand over a command the NOTE above says will refuse.
            print("Next: commit what was just installed:")
            print("        git add -A && git commit -m \"chore: install SDLC harness\"")
            print("      /sdlc runs stay withheld until this directory and the workspace root "
                  "are on one drive or share (the NOTE above says why); the rest of the "
                  "install works now.")
        else:
            # COMMIT FIRST, and said here because the next step refuses without
            # it. P0 requires a clean tree - a baseline measured over uncommitted
            # edits describes a state nobody can reconstruct - and the files that
            # make it dirty are the ones just written above. A first-time adopter
            # who follows the README hits that refusal on step two, which is how
            # this line came to be written.
            print("Next: commit what was just installed - the first run needs a clean tree:")
            print("        git add -A && git commit -m \"chore: install SDLC harness\"")
            print("      then open this repo in an AI coding tool and run  /sdlc <your bug or feature>")
            print("      (or 'follow the sdlc workflow for: <task>' in tools without slash commands).")
    return code


