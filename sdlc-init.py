#: `policy.yml`'s `deny_git`, in git's own words rather than as substrings.
#: The constitution matches these against a normalised command line; the
#: generated permission policy has to be checked against the same list, and this
#: file may not import `tools/` (it is the installer, and runs before there is
#: an environment). `test_red_team` asserts COVERAGE rather than equality: the
#: two are different vocabularies - the constitution matches substrings, this
#: names whole commands - so the check is that every substring `policy.yml`
#: denies appears inside at least one command named here.
DEFAULT_DENY_GIT = ("git push --force", "git push --force-with-lease",
                    "git push -f", "git reset --hard", "git clean -f",
                    "git push -f origin", "git filter-branch",
                    "git filter-repo", "git branch -D",
                    "git update-ref", "git reflog expire", "git gc --prune",
                    "git switch --force", "git checkout --force",
                    "git worktree remove --force")

#: The same idea for `policy.yml: deny_commands`, and a THIRD vocabulary,
#: because Claude Code matches a Bash rule by PREFIX and the constitution
#: matches by tokens. A prefix cannot say "rm with -r anywhere in the line", so
#: the spellings a prefix CAN express are written out: `Bash(rm -r:*)` covers
#: `rm -rf` and `rm -r`, `Bash(rm -f:*)` covers `rm -fr`, and so on. Held to the
#: constitution by a coverage test rather than by memory — every program the
#: constitution denies must appear here — for the reason item 43(f) exists: the
#: harness writing its own permission policy is a security surface, and it has
#: already generated its own bypass once.
#:
#: T366: this vocabulary is weaker than the constitution's, and INFERRED
#: rather than measured through this permission file itself — Claude Code
#: applies it, not this harness. A PREFIX rule is a literal string, so it
#: does not expand a GNU long-option ABBREVIATION (`rm --rec -f x` matches
#: none of `rm -r`, `rm -R`, `rm -f`, `rm --recursive` — only `-f` sitting
#: BEFORE the abbreviation would, by accident, via the unrelated `rm -f`
#: entry) and it cannot catch a flag that moved past where the literal
#: prefix ends (`rm -v --rec x` starts with none of the entries above at
#: all). This list is a best-effort, fast, LOCAL refusal for one runner -
#: `tools/sdlc/policy.py`'s token-matched `deny_commands`, reached through
#: every runner via `guard.check` (`tools/sdlc/guard.py`), is the actual
#: security boundary and is where the abbreviation fix lives.
DEFAULT_DENY_COMMANDS = ("rm -r", "rm -R", "rm -f", "rm --recursive",
                         "rmdir /s", "rmdir -r", "rd /s", "rd -r",
                         "del /s", "erase /s",
                         "Remove-Item -Recurse", "Remove-Item -r",
                         "ri -Recurse", "ri -r",
                         "find . -delete", "dd of=", "mkfs", "shred",
                         "sdelete", "truncate -s", "truncate --size")


def wrapper_permission(command: str) -> str | None:
    """Narrowest `Bash(...)` rule that still lets a repo's own check-in script run.

    Taking the first token is right for `./checkin.sh "{message}"` and catastrophic for
    `powershell -File ./checkin.ps1 "{message}"`: it yields `Bash(powershell:*)`, which
    lets an agent run `powershell -Command "git push"` straight through the deny_raw_git
    wall this function exists to build. So an interpreter is scoped by the whole command
    prefix up to the first placeholder, and a bare interpreter with nothing left to scope
    earns no rule at all — the agent gets a permission prompt, which is the safe direction.
    """
    # Strip the quote that opened the placeholder: `... ./checkin.ps1 "{message}"` leaves a
    # dangling `"` that would become part of the permission rule and match nothing.
    prefix = command.split("{")[0].strip().rstrip("\"'").strip()
    if not prefix:
        return None
    tokens = prefix.split()
    head = tokens[0]
    if Path(head).name.lower().removesuffix(".exe") not in INTERPRETERS:
        return f"Bash({head}:*)"
    return f"Bash({prefix}:*)" if len(tokens) > 1 else None


def policy_selfcheck(settings: dict, deny_git: list[str] | None = None,
                     deny_commands: list[str] | None = None) -> list[str]:
    """Every way the GENERATED policy permits what it denies. Empty is clean.

    Item 43(f) as a function rather than a memory. The harness writes an agent
    permission policy, which makes that policy a security surface of its own -
    and it has already produced its own bypass once: a PowerShell check-in
    wrapper yielded `Bash(powershell:*)` directly beside the `deny_raw_git`
    rules it was meant to reinforce.

    Two questions, both mechanical. Does any `allow` rule name a bare
    interpreter, which grants everything that interpreter can run? And can any
    `allow` prefix be extended into an operation `policy.yml`'s `deny_git`
    calls destructive - `git branch` into `git branch -D`, `git switch` into
    `git switch --force`?
    """
    perms = (settings or {}).get("permissions", {})
    allow = list(perms.get("allow", []))
    denied = list(deny_git if deny_git is not None else DEFAULT_DENY_GIT)
    # Destructive non-git commands are the same question asked about a different
    # list: `Bash(rm:*)` reaches `rm -rf` exactly as `Bash(git branch:*)` reaches
    # `git branch -D`. Leaving them out would have re-opened item 43(f) for
    # everything that is not git.
    denied += list(deny_commands if deny_commands is not None
                   else DEFAULT_DENY_COMMANDS)
    problems = []
    for rule in allow:
        inner = rule[len("Bash("):-len(":*)")] if rule.startswith("Bash(") and \
            rule.endswith(":*)") else ""
        if not inner:
            continue
        head = Path(inner.split()[0]).name.lower().removesuffix(".exe")
        if head in INTERPRETERS and len(inner.split()) == 1:
            problems.append(f"{rule} is a bare interpreter - it grants everything "
                            f"{head} can run, including anything this policy denies")
        for bad in denied:
            # A prefix rule allows any continuation, so `git branch` permits
            # `git branch -D`; the reverse containment is not a problem, because
            # a longer allow prefix cannot be shortened back into the operation.
            if bad.startswith(inner + " ") or bad == inner:
                which = "deny_git" if bad.split()[:1] == ["git"] else "deny_commands"
                problems.append(f"{rule} can be extended into `{bad}`, which "
                                f"policy.yml's {which} calls destructive")
    return problems


#: `policy_selfcheck`'s sentence for a prefix rule that reaches a denied operation.
_EXTENDS = re.compile(r"^(?P<rule>.+?) can be extended into `(?P<op>[^`]+)`, which "
                      r"policy\.yml's (?P<list>\w+) calls destructive$")


def grouped_findings(findings: list[str]) -> list[str]:
    """`policy_selfcheck`'s findings with one line per rule (review B12-8): a rule that
    reaches several denied operations - `Bash(rm:*)` reaches four spellings of a
    recursive delete - names them together instead of once each. Order is kept."""
    ordered: list = []
    reached: dict[tuple[str, str], list[str]] = {}
    for finding in findings:
        if not (match := _EXTENDS.match(finding)):
            ordered.append(finding)
            continue
        key = (match["rule"], match["list"])
        if key not in reached:
            reached[key] = []
            ordered.append(key)
        reached[key].append(match["op"])
    return [item if isinstance(item, str) else
            f"{item[0]} can be extended into "
            f"{', '.join(f'`{op}`' for op in reached[item])}, which policy.yml's "
            f"{item[1]} calls destructive"
            for item in ordered]


def build_settings(profile: dict, existing: dict | None) -> dict:
    """Merge a conservative permission allowlist + harness hooks into settings.json.

    Allows exactly the profile's test/coverage/lint/build binaries and the safe, local git
    the harness needs; denies destructive ops. Never clobbers existing settings keys.
    """
    allow = set()
    keys = ("test_command", "coverage_command", "lint_command", "build_command")
    # A multi-component profile keeps its commands per component and leaves the top
    # level blank, so reading only the top level would produce an allowlist that
    # permits none of the workspace's actual build tools — an install that looks
    # configured and prompts on every command.
    sources = [profile] + list(profile.get("components") or [])
    for source in sources:
        for key in keys:
            rule = wrapper_permission(str(source.get(key, "")).strip())
            if rule:
                allow.add(rule)
    vcs = profile.get("vcs") or {}
    # Narrowed at item 43, which red-teamed what the harness EMITS rather than
    # only what agents do. `Bash(git branch:*)` reaches `git branch -D` and
    # `Bash(git switch:*)` reaches `git switch --force` - both operations this
    # harness's own `policy.yml` lists in `deny_git` as destructive. The
    # generated allowlist was permitting what the constitution denied, which is
    # the same failure the Rev-5 `Bash(powershell:*)` incident was, one layer
    # up: a guardrail that generates its own bypass looks correct in review.
    #
    # A prefix rule cannot say "git branch but not -D", so each is narrowed to
    # the reading form the harness actually needs. `git worktree` is not here at
    # any setting: worktrees are made by `worktree.py`, so an agent never needs
    # the raw verb, and `git worktree remove --force` deletes a tree.
    safe_git = ["git status", "git diff", "git log", "git show", "git rev-parse",
                "git branch --list", "git branch --show-current",
                "git checkout -b", "git switch -c", "git stash list",
                "git stash show"]
    if not vcs.get("deny_raw_git"):
        safe_git += ["git add", "git commit"]
    for g in safe_git:
        allow.add(f"Bash({g}:*)")
    deny = {"Bash(git push --force:*)", "Bash(git push --force-with-lease:*)",
            "Bash(git reset --hard:*)", "Bash(git clean -f:*)",
            # Named explicitly as well as excluded from `allow`. An operation the
            # constitution calls destructive should be refused whatever else a
            # repository's own settings.json already permitted before this ran.
            "Bash(git branch -D:*)", "Bash(git worktree:*)",
            "Bash(git filter-branch:*)", "Bash(git filter-repo:*)",
            "Bash(git update-ref:*)", "Bash(git reflog expire:*)",
            "Bash(git gc --prune:*)"}
    # Was one hand-written `Bash(rm -rf:*)` — which denied exactly that spelling
    # and let `rm -fr`, `rm -Rf` and `rm -r -f` straight through, while every
    # runner that is not Claude Code had no wall at all. Derived now, so the
    # emitted policy and `policy.yml: deny_commands` cannot drift apart.
    deny |= {f"Bash({spelling}:*)" for spelling in DEFAULT_DENY_COMMANDS}
    if vcs.get("deny_raw_git"):
        # Raw git would reach the wrong remote / drop a second git dir - the repo's own
        # script is the only sanctioned path, so allow that binary and wall off the rest.
        deny |= {"Bash(git push:*)", "Bash(git commit:*)", "Bash(git worktree:*)"}
        for wrapper in (vcs.get("commit_command"), vcs.get("push_command")):
            rule = wrapper_permission((wrapper or "").strip())
            if rule:
                allow.add(rule)

    settings = dict(existing or {})
    perms = dict(settings.get("permissions", {}))
    perms["allow"] = sorted(set(perms.get("allow", [])) | allow)
    perms["deny"] = sorted(set(perms.get("deny", [])) | deny)
    settings["permissions"] = perms

    hooks = dict(settings.get("hooks", {}))
    autolint = {"matcher": "Edit|Write", "hooks": [{"type": "command",
                "command": 'python "$CLAUDE_PROJECT_DIR/.claude/hooks/sdlc-autolint.py"'}]}
    session = {"hooks": [{"type": "command",
               "command": 'python "$CLAUDE_PROJECT_DIR/.claude/hooks/sdlc-session-start.py"'}]}
    post = list(hooks.get("PostToolUse", []))
    if not any("sdlc-autolint" in json.dumps(h) for h in post):
        post.append(autolint)
    hooks["PostToolUse"] = post
    start = list(hooks.get("SessionStart", []))
    if not any("sdlc-session-start" in json.dumps(h) for h in start):
        start.append(session)
    hooks["SessionStart"] = start
    settings["hooks"] = hooks
    return settings


