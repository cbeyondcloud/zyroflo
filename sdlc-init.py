def find_uv() -> str | None:
    """Absolute path to the uv executable, resolved from PATH alone - never from the
    current directory.

    Windows resolves a bare program name against the process's CURRENT DIRECTORY before
    PATH - and this command's current directory is the target repository, the one
    directory whose contents must stay data and never become code. A committed `uv.exe`
    at an untrusted repo's root would beat the installed one. `shutil.which` inherits the
    same rule, so the search is spelled out here: each PATH entry in order, PATHEXT
    applied, empty and `.` entries (which mean the current directory) refused. The result
    is absolute, so the spawn in `run_builder` has no search left for the OS to take.
    """
    if os.name == "nt":
        pathext = [e for e in os.environ.get("PATHEXT", ".EXE").split(os.pathsep) if e]
        # uv ships as uv.exe; try that first so a stray uv.cmd shim never shadows it.
        exts = [".exe"] + [e.lower() for e in pathext if e.lower() != ".exe"]
    else:
        exts = [""]
    for entry in os.environ.get("PATH", "").split(os.pathsep):
        entry = entry.strip('"')
        if not entry or entry == os.curdir:
            continue
        for ext in exts:
            cand = Path(entry) / f"uv{ext}"
            if cand.is_file() and os.access(cand, os.X_OK):
                return str(cand)
    return None


def builder_hint(harness: Path) -> str:
    """The paste-ready prefix of a manual build command, for every printed hint.

    Three decisions, all load-bearing. `--project` pins uv to the harness clone's locked
    environment: pasted from any other directory, a bare `uv run` resolves the PASTER's
    project instead - a degraded build at exit 0 on the global interpreter, or a
    stranger's repository quietly gaining a `.venv`. The quotes survive paths with spaces,
    which this machine's own paths have. And it is derived from `GRAPH_BUILDER`, so the
    hint cannot rot apart from the command the chain actually runs.
    """
    return f'uv run --project "{harness}" python "{harness / GRAPH_BUILDER}"'


def graph_capability(harness: Path | None = None) -> str | None:
    """Why the graph cannot be built from here, or None if it can.

    **Detected, never assumed.** The build needs the harness clone's locked environment —
    tree-sitter grammars, the vendored binaries — and a developer who copied one file has
    none of it. Assuming otherwise would turn Tier 0's zero-dependency promise into a
    crash, and guessing the other way would silently drop the graph on machines that could
    have built one.

    Each reason names the missing thing and what to do about it, because "no graph was
    built" without a cause is indistinguishable from the tool having decided not to.
    """
    harness = Path(harness) if harness is not None else harness_root()
    builder = harness / GRAPH_BUILDER
    if not builder.is_file():
        return (f"there is no graph engine beside this script ({GRAPH_BUILDER.as_posix()} "
                f"is not in {harness}), so this is the standalone installer. The scaffold "
                f"above is complete and needs nothing else. For a graph, clone the harness "
                f"repo and run ITS sdlc-init.py from here.")
    if find_uv() is None:
        return (f"uv is not on PATH, and the build runs from the harness clone's locked "
                f"environment rather than from this repository. Install uv "
                f"(https://docs.astral.sh/uv/) and re-run, or build later with:\n"
                f"       {builder_hint(harness)} --target <repo>")
    return None


def no_chain_reason(root: Path, *, enabled: bool, workspace: dict | None,
                    harness: Path | None = None, estate: bool = False) -> str | None:
    """Why this run will not build a graph, or None if it will.

    Separate from the running of it so `--dry-run` can report the same decision without
    performing it — a dry run that omits the largest thing the command does is under-
    reporting, and this file's whole subject is output that reads like success.
    """
    harness = Path(harness) if harness is not None else harness_root()
    if not enabled:
        return "--no-graph was given."
    if workspace is not None:
        if estate:
            # Item 15 opens the seam item 80 closed: the workspace graph now has a home
            # — the TARGET's own .sdlc/graph — so with --estate the chain runs. The
            # capability checks still apply; the single-repo shape checks do not (the
            # target is the workspace-config repo, not a component).
            return graph_capability(harness)
        return ("a multi-repo workspace graph is about no single repository, so there is no "
                "repository to commit it into and it is not chained here. Build it with:\n"
                f"       {builder_hint(harness)} --workspace <your file>\n"
                f"       or re-run with --estate to chain it here, into "
                f"{(root / GRAPH_OUT)}.")
    if _git_dir(root) is None:
        return (f"{root} is not a repository root. The scaffold above is complete; a graph "
                f"needs a repository, so run this from one.")
    if reason := graph_capability(harness):
        return reason
    # Mirrors the builder's own refusal (`workspace_for_repo` raises on nested clones) so
    # the chain never launches a build whose first act is to refuse - which would land a
    # supported repository shape in the "attempted and broke" exit, with a re-run hint
    # that fails the same way forever. Checked after capability: for a standalone
    # installer the honest reason is the missing engine, not the shape of the repo.
    if nested := nested_clones(root):
        shown = ", ".join(nested[:5]) + (f" (+{len(nested) - 5} more)" if len(nested) > 5 else "")
        return (f"{root} contains repositories of its own ({shown}), which makes it a "
                f"multi-repo workspace - built as ONE component, every coupling between "
                f"them would silently collapse into a single node. Copy "
                f"sdlc_templates/workspace.example.toml, set `root`, and run:\n"
                f"       {builder_hint(harness)} --workspace <your file>")
    return None


def build_status(out: Path) -> str:
    """The `status` the report at `out` carries, or `""` if it cannot be read as one.

    A file rather than an import: `tools/` may depend on this stdlib-only installer, never
    the reverse. Read for MESSAGE WORDING only — the verdict is the builder's exit code,
    because `--empty-ok` moved the empty-graph judgement into the builder, which decides
    from the report in memory. A file read back after the fact can be stale (a build that
    dies before writing leaves the previous run's report sitting there); an exit code
    cannot. Anything unreadable — including a report that parses to something other than
    an object, or a status that is not a string — answers `""`, and the caller words its
    message without it.

    `out` is where the builder writes only because the caller has already established that
    `root` is a repository root: the builder's default for an inferred repository is that
    repository's own `.sdlc/graph`. Chained from a subdirectory the two would diverge, and
    this would read a file the build never touched.
    """
    try:
        report = json.loads((out / "build_report.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return ""
    if not isinstance(report, dict):
        return ""
    status = report.get("status")
    return status if isinstance(status, str) else ""


#: The build outcome that means "ran clean, nothing matched". The chained call passes
#: `--empty-ok`, so the BUILDER already exited 0 for it — most stacks have no extractor
#: yet (item 9 is pending), and failing the one-command install over coverage would fail
#: it on the majority of repositories it exists to serve. This constant only picks the
#: EMPTY wording for a build the builder itself has already called clean.
BENIGN_BUILD_STATUS = "no-activation"


def builder_command(root: Path, harness: Path) -> list[str]:
    """The exact chained invocation.

    **The program is an absolute path** (see `find_uv`): a bare name would leave the OS a
    search to perform, and on Windows that search visits the current directory — the
    target repository — before PATH. **`--empty-ok`** hands the builder the one bit of
    caller intent this command has: an unclaimed stack is coverage rather than a broken
    install, and the builder is the only party that can rule so unfoolably, because its
    verdict is an exit code and an exit code cannot be stale. **No `--out`.** Building a
    repository it inferred, the builder already defaults to that repository's own
    `.sdlc/graph`; passing it again would be a second place to change the same decision,
    and the two would drift in the direction nobody tests.
    """
    # Capability checking already found uv; if it vanished in between, the bare-name
    # fallback is refused by run_builder's guard and reported as a message.
    return [find_uv() or "uv", "run", "python", str(harness / GRAPH_BUILDER),
            "--target", str(root), "--empty-ok"]


def run_builder(cmd: list[str], cwd: Path) -> int:
    """Run the builder and return its exit code. The one seam the tests replace.

    Flushed first, because the child inherits the raw stream: with stdout block-buffered
    (any piped or redirected run) the parent's narration would otherwise land AFTER the
    child's entire report — a log that opens with thirty lines of extractor output
    introduced by nothing.

    A relative program name is refused rather than spawned: the OS would search for it,
    and on Windows that search starts in the current directory. `builder_command` always
    passes an absolute path; this guard makes that a guarantee rather than a habit.

    Output is deliberately NOT captured: the build prints a full per-extractor report, and
    a developer watching it needs to see that arrive rather than a silent wait ending in a
    summary. There is no timeout for the same reason — one that fires mid-build would
    destroy a correct run to protect against a hypothetical hang.
    """
    sys.stdout.flush()
    if not Path(cmd[0]).is_absolute():
        raise FileNotFoundError(f"refusing to spawn a bare program name: {cmd[0]!r}")
    return subprocess.run(cmd, cwd=str(cwd)).returncode


def run_capture(cmd: list[str], cwd: Path) -> tuple[int, str]:
    """`run_builder`'s captured sibling, for preflight steps whose output is reprinted
    indented rather than streamed. Same absolute-path guard, same test seam role."""
    if not Path(cmd[0]).is_absolute():
        raise FileNotFoundError(f"refusing to spawn a bare program name: {cmd[0]!r}")
    proc = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=300)
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


# ── estate mode (item 15) ─────────────────────────────────────────────────────
# The plan's original sketch named six steps; measurement shrank two of them and the
# docstrings say why. Clone-when-missing has no data source (the workspace schema
# carries no remote field — it arrives with its consumer); MCP registration waited
# for item 23 and now runs after the chained build (`register_mcp`), for estate and
# single-repo installs alike. Nothing here writes into any component, and nothing
# here starts a service.


def estate_verify_rows(harness: Path) -> list[str]:
    """The vendored-binary verification, reprinted. `third_party.py --verify` already
    prints the right rows (ok / unpinned / MISSING / mismatch); this spawns it through
    the same absolute-uv discipline as the chained build and indents its report."""
    uv = find_uv()
    if uv is None:
        return ["  binaries: SKIPPED - uv is not on PATH, so the verifier cannot run. "
                "The build degrades to Python fallbacks either way."]
    try:
        code, text = run_capture([uv, "run", "python",
                                  str(harness / "tools" / "third_party.py"),
                                  "--verify"], harness)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return [f"  binaries: verification could not run ({exc})."]
    rows = [f"  {line}" for line in text.splitlines() if line.strip()]
    if not rows:
        # CLAUDE.md's headline rule, at the supply-chain preflight: an external binary
        # returning nothing at exit 0 is not evidence of absence. An absent binary and a
        # mismatched digest both reported correctly here, at non-zero; it was SILENCE
        # that printed no row at all, so the preflight said nothing whatever about the
        # vendored tools and read as an all-clear. `could not look` is the word this
        # repository already uses for this state, and it is never folded into either side.
        return [f"  binaries: the verifier exited {code} and printed nothing, so this "
                "preflight could not look at the vendored tools. An empty answer is "
                "not evidence they are present and pinned - run `uv run python "
                "tools/third_party.py --verify` by hand before trusting them."]
    if code != 0:
        rows.append("  binaries: verification reported issues above - vendored tools "
                    "fall back to Python paths, slower but correct.")
    return rows


def estate_neo4j_row(harness: Path, environ) -> str:
    """Neo4j is OPTIONAL serving (the parity doctrine, item 62): this row reports
    readiness and never starts anything - a container nobody asked for is a state
    change, not a convenience. Key NAMES are reported, never values."""
    compose = harness / "docker-compose.neo4j.yml"
    keys = sorted(k for k in environ if k.startswith("NEO4J_"))
    if keys:
        return (f"  neo4j: configured via {', '.join(keys)} (values not shown); "
                f"the store connects lazily on first use.")
    if compose.exists():
        return (f"  neo4j: optional and not configured. To serve the graph from Neo4j: "
                f"docker compose -f {compose} up -d, then set NEO4J_URI/NEO4J_PASSWORD "
                f"in .env. The file-backed store works without it.")
    return "  neo4j: optional and not present here; the file-backed store is the default."


def estate_attach_rows(report: dict, ws_root: Path) -> list[str]:
    """The attach census: how each component is attached, and the one thing attach does
    NOT do, stated. A shallow clone is readable but un-diffable - a finding, not noise."""
    rows = []
    for c in report["components"]:
        kind = "git" if _git_dir(Path(ws_root) / c["path"]) else "declared (no .git)"
        shallow = ", SHALLOW - readable but un-diffable" if c.get("shallow") else ""
        rows.append(f"  {c['name']:<28} {kind}{shallow}")
    for rel in report.get("skipped", []):
        rows.append(f"  {rel:<28} skipped - no .git and not declared")
    rows.append("  attach reports and never clones: the workspace schema carries no "
                "remote to clone FROM (the field arrives with its consumer, recorded "
                "in the plan).")
    return rows


def builder_command_estate(workspace_path: Path, root: Path, harness: Path,
                           *, from_snapshot: bool) -> list[str]:
    """The chained estate invocation. Same discipline as `builder_command`: absolute
    program, `--empty-ok` (an estate nothing claims is coverage, not breakage). Unlike
    the single-repo chain it DOES pass `--out`: the builder's workspace default is no
    single repository's `.sdlc`, and the target is exactly the home this mode adds."""
    cmd = [find_uv() or "uv", "run", "python", str(harness / GRAPH_BUILDER),
           "--workspace", str(workspace_path), "--out", str(root / GRAPH_OUT),
           "--empty-ok"]
    if from_snapshot:
        cmd.append("--from-snapshot")
    return cmd


def chain_graph_build(root: Path, *, enabled: bool, workspace: dict | None,
                      harness: Path | None = None, estate: bool = False,
                      workspace_path: Path | None = None,
                      from_snapshot: bool = False) -> int:
    """Build this repository's graph, or say plainly that it was not built. Returns an
    exit code for the whole install.

    **Three outcomes, and the differences between them are the item.** An absent
    environment is a SUPPORTED configuration — Tier 0 is meant to run there — so it prints
    its reason and exits 0. An empty graph is a fact about extractor coverage rather than
    about this install, so it too exits 0, loudly. A build that was attempted and broke is
    neither: the command promised an artifact, something failed, and exiting 0 would say
    every artifact was created. This project has hit "a wrong answer at exit 0" in five
    separate modules; the command that produces every artifact is not the place for a sixth.

    **A broken build exits 3, not 1.** Every fatal-input path already exits 1 meaning
    "nothing was installed"; this outcome is its opposite — every scaffold file was
    written and only the graph is missing — and a caller that cannot tell the two apart
    from the code alone would have to parse stdout to decide whether to wipe and retry.
    """
    harness = Path(harness) if harness is not None else harness_root()
    print()
    if reason := no_chain_reason(root, enabled=enabled, workspace=workspace,
                                 harness=harness, estate=estate):
        print(f"{NO_GRAPH}{reason}")
        return 0

    out = root / GRAPH_OUT
    if estate and workspace_path is not None:
        verb = "loading the workspace's snapshot shards" if from_snapshot else \
               "building the workspace's estate graph"
        print(f"graph: {verb} into {out}")
        cmd = builder_command_estate(workspace_path, root, harness,
                                     from_snapshot=from_snapshot)
    else:
        print(f"graph: building this repository into {out}")
        cmd = builder_command(root, harness)
    print("       (first run in a fresh clone syncs the environment, which takes a minute)")
    try:
        code = run_builder(cmd, harness)
    except OSError as exc:
        # Capability said uv exists; the spawn disagreed (removed since, an unlaunchable
        # shim, permissions). A message, never a traceback — nothing else in this file is
        # allowed to die raw, and the spawn boundary is not an exception.
        print(f"\n{NO_GRAPH}uv could not be launched ({exc}). The scaffold is complete "
              f"and usable without a graph; check the uv install and re-run, or pass "
              f"--no-graph.")
        return 3
    if code == 0:
        if build_status(out) == BENIGN_BUILD_STATUS:
            print(f"\ngraph: built into {out}, and EMPTY - no extractor matched a single "
                  f"file here, so there is nothing to graph yet.")
            print("       That is coverage, not a failure: the build itself ran fine, and "
                  "extractors arrive per stack. The list it searched is above.")
        else:
            print(f"\ngraph: built -> {out}")
        return 0
    # No claim about what was or was not written: the report on disk may be stale (a
    # crash before writing leaves the previous run's), so the only honest summary is the
    # exit code and a pointer at the builder's own account, printed directly above.
    print(f"\ngraph: build FAILED - exited {code}; its own output is above and says how "
          f"far it got. The scaffold is complete and usable without a graph. Re-run just "
          f"the build with:")
    if estate and workspace_path is not None:
        print(f'       {builder_hint(harness)} --workspace "{workspace_path}" '
              f'--out "{root / GRAPH_OUT}"')
    else:
        print(f'       {builder_hint(harness)} --target "{root}"')
    return 3


# ── MCP registration (item 23) ────────────────────────────────────────────────
#: The server key this installer owns inside .mcp.json. Everything else in that
#: file is the developer's and is preserved byte-for-byte in content and order.
MCP_SERVER_NAME = "sdlc-graph"
MCP_CONFIG = ".mcp.json"


def mcp_server_entry(uv: str, root: Path, harness: Path,
                     workspace_path: Path | None = None) -> dict:
    """The `.mcp.json` entry for the graph server.

    The same three spawn decisions as `builder_command`, because the spawner here is
    the developer's AI tool with its working directory AT THE TARGET REPO — exactly
    the directory a bare program name would search first on Windows. So: `uv` is the
    absolute path resolved from PATH alone (the CALLER resolves it — a bare name
    written here would be a planted-binary hole with no spawn guard left to catch
    it); `--project` pins the harness clone's locked environment from any cwd; the
    server script is an absolute path into that clone. `--extra serve` self-heals
    the optional fastmcp layer on first launch. `--workspace`/`--target` is the
    freshness context: estate installs point at the workspace config (resolved —
    the spawner's cwd is not this process's), single repos at themselves.
    """
    args = ["run", "--project", str(harness), "--extra", "serve", "python",
            str(harness / GRAPH_SERVER), "--graph-dir", str(root / GRAPH_OUT)]
    if workspace_path is not None:
        args += ["--workspace", str(workspace_path.resolve())]
    else:
        args += ["--target", str(root)]
    return {"command": uv, "args": args}


def register_mcp(root: Path, harness: Path,
                 workspace_path: Path | None = None) -> str:
    """Merge the graph server into `<root>/.mcp.json`; return the one report line.

    Owns ONLY the `MCP_SERVER_NAME` key. A developer's other servers, their top-level
    keys and their ordering all survive, which is why this merges JSON rather than
    using the whole-file plan_op machinery — a `.new` beside a config the AI tool
    already read helps nobody. A file that cannot be parsed as an MCP config is left
    untouched and named: overwriting it would trade their configuration for ours.
    Never raises; registration is a convenience on top of a completed install.
    """
    uv = find_uv()
    if uv is None:
        # The build that gated this call found uv; if it vanished in between, a
        # bare "uv" must never be written — the AI tool would spawn it with its
        # cwd at the target repo, and Windows searches there before PATH.
        return ("mcp: NOT registered - uv left PATH since the build ran, and the "
                "entry must carry an absolute path. Re-run once uv is back.")
    path = root / MCP_CONFIG
    entry = mcp_server_entry(uv, root, harness, workspace_path)
    data: dict = {}
    if path.exists():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return (f"mcp: NOT registered - {MCP_CONFIG} exists but is not valid "
                    f"JSON. Fix or remove it and re-run.")
        if not isinstance(data, dict) or not isinstance(
                data.get("mcpServers", {}), dict):
            return (f"mcp: NOT registered - {MCP_CONFIG} is not shaped like an MCP "
                    f"config (an object whose 'mcpServers' is an object). Fix or "
                    f"remove it and re-run.")
    servers = data.setdefault("mcpServers", {})
    if servers.get(MCP_SERVER_NAME) == entry:
        return f"mcp: {MCP_SERVER_NAME} already registered in {MCP_CONFIG} (unchanged)."
    verb = "updated" if MCP_SERVER_NAME in servers else "registered"
    servers[MCP_SERVER_NAME] = entry
    try:
        write_lf(path, json.dumps(data, indent=2) + "\n")
    except OSError as exc:
        return f"mcp: NOT registered - {MCP_CONFIG} could not be written ({exc})."
    return (f"mcp: {verb} {MCP_SERVER_NAME} -> {MCP_CONFIG} (8 graph tools over "
            f"{GRAPH_OUT}; AI tools that read {MCP_CONFIG} pick it up on restart).")


# ── main install ──────────────────────────────────────────────────────────────
def workspace_profile(components: list[dict]) -> dict:
    """Top-level profile values for a multi-component install.

    The commands are deliberately BLANK. Every component carries its own, and a single
    top-level `test_command` for a workspace that has no single build is a claim the
    harness cannot honour — it would run one component's suite and report it as the
    workspace's.

    `deny_raw_git` is the union, not the intersection: if any component forbids raw git,
    the fallback forbids it too. Under-restricting is the direction that lets an agent
    push through a wall some component put up on purpose.
    """
    stacks = {c.get("stack", "unknown") for c in components}
    denied = sorted(c["name"] for c in components if (c.get("vcs") or {}).get("deny_raw_git"))
    return {
        "stack": stacks.pop() if len(stacks) == 1 else "mixed",
        "test_command": "", "coverage_command": "", "lint_command": "",
        "build_command": "", "deploy_command": "",
        "coverage_threshold": 90,
        "vcs": {
            "commit_command": "", "push_command": "", "deny_raw_git": bool(denied),
            "notes": ("raw git is denied by default because " + ", ".join(denied) +
                      " forbid it; per-component vcs blocks carry the specifics")
                     if denied else "",
        },
        "components": components,
    }


def _report_workspace(ws: dict, report: dict) -> list[str]:
    """Print what discovery found; return the findings to print with the other notes.

    Every note here is something the developer cannot see from the config file alone
    and would otherwise meet much later, as behaviour.
    """
    components = report["components"]
    print(f"  workspace      : {ws['root']}")
    print(f"  components     : {len(components)} "
          f"({'estate' if len(components) > 1 else 'repo'} scope, "
          f"gate_profile {'team' if len(components) > 1 else 'solo'})")
    for c in components:
        role = "" if c["role"] == DEFAULT_ROLE else f"  [{c['role']}]"
        print(f"    - {c['name']:<24} {c['stack']:<14} {c['path']}{role}")

    notes: list[str] = []
    if report["skipped"]:
        notes.append(
            f"{len(report['skipped'])} director"
            f"{'y' if len(report['skipped']) == 1 else 'ies'} under the workspace root had "
            f"no .git and are not components: {', '.join(report['skipped'][:8])}"
            f"{' ...' if len(report['skipped']) > 8 else ''}")
    shallow = [c["name"] for c in components if c["shallow"]]
    if shallow:
        # Reported, never filtered: a shallow clone is readable but un-diffable, so half
        # the harness works on it. That is a finding, not a reason to hide it.
        notes.append(
            f"shallow clone(s): {', '.join(shallow)}. Readable but un-diffable, so impact "
            f"and changed-file coverage over their history will be wrong. Run "
            f"`git fetch --unshallow` in each before relying on those.")
    if not ws["name"]:
        notes.append(
            "`name` is blank in your workspace file, so the leak guard has no workspace "
            "term to protect. Set it, then run `python tools/tests/ban.py "
            "--from-workspace <file>` to seed the ban list.")
    return notes


def install(root: Path, tools: list[str], force: bool, dry_run: bool,
            claude_extras: bool = False, workspace: dict | None = None,
            graph: bool = True, estate: bool = False,
            workspace_path: Path | None = None, from_snapshot: bool = False,
            single_component: bool = False, corpus_replay: bool = False,
            snapshot_cadence: bool = False) -> int:
    skill_meta, skill_body = parse_frontmatter(load_template("SKILL.md"))
    # The phase SOPs live in the harness and are POINTED at, never copied — the
    # same rule the graph skill and the workflows follow, so there is one copy
    # of each procedure to keep current. A moved clone means re-running INIT.
    try:
        skill_body, no_commands = render_skill_body(skill_body)
    except ValueError as exc:
        # `load_template` PREFERS the editable sibling file, so the template the
        # resolver reads is one a harness clone's owner can edit -- and a broken region
        # then reached them as a TRACEBACK, which is item 117's class and the one thing
        # this run exists to refuse. Refused in the same voice, and BEFORE anything is
        # written, as the surviving-placeholder check below.
        print(f"!! refusing: SKILL.md has a broken <!--harness-only--> region - {exc}. "
              f"Nothing was written. Fix the markers in the template beside "
              f"{Path(__file__).name}.")
        return 1
    if "@@HARNESS@@" in skill_body:
        # Refused BEFORE anything is written. A surviving placeholder means the
        # template grew a harness path the renderer does not know about, and shipping
        # it either leaks this machine's layout or leaves `@@HARNESS@@` literal in an
        # adopter's skill -- both of which a test pins, in THIS tree, where the damage
        # is not.
        print(f"!! refusing: SKILL.md still carries @@HARNESS@@ after rendering, so "
              f"this install would teach a path it cannot fill. Add the new pointer "
              f"to render_skill_body in {Path(__file__).name}.")
        return 1
    description = skill_meta.get("description", "Run the full SDLC for a bug fix or feature.")
    report: dict | None = None
    if workspace is None:
        units = build_units(root)
        if units["multi"] and not single_component:
            # Refused BEFORE anything is written: exit 1 means nothing was
            # installed, and a half-install whose model is wrong is worse than
            # no install, because the model cannot be changed once a run has
            # pinned artifacts that name it.
            listed = ", ".join(units["dirs"][:_UNIT_SAMPLE_CAP])
            more = ("" if len(units["dirs"]) <= _UNIT_SAMPLE_CAP
                    else f", and {len(units['dirs']) - _UNIT_SAMPLE_CAP} more")
            print(
                f"!! refusing: {root.name} has no {units['stack']} manifest at its "
                f"root and {units['count']} below it, in {listed}{more}.\n"
                f"   Installed as a single repository it becomes ONE component "
                f"rooted at '.', which is a claim nobody made. Measured cost of "
                f"getting this wrong: P2 scoping maps the whole tree as one node "
                f"and P5's supply-chain gate inherits every dependency in the "
                f"repository - and NEITHER can be changed once a run has started, "
                f"because the gates pin artifacts that name the model.\n"
                f"   Either declare the components:\n"
                f"     python sdlc-init.py --target {root} --workspace <file>\n"
                f"   or say this repository really is one, and have it recorded:\n"
                f"     python sdlc-init.py --target {root} --single-component")
            return 1
        profile = detect_stack(root)
        if units["multi"]:
            prior = (profile.get("stack_note") or "").rstrip()
            # `. ` between two sentences, and not a second full stop when the
            # first already ends in one. The field run's own profile ran them
            # together into one unreadable line.
            profile["stack_note"] = (prior + ("" if prior.endswith(".") else ".")
                                     + " " if prior else "") + (
                f"{units['count']} {units['stack']} build units were found below "
                f"the root and this repository was installed as ONE component "
                f"anyway (--single-component). P2 scoping and P5's supply-chain "
                f"gate are therefore repository-wide, not change-shaped; declare "
                f"components and re-install to narrow them.")
        profile["vcs"] = detect_vcs(root)
    else:
        # `--workspace` supplies the CONTENT (which components exist); `--target` still
        # supplies the LOCATION. The harness points AT the workspace through this config
        # and keeps zero footprint inside the components themselves.
        report = discover_components(workspace)
        profile = workspace_profile(report["components"])

    ops: list[dict] = []
    # Shared harness data (.sdlc/)
    ops.append(plan_op(root, ".sdlc/profile.yml", render_profile(profile, tools),
                       preserve=not force))
    # The guardrail constitution (item 35). `preserve`, like profile.yml: a
    # developer who TIGHTENED a floor has stated something about their repository,
    # and a re-run that silently loosened it back would be the exact failure the
    # tighten-only rule exists to prevent.
    ops.append(plan_op(root, ".sdlc/policy.yml", load_template("policy.yml"),
                       preserve=not force))
    ops.append(plan_op(root, ".sdlc/review-rubric.md", load_template("review-rubric.md")))
    ops.append(plan_op(root, ".sdlc/plan-template.md", load_template("plan-template.md")))
    ops.append(plan_op(root, ".sdlc/plans/.gitkeep", ""))
    # `preserve`, like profile.yml and unlike the other generated files: a developer who
    # added a rule here has stated something about their repository, and clobbering it
    # would be silent — they would find out when something they excluded got committed.
    ops.append(plan_op(root, ".sdlc/.gitignore", sdlc_gitignore(workspace is not None),
                       preserve=not force))
    # The CI ledger gate (item 44): the check and the workflow that runs it are ONE
    # decision, because either alone is a lie - a check nothing runs, or a required job
    # whose script is absent.
    ledger_skipped = no_ledger_gate_reason(root)
    if not ledger_skipped:
        ops.extend(ledger_gate_ops(root))
    # The nightly corpus replay (item 101), and ONLY when asked. A scheduled job
    # on a repository with no corpus goes red every night, and a recurring red is
    # how a real check gets switched off.
    if corpus_replay:
        ops.extend(replay_job_ops(root, workspace_path))
    # The weekly snapshot (item 58), and ONLY when asked - same reason.
    if snapshot_cadence:
        ops.extend(snapshot_job_ops(root, workspace_path))
    # Per-tool entry points. The graph tier ships only when THIS run will build a
    # graph — the chain's own decision (no_chain_reason is already the dry-run's
    # and the chain's single authority), because provider files teaching a graph
    # the install will not build are instructions to nowhere.
    # The graph tier ships when the target HAS a graph or is getting one now.
    # Keying it to this run alone stripped the tier out of a re-run with
    # --no-graph while the graph itself, its MCP registration and the per-file
    # skills all stayed — three surfaces disagreeing about one repository.
    will_build = no_chain_reason(root, enabled=graph, workspace=workspace,
                                 estate=estate) is None
    graph_present = (root / GRAPH_OUT / "graph.jsonl").is_file()
    graph_on = will_build or graph_present
    # A graph that only ARRIVES during this run cannot be taught before it exists:
    # a build that fails would leave AGENTS.md and the skill files citing a graph
    # that is not there, with nothing to say so. Those surfaces wait for the build.
    defer_graph = graph_on and not graph_present
    extras_on = claude_extras and "claude" in tools
    # A dry run plans them anyway and says when they land: it describes the whole
    # command, and hiding the graph surfaces would describe a smaller one.
    ops.extend(surface_ops(root, tools, skill_body, description,
                           with_graph=graph_on and (dry_run or not defer_graph),
                           extras_on=extras_on))
    # Optional Claude Code power layer
    extras_skipped = claude_extras and "claude" not in tools
    if extras_on:
        ops.extend(claude_extras_ops(root, profile))

    # Report + execute
    print(f"SDLC harness -> {root}")
    ws_notes: list[str] = []
    if report is not None:
        ws_notes = _report_workspace(workspace, report)
    else:
        print(f"  stack detected : {profile['stack']}")
        print(f"  test command   : {profile['test_command'] or '(none - edit .sdlc/profile.yml)'}")
    print(f"  tools          : {', '.join(tools)}")
    _vcs = profile["vcs"]
    print(f"  vcs            : {_vcs['commit_command'] or 'git (default)'}"
          f"{'  [raw git DENIED]' if _vcs['deny_raw_git'] else ''}")
    print(f"  claude extras  : {'on' if (claude_extras and not extras_skipped) else 'off'}")
    print("  files:")
    changed = 0
    for op in ops:
        if op["status"] == "blocked":
            # `op["cause"]`, never a default: a blocked op that forgot its cause is a bug
            # in the producer, and borrowing the neighbouring cause is exactly how two
            # files that did not exist came to be reported as having damaged markers.
            mark = f"x BLOCKED ({op['cause']})"
        else:
            mark = {"create": "+ create", "update": "~ update",
                    "unchanged": "= unchanged",
                    "preserved": "! preserved (edited -> wrote .new)"}[op["status"]]
        print(f"    {mark:<38} {op['rel']}")
        if op["status"] not in ("unchanged", "blocked"):
            changed += 1
            if not dry_run:
                write_lf(op["path"], op["content"])

    for op in (o for o in ops if o["status"] == "blocked"):
        # "left untouched" is true of a file that EXISTS. Three of the absent/damaged
        # causes are files this install never wrote, and telling an adopter their absent
        # workflow was left untouched sends them looking for it. The could-not-look cause
        # is a file that EXISTS (the read got past the existence check and failed on the
        # bytes), so its verb is FIXED rather than re-derived from Path.exists(), which
        # swallows an OSError into *was not written* - the on-disk file it describes.
        if op["cause"] == BLOCKED_UNREADABLE:
            verb = "could not be read"
        else:
            verb = "was left untouched" if op["path"].exists() else "was not written"
        print(f"\n  NOTE: {op['rel']} {verb} — {op['reason']}")

    for note in ws_notes:
        print(f"\n  NOTE: {note}")

    if profile["stack"] == "unknown":
        print("\n  NOTE: stack not recognised - .sdlc/profile.yml has blank commands; fill them in before running /sdlc.")
    if profile["vcs"]["deny_raw_git"] and not profile["vcs"]["commit_command"]:
        print("\n  NOTE: raw git is unsafe here (" + profile["vcs"]["notes"].split(" - ")[0] +
              ") but no check-in script was found. Set vcs.commit_command in .sdlc/profile.yml"
              " before running /sdlc, or the harness will stop and ask.")
    # Named per file, not hardcoded: two files are preserve-capable now, and a NOTE that
    # always said profile.yml sent gitignore editors to diff a file that does not exist.
    for op in (o for o in ops if o["status"] == "preserved"):
        print(f"\n  NOTE: your edited {op['rel'][:-len('.new')]} was kept; the new version "
              f"is at {op['rel']} (diff & merge, or re-run with --force).")
    if extras_skipped:
        print("\n  NOTE: --claude-extras ignored (Claude Code is not in the tool set).")
    if no_commands:
        # Said out loud for the same reason the ledger NOTE below is: this run MEASURED
        # the absence, and an omission nobody is told about reads as a skill that forgot.
        print(f"\n  NOTE: the skill teaches no harness commands - {no_commands}. Work "
              f"the phases by hand, or clone the harness and re-run its sdlc-init.py "
              f"here to get paths that resolve.")
    if ledger_skipped:
        print(f"\n  NOTE: no CI ledger gate - {ledger_skipped}. Approvals are still "
              f"hash-chained and locally verifiable; nothing enforces them at merge.")
    else:
        print(f"\n  NOTE: the ledger gate is installed but not yet REQUIRED - GitHub "
              f"only enforces a check a branch protection rule names. See the header of "
              f"{LEDGER_WORKFLOW_REL}.")

    if dry_run:
        print(f"\n[dry-run] {changed} file(s) would change. Nothing written.")
        if estate and workspace is not None and report is not None:
            print("[dry-run] estate: would verify vendored binaries "
                  "(tools/third_party.py --verify)")
            print(estate_neo4j_row(harness_root(), os.environ))
            for row in estate_attach_rows(report, workspace["root"]):
                print(row)
        # The graph is the largest thing this command does. A dry run that lists four file
        # writes and never mentions it describes a different command than the real one.
        reason = no_chain_reason(root, enabled=graph, workspace=workspace, estate=estate)
        if reason:
            print(f"[dry-run] {NO_GRAPH}{reason}")
        elif estate and workspace is not None:
            print(f"[dry-run] graph: would build the workspace into {root / GRAPH_OUT}")
        else:
            print(f"[dry-run] graph: would build into {root / GRAPH_OUT}")
        if defer_graph and not reason:
            print("[dry-run] graph surfaces: the sdlc-graph skill/rules files and the "
                  "instruction-file graph section would be written after a successful "
                  "build, not before it")
        if not reason:
            print(f"[dry-run] mcp: would register {MCP_SERVER_NAME} in {MCP_CONFIG} "
                  f"once the graph exists")
        return 0

    print(f"\nDone. {changed} file(s) written.")
    if estate and workspace is not None and report is not None:
        # Preflight before the build, so an environment finding is read in the minute
        # the build takes rather than scrolled away by it.
        print("\nestate preflight:")
        for row in estate_verify_rows(harness_root()):
            print(row)
        print(estate_neo4j_row(harness_root(), os.environ))
        for row in estate_attach_rows(report, workspace["root"]):
            print(row)
    # Before the tips, not after: a build can take minutes, and a sign-off line printed
    # above it would read as the end of the command.
    code = chain_graph_build(root, enabled=graph, workspace=workspace, estate=estate,
                             workspace_path=workspace_path, from_snapshot=from_snapshot)
    # The deferred graph surfaces, now the build has had its turn. Written only if a
    # graph actually exists: `code == 0` also covers "honestly not built", which
    # teaches nothing, and a failed build must leave no instructions to nowhere.
    if defer_graph:
        if (root / GRAPH_OUT / "graph.jsonl").is_file():
            late = [o for o in surface_ops(root, tools, skill_body, description,
                                           with_graph=True, extras_on=extras_on)
                    if o["status"] not in ("unchanged", "blocked")]
            if late:
                print("\n  graph surfaces (written now the graph exists):")
                for op in late:
                    mark = "+ create" if op["status"] == "create" else "~ update"
                    print(f"    {mark:<38} {op['rel']}")
                    write_lf(op["path"], op["content"])
        else:
            print("\n  NOTE: no graph was built, so nothing that teaches one was "
                  "written - no sdlc-graph skill/rules files, and no graph section in "
                  "the instruction files. Re-run once the build succeeds.")
    # Registration is gated on the graph the entry would serve actually existing —
    # a server registered over nothing greets every session with a startup refusal.
    # Re-deriving the chain decision is the dry-run's own pattern; `code == 0` alone
    # would also cover "honestly not built", which writes no graph to serve.
    if (code == 0
            and no_chain_reason(root, enabled=graph, workspace=workspace,
                                estate=estate) is None
            and (root / GRAPH_OUT / "graph.jsonl").is_file()):
        print(register_mcp(root, harness_root(),
                           workspace_path=workspace_path if estate else None))
    # The same logic in reverse on failure: sign-off tips printed BELOW "build FAILED"
    # would read as the end of the command, and the end of the command would read as
    # success. The failure message already says the scaffold is usable.
    if code == 0:
        if claude_extras and not extras_skipped:
            print("Claude extras: subagents + auto-lint/session hooks + a scoped permission allowlist"
                  " were installed (settings.json merged, not clobbered).")
        elif "claude" in tools:
            print("Tip: add --claude-extras for reviewer subagents, a no-prompt permission allowlist,"
                  " and automation hooks (Claude Code only).")
        # COMMIT FIRST, and said here because the next step refuses without
        # it. P0 requires a clean tree - a baseline measured over uncommitted
        # edits describes a state nobody can reconstruct - and the files that
        # make it dirty are the ones just written above. A first-time adopter
        # who follows the README hits that refusal on step two, which is how
        # this line came to be written.
        print("Next: commit what was just installed - the first run needs a clean tree:")
        print("        git add -A && git commit -m \"chore: install SDLC harness\"")
        print("      then open this repo in an AI coding tool and run  /sdlc <your bug or feature>")
        print("      (or 'follow the sdlc workflow for: <task>' in tools without slash commands).")
    return code


# ── extras ────────────────────────────────────────────────────────────────────
def do_bundle(out: Path) -> int:
    """Emit a single self-contained script with templates base64-embedded."""
    src = Path(__file__).resolve().read_text(encoding="utf-8")
    names = TEMPLATE_FILES + EXTRA_TEMPLATE_FILES
    emb = {name: base64.b64encode(load_template(name).encode("utf-8")).decode("ascii")
           for name in names}
    literal = "_EMBEDDED: dict[str, str] = " + json.dumps(emb, indent=0) + "\n"
    new_src, n = re.subn(r"^_EMBEDDED: dict\[str, str\] = \{\}\s*$", literal, src, count=1, flags=re.M)
    if n != 1:
        sys.exit("error: could not locate _EMBEDDED placeholder to bundle")
    write_lf(out, new_src)
    print(f"Wrote self-contained bundle -> {out} ({len(names)} templates embedded).")
    return 0


def do_dump_templates(dest: Path) -> int:
    names = TEMPLATE_FILES + EXTRA_TEMPLATE_FILES
    for name in names:
        write_lf(dest / name, load_template(name))
    print(f"Wrote {len(names)} templates -> {dest}")
    return 0


