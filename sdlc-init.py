class WorkspaceError(Exception):
    """A workspace config that cannot be trusted. Always fatal, never a warning."""


def _ws_reject(where: str, key: str, known) -> None:
    """Unknown key -> hard error, with a spelling hint.

    Never a warning. An ignored key means the thing the developer asked for silently
    did not happen, and they find out much later from behaviour that looks like a bug
    in the harness rather than a typo in their config.
    """
    from difflib import get_close_matches
    hint = get_close_matches(key, sorted(known), n=1, cutoff=0.6)
    raise WorkspaceError(
        f"unknown key `{key}` in {where}."
        + (f" Did you mean `{hint[0]}`?" if hint else "")
        + f"\n  known keys: {', '.join(sorted(known))}"
    )


def _ws_str(block: dict, key: str, where: str, default: str = "") -> str:
    v = block.get(key, default)
    if not isinstance(v, str):
        raise WorkspaceError(f"`{key}` in {where} must be a string, not {type(v).__name__}")
    return v.strip()


def _escapes_root(pat: str) -> str | None:
    """How `pat` leaves the directory it is relative to — `"absolute"`, `"parent"`,
    or None when it stays inside.

    ONE implementation of *does this escape the root*, because there were two
    questions with the same answer 1,500 lines apart and only one of them was
    being asked: `_ws_globs` refused an include glob with `'..'` in it, while the
    cadence jobs rendered `../workspace.toml` into a workflow whose runner has
    nothing above the checkout. A second implementation of this predicate is the
    class the first one exists to end.

    A backslash is normalised first: on Windows `os.path.relpath` answers with
    them, and `Path("..\\\\x").parts` on POSIX is a single part that contains
    `..` without ever equalling it.
    """
    p = pat.strip().replace("\\", "/")
    if p.startswith("/") or (len(p) > 1 and p[1] == ":"):
        return "absolute"
    if ".." in PurePosixPath(p).parts:
        return "parent"
    return None


def _ws_globs(data: dict, key: str) -> list[str]:
    v = data.get(key, [])
    if not isinstance(v, list):
        raise WorkspaceError(f"`{key}` must be a list of glob strings, not {type(v).__name__}")
    out = []
    for i, item in enumerate(v):
        if not isinstance(item, str):
            raise WorkspaceError(f"`{key}[{i}]` must be a string, not {type(item).__name__}")
        pat = item.strip().replace("\\", "/")
        if not pat:
            raise WorkspaceError(f"`{key}[{i}]` is empty — an empty glob has no defensible "
                                 f"meaning, so it is rejected rather than guessed at")
        # Both of these reach `Path.glob`, which raises NotImplementedError on an absolute
        # pattern — an unhandled traceback out of a function whose entire contract is that a
        # bad config produces a message. And a pattern is meant to be relative to `root`;
        # one that escapes it is describing a different workspace.
        how = _escapes_root(pat)
        if how == "absolute":
            raise WorkspaceError(f"`{key}[{i}]` is an absolute path ({item!r}). Patterns are "
                                 f"relative to `root` — move the common prefix into `root`")
        if how == "parent":
            raise WorkspaceError(f"`{key}[{i}]` escapes `root` with '..' ({item!r}). If the "
                                 f"components live elsewhere, that elsewhere is your `root`")
        out.append(pat)
    return out


def _ws_str_list(block: dict, key: str, where: str) -> list[str]:
    """A list of strings, or a hard error. Never a bare string.

    `known_failures = "test_a"` is the natural typo, and `list("test_a")` is
    `['t','e','s','t','_','a']` — six invented quarantined test names, written into the
    profile, with nothing anywhere reporting a problem.
    """
    v = block.get(key, [])
    if isinstance(v, str):
        raise WorkspaceError(f"`{key}` in {where} must be a LIST, not a bare string: write "
                             f"`{key} = [{v!r}]`")
    if not isinstance(v, list) or any(not isinstance(x, str) for x in v):
        raise WorkspaceError(f"`{key}` in {where} must be a list of strings")
    return [x for x in (s.strip() for s in v) if x]


def _ws_int(block: dict, key: str, where: str, lo: int, hi: int) -> int | None:
    """An int in range, or a hard error. `True` is NOT an int here.

    `isinstance(True, int)` is True in Python, so a naive check lets `coverage_threshold =
    true` through as the integer 1 — a 1% coverage gate that passes everything, silently.
    A float is rejected rather than rounded: silently ignoring a value the developer wrote
    is the same failure in a quieter coat.
    """
    if key not in block:
        return None
    v = block[key]
    if isinstance(v, bool) or not isinstance(v, int):
        raise WorkspaceError(f"`{key}` in {where} must be a whole number between {lo} and "
                             f"{hi}, not {v!r}")
    if not lo <= v <= hi:
        raise WorkspaceError(f"`{key}` in {where} is {v}, outside {lo}–{hi}")
    return v


def read_workspace(path: Path) -> dict:
    """Parse and validate a developer-filled workspace config.

    Every failure here is loud. The alternative — tolerate, warn, continue — produces
    a component list that is confidently wrong, and an empty or truncated workspace
    reads exactly like a clean one.

    Returns a dict with `root` resolved to an absolute Path, `overrides` keyed by
    component name (so the merge in discovery is a lookup), and `canonical` as a list.
    Whether a `[[canonical]]` owner names a real component cannot be checked here —
    nothing has been discovered yet — so that check belongs to discovery.
    """
    try:
        import tomllib
    except ModuleNotFoundError:  # pragma: no cover - depends on the interpreter
        raise WorkspaceError(
            "workspace mode needs Python 3.11+ for stdlib `tomllib` "
            f"(this is {sys.version_info.major}.{sys.version_info.minor}).\n"
            "  Single-repo mode has no such floor — run without --workspace."
        )

    if not path.is_file():
        raise WorkspaceError(f"no such workspace file: {path}\n"
                             "  copy sdlc_templates/workspace.example.toml and fill in `root`")
    try:
        # utf-8-sig: a BOM is invisible in an editor and yields a baffling parse error.
        raw_text = path.read_text(encoding="utf-8-sig")
        data = tomllib.loads(raw_text)
    except tomllib.TOMLDecodeError as e:
        raise WorkspaceError(f"{path} is not valid TOML: {e}")

    for key in data:
        if key not in _WS_TOP_KEYS:
            _ws_reject("the top level", key, _WS_TOP_KEYS)

    version = data.get("schema_version", WORKSPACE_SCHEMA_VERSION)
    if version != WORKSPACE_SCHEMA_VERSION:
        raise WorkspaceError(f"schema_version {version!r} is not supported "
                             f"(this harness reads version {WORKSPACE_SCHEMA_VERSION})")

    raw_root = _ws_str(data, "root", "the top level")
    if not raw_root:
        raise WorkspaceError(
            "`root` is required and is the only required field — the directory that "
            "CONTAINS your repositories.\n  A scanner has to start somewhere and there "
            "is no way to infer where."
        )
    # Relative to THIS FILE, never to the shell's cwd: the same file must not mean
    # different things depending on where it was run from. Joining an absolute path
    # replaces the left side, so this handles both forms.
    root = (path.parent / raw_root).resolve()
    if not root.is_dir():
        raise WorkspaceError(
            f"`root` does not exist or is not a directory: {root}\n"
            "  Refusing to continue: a mistyped root finds zero components, and an "
            "empty workspace reads exactly like a clean one."
        )

    overrides: dict[str, dict] = {}
    blocks = data.get("component", [])
    if not isinstance(blocks, list):
        raise WorkspaceError("`component` must be written as [[component]] blocks")
    for i, block in enumerate(blocks):
        if not isinstance(block, dict):
            raise WorkspaceError(f"[[component]] #{i + 1} is not a table")
        where = f"[[component]] #{i + 1}"
        for key in block:
            if key not in _WS_COMPONENT_KEYS:
                _ws_reject(where, key, _WS_COMPONENT_KEYS)
        name = _ws_str(block, "name", where)
        if not name:
            raise WorkspaceError(f"{where} has no `name` — the name is what says which "
                                 f"component the block overrides")
        if name in overrides:
            raise WorkspaceError(f"two [[component]] blocks are both named {name!r} — "
                                 f"there is no way to tell which one you meant")
        role = _ws_str(block, "role", where, DEFAULT_ROLE) or DEFAULT_ROLE
        if role not in COMPONENT_ROLES:
            raise WorkspaceError(f"{where}: role {role!r} is not one of "
                                 f"{', '.join(COMPONENT_ROLES)}")
        vcs = block.get("vcs", {})
        if not isinstance(vcs, dict):
            raise WorkspaceError(f"{where}: `vcs` must be a table")
        for key in vcs:
            if key not in _WS_VCS_KEYS:
                _ws_reject(f"{where} [component.vcs]", key, _WS_VCS_KEYS)
        merged = {**block, "name": name, "role": role, "vcs": dict(vcs),
                  "known_failures": _ws_str_list(block, "known_failures", where)}
        if (threshold := _ws_int(block, "coverage_threshold", where, 0, 100)) is not None:
            merged["coverage_threshold"] = threshold
        overrides[name] = merged

    canonical: list[dict] = []
    seen_services: set[str] = set()
    blocks = data.get("canonical", [])
    if not isinstance(blocks, list):
        raise WorkspaceError("`canonical` must be written as [[canonical]] blocks")
    for i, block in enumerate(blocks):
        if not isinstance(block, dict):
            raise WorkspaceError(f"[[canonical]] #{i + 1} is not a table")
        where = f"[[canonical]] #{i + 1}"
        for key in block:
            if key not in _WS_CANONICAL_KEYS:
                _ws_reject(where, key, _WS_CANONICAL_KEYS)
        service = _ws_str(block, "service", where)
        owner = _ws_str(block, "owner", where)
        if not service or not owner:
            raise WorkspaceError(f"{where} needs both `service` and `owner` — a collision "
                                 f"with no owner records the problem without deciding it")
        if service in seen_services:
            raise WorkspaceError(f"two [[canonical]] blocks both claim service {service!r}")
        seen_services.add(service)
        # `path` narrows the decision when one component holds several variants — two
        # deployment trees in one repository, say. `owner` alone answers "which component",
        # which is enough for the usual collision and not enough for that one.
        canonical.append({"service": service, "owner": owner,
                          "path": _ws_str(block, "path", where)})

    # ── [[generated]]: committed codegen, declared so its facts change MEANING ──
    # Declared, never detected: a DO-NOT-EDIT header is a convention some generators
    # skip and some humans paste, while this block is a statement of intent. Measured
    # before designed — on a real estate 577 marker-bearing files followed ZERO of the
    # classic name conventions, so a name-based detector would have found nothing.
    generated: list[dict] = []
    seen_trees: set[tuple[str, str]] = set()
    blocks = data.get("generated", [])
    if not isinstance(blocks, list):
        raise WorkspaceError("`generated` must be written as [[generated]] blocks")
    for i, block in enumerate(blocks):
        if not isinstance(block, dict):
            raise WorkspaceError(f"[[generated]] #{i + 1} is not a table")
        where = f"[[generated]] #{i + 1}"
        for key in block:
            if key not in _WS_GENERATED_KEYS:
                _ws_reject(where, key, _WS_GENERATED_KEYS)
        component = _ws_str(block, "component", where)
        tree = _ws_str(block, "path", where).strip("/")
        if not component or not tree:
            raise WorkspaceError(
                f"{where} needs both `component` and `path` — a generated tree is a "
                f"place, and a blank path would claim the whole component silently")
        if (component, tree) in seen_trees:
            raise WorkspaceError(
                f"two [[generated]] blocks both claim {component}/{tree}")
        seen_trees.add((component, tree))
        # `from` is where a human actually makes the change — the generator's input.
        # Recorded verbatim, workspace-root-relative; existence is checked at
        # discovery, where the root is known to hold real directories.
        generated.append({"component": component, "path": tree,
                          "from": _ws_str(block, "from", where)})

    # ── item 79: the semantic layer — declarations extraction cannot reach ──
    # Each dict carries the DECLARATION's own citation (this file's basename + the
    # block's header line, found in the raw text because tomllib keeps no line
    # numbers): a hand-declared fact must cite the place a human typed it, or it
    # becomes indistinguishable from extraction exactly where the provenance
    # guarantee matters most. tomllib preserves array order, so the i-th block is
    # the i-th header. Node EXISTENCE is a link-time question — the graph is not
    # built yet — so a miss becomes an unresolved row there, never a silent no-op.
    def _block_lines(kind: str) -> list[int]:
        return [i + 1 for i, ln in enumerate(raw_text.splitlines())
                if ln.strip().startswith(f"[[{kind}]]")]

    def _semantic_cite(kind: str, index: int) -> tuple[str, int]:
        lines = _block_lines(kind)
        return path.name, lines[index] if index < len(lines) else 0

    entrypoints: list[dict] = []
    seen_nodes: set[str] = set()
    blocks = data.get("entrypoint", [])
    if not isinstance(blocks, list):
        raise WorkspaceError("`entrypoint` must be written as [[entrypoint]] blocks")
    for i, block in enumerate(blocks):
        if not isinstance(block, dict):
            raise WorkspaceError(f"[[entrypoint]] #{i + 1} is not a table")
        where = f"[[entrypoint]] #{i + 1}"
        for key in block:
            if key not in _WS_ENTRYPOINT_KEYS:
                _ws_reject(where, key, _WS_ENTRYPOINT_KEYS)
        node = _ws_str(block, "node", where)
        if not node or ":" not in node:
            raise WorkspaceError(
                f"{where} needs `node` as a graph node id (TYPE:REST, e.g. "
                f"\"ep:/orders/v1/list\") — the ids the graph's own listings print")
        if node in seen_nodes:
            raise WorkspaceError(f"two [[entrypoint]] blocks both declare {node!r}")
        seen_nodes.add(node)
        file, line = _semantic_cite("entrypoint", i)
        entrypoints.append({"node": node, "note": _ws_str(block, "note", where),
                            "file": file, "line": line})

    aliases: list[dict] = []
    seen_pairs: set[frozenset[str]] = set()
    blocks = data.get("alias", [])
    if not isinstance(blocks, list):
        raise WorkspaceError("`alias` must be written as [[alias]] blocks")
    for i, block in enumerate(blocks):
        if not isinstance(block, dict):
            raise WorkspaceError(f"[[alias]] #{i + 1} is not a table")
        where = f"[[alias]] #{i + 1}"
        for key in block:
            if key not in _WS_ALIAS_KEYS:
                _ws_reject(where, key, _WS_ALIAS_KEYS)
        a, b = _ws_str(block, "a", where), _ws_str(block, "b", where)
        if not a or not b or ":" not in a or ":" not in b:
            raise WorkspaceError(
                f"{where} needs `a` and `b` as graph node ids (TYPE:REST) — an alias "
                f"joins two existing entities; it cannot mint one")
        if a == b:
            raise WorkspaceError(f"{where} aliases {a!r} to itself")
        if frozenset((a, b)) in seen_pairs:
            raise WorkspaceError(f"two [[alias]] blocks both join {a!r} and {b!r}")
        seen_pairs.add(frozenset((a, b)))
        file, line = _semantic_cite("alias", i)
        aliases.append({"a": a, "b": b, "note": _ws_str(block, "note", where),
                        "file": file, "line": line})

    return {
        "schema_version": WORKSPACE_SCHEMA_VERSION,
        "config_path": path.resolve(),
        "root": root,
        "name": _ws_str(data, "name", "the top level"),
        "profile": _ws_str(data, "profile", "the top level"),
        "include": _ws_globs(data, "include"),
        "exclude": _ws_globs(data, "exclude"),
        "overrides": overrides,
        "canonical": canonical,
        "generated": generated,
        "entrypoint": entrypoints,
        "alias": aliases,
    }


# ── component discovery ───────────────────────────────────────────────────────
# Everything detection CAN reach, reached by running the detectors the single-repo
# path already uses — a `for` loop over components, not a second implementation.
# The workspace config supplies only what a scanner cannot see: where to look, what
# to ignore, what each component's role is, and who owns a contested name.

#: Fields a [[component]] block may override, with the type that survives a merge.
#: A BLANK STRING MEANS INHERIT, never "set this to empty". The commented example
#: block in the template ships with blank values, and a developer who uncomments it
#: wholesale must not thereby wipe every detected command. To genuinely disable a
#: step, blank it in the generated `.sdlc/profile.yml`, where blank means skipped —
#: that file is preserved across re-runs precisely so it can hold such edits.
_MERGEABLE_STRINGS = ("path", "stack", "test_command", "coverage_command",
                      "lint_command", "build_command", "deploy_command")


def _git_dir(component: Path) -> Path | None:
    """The real git directory for a component, or None if it is not a repository.

    `.git` is a DIRECTORY in an ordinary clone and a FILE (`gitdir: <path>`) in a
    worktree or a submodule. Testing only `is_dir()` would silently drop every
    submodule in the workspace — a common way to lay one out, and a failure that
    presents as "the harness just didn't see that repo".
    """
    dot = component / ".git"
    if dot.is_dir():
        return dot
    if dot.is_file():
        try:
            text = dot.read_text(encoding="utf-8", errors="replace").strip()
        except OSError:
            return None
        if text.startswith("gitdir:"):
            return (component / text.split(":", 1)[1].strip()).resolve()
    return None


# ── the repository you are standing in (no config file at all) ────────────────
# One repo is the degenerate one-component case, so it gets the same pipeline through a
# synthesized workspace rather than a second code path. `read_workspace` is untouched.


def find_repo_root(start: Path | None = None) -> Path | None:
    """The repository containing `start` (default: the shell's cwd), or None if there is none.

    Walks up. `.git` is a directory in an ordinary clone and a file in a worktree or a
    submodule, and `_git_dir` already knows the difference — so a developer standing in a
    linked worktree gets that worktree, which is the tree their edits are actually in.
    """
    here = (Path(start) if start is not None else Path.cwd()).resolve()
    if here.is_file():
        here = here.parent
    for candidate in (here, *here.parents):
        if _git_dir(candidate) is not None:
            return candidate
    return None


def nested_clones(repo: Path) -> list[str]:
    """Immediate child directories of `repo` that are independent clones.

    **The `.git` DIRECTORY is the whole test, and the file form is deliberately excluded.**
    A submodule or a linked worktree carries a `.git` *file* pointing back into the parent:
    it is part of this repository rather than a peer of it, and counting it would refuse to
    build every superproject that vendors a dependency the ordinary way.

    Depth one, matching what `discover_components` scans by default — so this finds exactly
    the components the multi-repo path would have found, and nothing it would have missed.
    """
    try:
        children = sorted(repo.iterdir())
    except OSError:
        return []
    return [c.name for c in children if c.is_dir() and (c / ".git").is_dir()]


def workspace_for_repo(start: Path | None = None) -> dict:
    """A one-component workspace inferred from the repository containing `start`.

    **The same shape `read_workspace` returns**, so discovery, rendering and the build
    engine cannot tell the two routes apart — which is the point. A second workspace shape
    would mean every consumer downstream had to learn which route a workspace arrived by.

    Standing inside a repository, `root` is reachable, so the template's own rule — declare
    only what detection cannot reach — says it must not be asked for. It stays required
    *inside a config file*, where "wherever you ran it from" would make one file mean
    different things on different machines, and it stays required for multi-repo, where no
    scanner can infer the directory holding your clones from inside one of them.

    Two silences are refused rather than papered over, because each produces output that
    reads exactly like a correct answer.
    """
    where = (Path(start) if start is not None else Path.cwd()).resolve()
    repo = find_repo_root(where)
    if repo is None:
        raise WorkspaceError(
            f"not inside a git repository: {where}\n"
            "  Nothing at or above this directory carries a .git, so there is no repository "
            "to build and no defensible way to guess which one you meant.\n"
            "  Refusing rather than reporting an empty workspace, which is indistinguishable "
            "from a clean one.\n"
            "  cd into a repository, or name a workspace with --workspace <file>."
        )
    if repo.parent == repo:
        raise WorkspaceError(
            f"the repository at {repo} is a filesystem root, so it has no parent directory "
            f"to serve as `root`.\n"
            "  Name a workspace with --workspace <file> instead."
        )
    if nested := nested_clones(repo):
        shown = ", ".join(nested[:5]) + (f" (+{len(nested) - 5} more)" if len(nested) > 5 else "")
        raise WorkspaceError(
            f"{repo} contains repositories of its own: {shown}\n"
            "  Building it as ONE component would collapse every coupling between them into "
            "a single node, and nothing in the output would say so — a graph that is wrong "
            "in a way nothing downstream can detect.\n"
            "  This is a multi-repo workspace: copy sdlc_templates/workspace.example.toml, "
            "set `root`, and pass it with --workspace."
        )
    return {
        "schema_version": WORKSPACE_SCHEMA_VERSION,
        # No file was read. Consumers render this as "inferred" rather than as a path, and
        # a profile — which resolves relative to the config file — cannot be selected without
        # one, which is correct: a profile is a deliberate choice, never an inferred default.
        "config_path": None,
        "inferred_from": repo,
        "root": repo.parent,
        # Blank, and loudly so. `name` seeds the leak guard's ban list, and a directory name
        # is a guess at an organisation's identity rather than a statement of it — hashing a
        # guess protects nothing while looking exactly like protection.
        "name": "",
        "profile": "",
        # Escaped: `glob` reads `[`, `]`, `*` and `?` as pattern syntax, so a repository
        # named `svc[1]` would match `svc1` and report zero components — the mistyped-root
        # failure, arriving from a name the developer never typed.
        "include": [glob.escape(repo.name)],
        "exclude": [],
        "overrides": {},
        "canonical": [],
        "generated": [],
        "entrypoint": [],
        "alias": [],
    }


def _expand(root: Path, patterns: list[str]) -> set[Path]:
    """Glob patterns against `root`, anchored. Directories only.

    `include` and `exclude` deliberately share this one semantic. Two different
    matching rules for two adjacent fields is a trap: the developer would have to
    know which field they were in to predict what a pattern meant.
    """
    out: set[Path] = set()
    for pat in patterns:
        out.update(p for p in root.glob(pat) if p.is_dir())
    return out


def _describe(path: Path, rel: str) -> dict:
    """Everything detection can say about one component directory.

    Shared by both routes in, so a declared component and a discovered one are the same
    shape — otherwise the renderer and the build engine would each need to know which
    route a component arrived by.
    """
    git_dir = _git_dir(path)
    return {
        "name": path.name,
        "path": rel,
        "role": DEFAULT_ROLE,
        # Detected and REPORTED, never filtered out. A shallow clone is readable but
        # un-diffable, so half the harness works on it and half does not — that is a
        # finding the developer needs, not noise to hide.
        "shallow": bool(git_dir and (git_dir / "shallow").is_file()),
        "known_failures": [],
        **detect_stack(path),
        "vcs": detect_vcs(path),
    }


def discover_components(ws: dict) -> dict:
    """Find the workspace's components and describe each one.

    Returns `{"components": [...], "skipped": [...]}`. `skipped` lists candidate
    directories that carry no `.git`; it is reported rather than dropped, because a
    directory the developer's own `include` glob selected and the harness then
    ignored is exactly the kind of silence that reads as a harness bug later.
    """
    root: Path = ws["root"]
    candidates = _expand(root, ws["include"]) if ws["include"] else {
        p for p in root.iterdir() if p.is_dir()}
    candidates -= _expand(root, ws["exclude"])

    components: list[dict] = []
    skipped: list[str] = []
    for path in sorted(candidates):
        rel = path.relative_to(root).as_posix()
        if _git_dir(path) is None:
            skipped.append(rel)
            continue
        components.append(_describe(path, rel))

    if not components and not ws["overrides"]:
        raise WorkspaceError(
            f"no components found under {root}\n"
            f"  scanned: {'the patterns in `include`' if ws['include'] else 'every immediate subdirectory'}\n"
            f"  {len(skipped)} director{'y' if len(skipped) == 1 else 'ies'} had no .git"
            + (f": {', '.join(skipped[:5])}" if skipped else "")
            + "\n  Refusing to continue rather than reporting an empty workspace, which "
              "is indistinguishable from a clean one."
        )

    _apply_overrides(components, ws)
    components.sort(key=lambda c: c["name"])

    known = {c["name"] for c in components}
    for entry in ws["canonical"]:
        if entry["owner"] not in known:
            raise WorkspaceError(
                f"[[canonical]] service {entry['service']!r} names owner "
                f"{entry['owner']!r}, which is not a discovered component.\n"
                f"  discovered: {', '.join(sorted(known))}"
            )
    for entry in ws.get("generated", []):
        if entry["component"] not in known:
            raise WorkspaceError(
                f"[[generated]] path {entry['path']!r} names component "
                f"{entry['component']!r}, which is not a discovered component.\n"
                f"  discovered: {', '.join(sorted(known))}"
            )
        # "Regenerate from X" pointing at a missing X is advice that is confidently
        # wrong — the failure mode this whole feature exists to remove. A directory
        # is as legal as a file: a generated spec's input is often a source tree.
        if entry["from"] and not (root / entry["from"]).exists():
            raise WorkspaceError(
                f"[[generated]] {entry['component']}/{entry['path']} says regenerate "
                f"from {entry['from']!r}, which does not exist under the workspace "
                f"root — the path is root-relative, so name it from the top"
            )

    return {"components": components, "skipped": skipped}


def _apply_overrides(components: list[dict], ws: dict) -> None:
    """Merge each [[component]] block onto the component it targets, in place.

    A block that targets nothing is a HARD ERROR. It is the quietest possible
    failure otherwise: the developer wrote a deliberate instruction, the harness
    ignored it, and the only symptom is behaviour that looks like the override was
    never honoured — which is precisely what happened.
    """
    by_path = {c["path"]: c for c in components}
    by_name = {c["name"]: c for c in components}

    for name, block in ws["overrides"].items():
        # `path` identifies the component by LOCATION, which also allows a rename:
        # a directory called `orders-service` can be declared as component `orders`.
        # Without that, matching on name alone would reject the rename as unknown.
        target_path = str(block.get("path", "")).strip().replace("\\", "/").strip("/")
        if target_path:
            target = by_path.get(target_path)
            if target is None:
                # A block with an explicit path DECLARES a component; it does not merely
                # annotate a discovered one. The `.git` requirement is a heuristic for
                # deciding what is a component when nobody said — it must not overrule
                # somebody who did. Without this there is no way to describe a workspace
                # whose components are not separate clones: a monorepo's service
                # directories, a vendored tree, or the harness's own fixture workspace.
                directory = ws["root"] / target_path
                if not directory.is_dir():
                    raise WorkspaceError(
                        f"[[component]] {name!r} has path {target_path!r}, which does not "
                        f"exist under {ws['root']}.\n  discovered paths: "
                        f"{', '.join(sorted(by_path)) or 'none'}"
                    )
                target = _describe(directory, target_path)
                components.append(target)
                by_path[target_path] = target
        else:
            target = by_name.get(name)
            if target is None:
                raise WorkspaceError(
                    f"[[component]] {name!r} matches no discovered component, so the "
                    f"whole block would do nothing.\n  discovered: "
                    f"{', '.join(sorted(by_name))}\n"
                    f"  If the directory is named differently, set `path` in the block."
                )

        target["name"] = name
        target["role"] = block["role"]
        for key in _MERGEABLE_STRINGS:
            value = str(block.get(key, "")).strip()
            if value:
                target[key] = value
        # Both were validated at read time — a bool or a bare string never reaches here.
        if "coverage_threshold" in block:
            target["coverage_threshold"] = block["coverage_threshold"]
        if block["known_failures"]:
            target["known_failures"] = list(block["known_failures"])
        # The vcs block merges KEY BY KEY onto what detection found: a developer who
        # only wants to set deny_raw_git must not thereby erase a detected
        # commit_command they never mentioned.
        target["vcs"] = {**target["vcs"], **block["vcs"]}

    final = [c["name"] for c in components]
    clashes = sorted({n for n in final if final.count(n) > 1})
    if clashes:
        raise WorkspaceError(
            f"renaming produced duplicate component names: {', '.join(clashes)}\n"
            f"  two components cannot share a name — every edge in the graph is keyed on it"
        )


# ── rendering ─────────────────────────────────────────────────────────────────
def _yaml_dq(v: str) -> str:
    """Escape a value for a double-quoted YAML scalar (commands may contain quotes)."""
    return v.replace("\\", "\\\\").replace('"', '\\"')


def _yaml_list(values) -> str:
    """A flow-style list of quoted scalars. Empty renders as `[]`, not as a blank."""
    return "[" + ", ".join('"' + _yaml_dq(str(v)) + '"' for v in values) + "]"


#: What `components:` looks like when there is only one repo: commented-out
#: documentation. A single-repo install must render byte-for-byte what it always
#: has, so this is the existing block with `role` added — the drop-in regression
#: tests are what hold that promise.
COMPONENTS_PLACEHOLDER = """\
# components:                            # multi-component installs only; one per repo
#   - name: orders-service
#     path: ../orders-service            # relative to this file, or absolute
#     role: authoritative                # authoritative | legacy | fork | vendor
#     test_command: "mvn -q test"        # per-component overrides; blank = inherit
#     build_command: ""
#     coverage_command: ""
#     known_failures: []                 # pre-existing reds, quarantined not ignored
#     vcs: {}                            # same shape as the top-level vcs: block"""

#: Emitted per component, in this order, as double-quoted YAML scalars.
_COMPONENT_COMMANDS = ("test_command", "coverage_command", "lint_command",
                       "build_command", "deploy_command")


def render_components(components: list[dict]) -> str:
    """Render discovered components as a YAML block.

    Deliberately NOT emitted: `shallow`. It is true at install time and false the
    moment someone runs `git fetch --unshallow`, and a config value that silently
    goes stale is worse than a `.git/shallow` stat at the point of use. It is
    reported by the installer instead, where it is a finding rather than a fact on
    file.
    """
    if not components:
        return COMPONENTS_PLACEHOLDER
    lines = ["components:"]
    for c in components:
        name = _yaml_dq(str(c["name"]))
        path = _yaml_dq(str(c["path"]))
        lines.append('  - name: "' + name + '"')
        lines.append('    path: "' + path + '"')
        lines.append("    role: " + str(c.get("role", DEFAULT_ROLE)))
        lines.append("    stack: " + str(c.get("stack", "unknown")))
        # Emitted per component for the same reason as at the top level: in a workspace
        # this is where a multi-stack component is actually visible, and a blank command
        # below with nothing explaining it reads as detection having failed.
        lines.append("    stacks: " + _yaml_list(c.get("stacks") or []))
        lines.append('    stack_note: "' + _yaml_dq(str(c.get("stack_note", ""))) + '"')
        for key in _COMPONENT_COMMANDS:
            lines.append("    " + key + ': "' + _yaml_dq(str(c.get(key, ""))) + '"')
        lines.append("    coverage_threshold: " + str(int(c.get("coverage_threshold", 90))))
        lines.append("    known_failures: " + _yaml_list(c.get("known_failures") or []))
        vcs = c.get("vcs") or {}
        lines.append("    vcs:")
        lines.append('      commit_command: "' + _yaml_dq(str(vcs.get("commit_command", ""))) + '"')
        lines.append('      push_command: "' + _yaml_dq(str(vcs.get("push_command", ""))) + '"')
        # Blank means "the policy's own" for both. Emitted anyway, because a key
        # that is absent from the file is a key nobody knows they could set.
        lines.append('      push_remote: "' + _yaml_dq(str(vcs.get("push_remote", ""))) + '"')
        lines.append('      branch_pattern: "' + _yaml_dq(str(vcs.get("branch_pattern", ""))) + '"')
        lines.append("      deny_raw_git: " + ("true" if vcs.get("deny_raw_git") else "false"))
        lines.append('      notes: "' + _yaml_dq(str(vcs.get("notes", ""))) + '"')
    return "\n".join(lines)


def render_profile(profile: dict, tools: list[str]) -> str:
    tpl = load_template("profile.yml")
    vcs = profile.get("vcs") or {}
    components = profile.get("components") or []
    # `solo` is a HARD REFUSAL above one component (LIFECYCLE.md, Gates). Emitting it
    # anyway would ship a profile the spec that generated it would reject — which is
    # exactly what the template did before this token existed.
    multi = len(components) > 1
    # Command values land inside double-quoted YAML slots -> must be escaped so a
    # value like  dotnet test --collect:"XPlat Code Coverage"  stays valid YAML.
    # NOTHING here may vary between two renders of the same version. This file is
    # `preserve`-compared byte-for-byte on every re-run (plan_op), so a value the
    # installer changes on its own is read as the ADOPTER's edit: the profile
    # upgrade is skipped, a `.new` is written that `.sdlc/.gitignore` hides behind
    # `*.new`, and they are told they edited a file they never touched. A
    # `# Generated: <today>` stamp did exactly that, silently, from the day after
    # every install — the same rule as keeping `run_id` out of the graph snapshot.
    repl = {
        "@@STACK@@": profile["stack"],
        # `.get`, not `[...]`: a caller assembling a profile by hand (the token-contract
        # test is one) predates these keys, and a renderer that raises on a missing
        # informational field would make an additive schema change a breaking one.
        "@@STACKS@@": _yaml_list(profile.get("stacks") or []),
        "@@STACK_NOTE@@": _yaml_dq(profile.get("stack_note", "")),
        "@@SCOPE@@": "estate" if multi else "repo",
        "@@COMPONENTS@@": render_components(components),
        "@@GATE_PROFILE@@": "team" if multi else "solo",
        "@@TEST_COMMAND@@": _yaml_dq(profile["test_command"]),
        "@@COVERAGE_COMMAND@@": _yaml_dq(profile["coverage_command"]),
        "@@COVERAGE_THRESHOLD@@": str(profile["coverage_threshold"]),
        "@@LINT_COMMAND@@": _yaml_dq(profile["lint_command"]),
        "@@BUILD_COMMAND@@": _yaml_dq(profile["build_command"]),
        "@@DEPLOY_COMMAND@@": _yaml_dq(profile["deploy_command"]),
        "@@TOOLS@@": ", ".join(tools),
        "@@VCS_COMMIT_COMMAND@@": _yaml_dq(vcs.get("commit_command", "")),
        "@@VCS_PUSH_COMMAND@@": _yaml_dq(vcs.get("push_command", "")),
        "@@VCS_DENY_RAW_GIT@@": "true" if vcs.get("deny_raw_git") else "false",
        "@@VCS_NOTES@@": _yaml_dq(vcs.get("notes", "")),
    }
    for k, v in repl.items():
        tpl = tpl.replace(k, v)
    return tpl


def tool_files(tool: str, skill_body: str, description: str,
               name: str = "sdlc") -> list[tuple[str, str, str]]:
    """Return [(relative_path, content, kind)] for one tool. kind: 'file' or 'block'.

    `name` selects which skill is being written. The graph tier used to be a
    second function carrying character-for-character copies of these three
    frontmatter formats, so a fix to one silently left the other stale."""
    if tool == "claude":
        full = f"---\nname: {name}\ndescription: {description}\n---\n\n{skill_body}"
        return [(f".claude/skills/{name}/SKILL.md", full, "file")]
    if tool == "cursor":
        fm = f"---\ndescription: {description}\nalwaysApply: false\n---\n\n"
        return [(f".cursor/rules/{name}.mdc", fm + skill_body, "file")]
    if tool == "windsurf":
        fm = f"---\ndescription: {description}\n---\n\n"
        return [(f".windsurf/rules/{name}.md", fm + skill_body, "file")]
    if tool == "copilot":
        return [(".github/copilot-instructions.md", skill_body, "block")]
    if tool == "gemini":
        return [("GEMINI.md", skill_body, "block")]
    if tool == "aider":
        return [("CONVENTIONS.md", skill_body, "block")]
    return []


#: The graph tier's skill name — its own file where a tool has per-file entry
#: points, its own section of the one block where it does not.
GRAPH_SKILL_NAME = "sdlc-graph"


def _tool_kinds(tool: str) -> set[str]:
    return {kind for _, _, kind in tool_files(tool, "", "")}


#: Tools whose entry point is a SHARED file owned one-block-at-a-time by merge_block.
#: The graph tier joins that one block rather than adding a second — merge_block's
#: unbalanced-marker refusal exists precisely to stop multi-block files, and arming
#: it against our own output would turn every re-run into a "repair by hand" note.
#: DERIVED from tool_files, not hand-listed: the per-tool knowledge sat in three
#: parallel tables, and a seventh tool added to one of them would have shipped no
#: graph tier at all — no error, no test, nothing to notice.
BLOCK_TOOLS = {t for t in ALL_TOOLS if _tool_kinds(t) == {"block"}}


def graph_skill(harness: Path) -> tuple[str, str]:
    """(description, body) of the graph-tier skill, rendered for THIS install.

    The body POINTS at the harness's workflows instead of restating them: the SOPs
    are currency-guarded once in `workflows/` (test_workflows), and six provider
    copies of their prose would be six independently rotting restatements. The
    harness path is machine-specific by nature (the same recorded decision as
    `.mcp.json`'s absolute command at item 23) and the text says a moved clone
    means re-running the installer."""
    meta, body = parse_frontmatter(load_template("GRAPH-SKILL.md"))
    body = (body.replace("@@HARNESS@@", harness.resolve().as_posix())
                .replace("@@GRAPH_DIR@@", Path(GRAPH_OUT).as_posix()))
    return meta.get("description", "Query the repository's dependency graph."), body


def graph_tool_files(tool: str, body: str, description: str) -> list[tuple[str, str, str]]:
    """The graph tier through the SAME fan-out, under its own skill name: a
    SECOND file for tools with per-file entry points; nothing for BLOCK_TOOLS
    (their graph section joins the one sdlc block at the install() call site)."""
    if tool in BLOCK_TOOLS:
        return []
    return tool_files(tool, body, description, name=GRAPH_SKILL_NAME)


def surface_ops(root: Path, tools: list[str], skill_body: str, description: str,
                *, with_graph: bool, extras_on: bool) -> list[dict]:
    """Every per-tool entry point plus the instruction-file blocks, as plan_ops.

    One function, called once when the graph is already there and twice when it
    arrives during this run (see install): the surfaces that teach a graph must
    not be written before the build that produces it has succeeded."""
    ops: list[dict] = []
    g_desc = g_body = addendum = ""
    if with_graph:
        g_desc, g_body = graph_skill(harness_root())
        addendum = graph_addendum(harness_root())
    for tool in tools:
        body = skill_body + ("\n\n" + g_body
                             if with_graph and tool in BLOCK_TOOLS else "")
        for rel, content, kind in tool_files(tool, body, description):
            ops.append(plan_op(root, rel, content, kind=kind))
        if with_graph:
            for rel, content, kind in graph_tool_files(tool, g_body, g_desc):
                ops.append(plan_op(root, rel, content, kind=kind))
    # Instruction files: CLAUDE.md is Claude's, AGENTS.md the cross-tool standard.
    # A graph install CREATES AGENTS.md (the graph is exactly the context every
    # agent needs); without a graph the old rule stands — touch it only if the
    # repo already keeps one.
    if "claude" in tools:
        parts = instruction_parts(root, "CLAUDE.md", extras_on, addendum)
        if parts:
            ops.append(plan_op(root, "CLAUDE.md", "\n\n".join(parts), kind="block"))
    parts = instruction_parts(root, "AGENTS.md", extras_on, addendum)
    if parts and (with_graph or (root / "AGENTS.md").exists()):
        ops.append(plan_op(root, "AGENTS.md", "\n\n".join(parts), kind="block"))
    # At most ONE op per file, enforced rather than remembered: two ops on one file
    # would each read the ORIGINAL text, and the second write would silently drop
    # the first's block.
    rels = [o["rel"] for o in ops]
    if len(rels) != len(set(rels)):
        dupes = sorted({r for r in rels if rels.count(r) > 1})
        raise RuntimeError(f"two ops target the same file(s): {dupes} - one write "
                           f"would silently drop the other's block")
    return ops


#: The two sections a harness-managed instruction block can carry. They are
#: identified by heading so a run can tell which parts it OWNS from parts an
#: earlier run left: the block is replaced wholesale, so anything not recomposed
#: is deleted — which is how a plain re-run used to remove the /sdlc pointer a
#: `--claude-extras` install had written, while every file it pointed at stayed.
POINTER_HEADING = "## SDLC workflow (harness)"
GRAPH_HEADING = "## Dependency graph (sdlc-graph)"


def graph_addendum(harness: Path) -> str:
    """The instruction-file digest (CLAUDE.md / AGENTS.md block section): route a
    reader into the graph before they review or scope, in six lines, and point at
    the full skill for the doctrine.

    The harness path is QUOTED, for the reason builder_hint states: a clone under
    a path with a space word-splits, and every command this text teaches would
    fail for every reader."""
    h = harness.resolve().as_posix()
    return (
        f"{GRAPH_HEADING}\n\n"
        f"This target carries an extracted dependency graph at `{Path(GRAPH_OUT).as_posix()}` "
        "— every fact cites `source_file:line`. Before reviewing a diff or scoping a "
        f"feature, follow `{h}/workflows/impact-review.md` or "
        f"`{h}/workflows/feature-impact.md`: the `{MCP_SERVER_NAME}` MCP server where "
        "the tool reads `.mcp.json`, or the always-works CLI tier, run from the "
        "repository root\n"
        f"`uv run --project \"{h}\" python \"{h}/tools/graph/impact.py\" --graph-dir "
        f"{Path(GRAPH_OUT).as_posix()} ...`\n"
        "The installed `sdlc-graph` skill/rules file carries the full doctrine."
    )


def block_parts(root: Path, rel: str) -> dict[str, str]:
    """The parts an EARLIER run left in this file's harness block, by heading.

    Read so this run can carry forward what it does not own. Anything outside a
    known heading is dropped deliberately: the block is harness-owned, and the
    user's own text lives outside the markers, where merge_block preserves it."""
    try:
        text = _read(root / rel)
    except FileUnreadableError:
        # Cannot carry forward what cannot be read. This is the first of `_read`'s two
        # doors and it runs BEFORE plan_op, so it must not raise; plan_op reports the
        # could-not-look state when a write is actually attempted, and here we degrade
        # to "nothing prior to carry".
        return {}
    if not text or text.count(BLOCK_BEGIN) != 1 or text.count(BLOCK_END) != 1:
        return {}
    b, e = text.find(BLOCK_BEGIN) + len(BLOCK_BEGIN), text.find(BLOCK_END)
    if e < b:
        return {}
    parts: dict[str, list[str]] = {}
    current: str | None = None
    for line in text[b:e].splitlines():
        if line.strip() in (POINTER_HEADING, GRAPH_HEADING):
            current = line.strip()
            parts[current] = [line.strip()]
        elif current:
            parts[current].append(line)
    return {k: "\n".join(v).strip("\n") for k, v in parts.items()}


def instruction_parts(root: Path, rel: str, pointer_on: bool, addendum: str) -> list[str]:
    """The block this run should write for one instruction file.

    The pointer is CARRIED FORWARD when this run does not own it: the `/sdlc`
    workflow it names is still installed, so deleting the line would remove
    working guidance a previous run put there. The graph section is NOT carried
    forward — its truth is exactly whether a graph exists, which this run
    re-decides, so a stale one would be instructions to nowhere."""
    prior = block_parts(root, rel)
    pointer = SDLC_POINTER if pointer_on else prior.get(POINTER_HEADING, "")
    return [p for p in (pointer, addendum) if p]


# ── file ops ──────────────────────────────────────────────────────────────────
class FileUnreadableError(Exception):
    """A file EXISTS but its bytes could not be read as text - non-UTF-8, or an OS
    error opening it. The THIRD read-state, next to absent (`_read` returns None) and
    damaged (unbalanced markers): a decode error used to escape `_read` as a bare
    traceback, the one document class the installer's reporting layer exists to refuse."""


def _read(path: Path) -> str | None:
    if not path.exists():
        return None
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise FileUnreadableError(str(exc)) from exc


def _norm(s: str) -> str:
    return s.replace("\r\n", "\n").strip("\n")


class BlockMarkerError(Exception):
    """The harness-owned markers in a shared file are unbalanced."""


def merge_block(existing: str | None, block_body: str) -> str:
    """Replace the harness-owned block in a file the user also writes in.

    Refuses to guess when the markers are unbalanced, because "replace everything between
    BEGIN and END" is only safe when there is exactly one of each, in order. The real
    failure: a file with a BEGIN but no END fell through to the append branch, leaving two
    BEGINs and one END; the next run then took the FIRST BEGIN and the ONLY END and deleted
    everything between them — including every line the user had written in between. Silent
    data loss in the file the user is most likely to have edited by hand.
    """
    block = f"{BLOCK_BEGIN}\n\n{block_body}\n\n{BLOCK_END}\n"
    if existing is None:
        return block
    begins, ends = existing.count(BLOCK_BEGIN), existing.count(BLOCK_END)
    if begins == 0 and ends == 0:
        sep = "" if existing.endswith("\n") else "\n"
        return existing + sep + "\n" + block
    b, e = existing.find(BLOCK_BEGIN), existing.find(BLOCK_END)
    if begins != 1 or ends != 1 or e < b:
        raise BlockMarkerError(
            f"unbalanced harness markers ({begins}x BEGIN, {ends}x END"
            f"{', END before BEGIN' if 0 <= e < b else ''}). Refusing to edit this file: "
            f"replacing between mismatched markers would delete your own text. "
            f"Repair the markers by hand — keep exactly one '{BLOCK_BEGIN}' followed by one "
            f"'{BLOCK_END}' — then re-run."
        )
    # The block re-supplies exactly the one newline that ends its own END marker line
    # (`{BLOCK_END}\n`), so drop only that one from the text that followed - never the
    # adopter's blank line beneath it. `.lstrip("\n")` ate every leading newline, taking
    # a blank line the adopter had written to separate the block from their own notes
    # (measured 529 -> 528 bytes); this module's whole promise is that it does not touch
    # what somebody else wrote.
    tail = existing[e + len(BLOCK_END):]
    if tail.startswith("\n"):
        tail = tail[1:]
    return existing[:b] + block + tail


#: Why a planned write was blocked, in the words the file list prints. Five separate
#: sites produce `status == "blocked"` and the report rendered every one of them as
#: *markers unbalanced* - so two scheduled workflows that DO NOT EXIST were reported as
#: having damaged markers, contradicting the installer's own NOTE two lines below.
#: Absent, damaged and could-not-look are this project's most repeated distinction because
#: the repair for each is nothing like the others': you cannot fix markers in a file that
#: was never written, nor in one whose bytes you cannot read. Every blocked op carries its
#: own `cause`; the report reads it rather than assuming, and a producer that forgets one
#: raises instead of borrowing another cause's sentence.
BLOCKED_MARKERS = "markers unbalanced"
#: A file that EXISTS and cannot be decoded (item 117's third read-state). `plan_op`
#: returns this rather than letting `_read`'s decode error escape as a traceback.
BLOCKED_UNREADABLE = "could not read"
BLOCKED_NO_CHECK_GENERATOR = "check generator could not run"
BLOCKED_NO_SNAPSHOT_JOB = "no weekly snapshot to write"
BLOCKED_NO_REPLAY_JOB = "no nightly replay to write"


def plan_op(root: Path, rel: str, new_content: str, *, kind: str = "file", preserve: bool = False):
    """Compute a pending write. Returns dict(path, rel, status, content) or None if unchanged."""
    path = root / rel
    try:
        existing = _read(path)
    except FileUnreadableError as exc:
        # The third read-state: a file that EXISTS and cannot be decoded is neither absent
        # (None, written fresh below) nor damaged (unbalanced markers). Merging into bytes
        # we cannot read would guess at the adopter's own text, so report could-not-look and
        # leave the file alone - item 117, the state that used to escape here as a traceback.
        return {"rel": rel, "status": "blocked", "path": path, "content": None,
                "cause": BLOCKED_UNREADABLE, "reason": str(exc)}
    if kind == "block":
        try:
            final = merge_block(existing, new_content)
        except BlockMarkerError as exc:
            # Skip this one file rather than aborting: the rest of the install is still
            # correct, and the user needs the specific file named to repair it.
            return {"rel": rel, "status": "blocked", "path": path, "content": None,
                    "cause": BLOCKED_MARKERS, "reason": str(exc)}
    elif preserve and existing is not None:
        if _norm(existing) == _norm(new_content):
            return {"rel": rel, "status": "unchanged", "path": path, "content": None}
        # user-edited profile: never clobber — stage alongside
        return {"rel": rel + ".new", "status": "preserved", "path": root / (rel + ".new"), "content": new_content}
    else:
        final = new_content
    if existing is None:
        status = "create"
    elif _norm(existing) == _norm(final):
        return {"rel": rel, "status": "unchanged", "path": path, "content": None}
    else:
        status = "update"
    return {"rel": rel, "status": status, "path": path, "content": final}


def write_lf(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


