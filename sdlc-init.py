# Populated only in a bundled copy (see --bundle). Maps template filename -> base64 body.
_EMBEDDED: dict[str, str] = {}


# ── template loading ──────────────────────────────────────────────────────────
def _template_dir() -> Path:
    return Path(__file__).resolve().parent / "sdlc_templates"


def load_template(name: str) -> str:
    """Prefer the editable sibling file; fall back to an embedded (bundled) copy."""
    p = _template_dir() / name
    if p.exists():
        return p.read_text(encoding="utf-8")
    if name in _EMBEDDED:
        return base64.b64decode(_EMBEDDED[name]).decode("utf-8")
    sys.exit(f"error: template '{name}' not found (no sdlc_templates/ dir and no embedded copy)")


def parse_frontmatter(text: str) -> tuple[dict, str]:
    """Split a leading '---' YAML frontmatter block from the body. Minimal parser."""
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    raw = text[3:end].strip()
    body = text[end + 4:].lstrip("\n")
    meta: dict[str, str] = {}
    for line in raw.splitlines():
        if ":" in line:
            k, _, v = line.partition(":")
            meta[k.strip()] = v.strip()
    return meta, body


# ── detection ─────────────────────────────────────────────────────────────────
def _exists(root: Path, *names: str) -> bool:
    return any((root / n).exists() for n in names)


def detect_stack(root: Path) -> dict:
    """Return profile values inferred from files in the repo root."""
    d = {"coverage_threshold": 90, "build_command": "", "deploy_command": ""}

    # Python
    if _exists(root, "pytest.ini", "pyproject.toml", "setup.cfg", "tox.ini", "requirements.txt", "conftest.py") \
            or next(root.glob("**/test_*.py"), None) or (root / "tests").is_dir():
        lint = ""
        if _exists(root, "ruff.toml", ".ruff.toml") or _pyproject_has(root, "ruff"):
            lint = "ruff check ."
        elif _exists(root, ".flake8") or _cfg_has(root, "flake8"):
            lint = "flake8"
        return {**d, "stack": "python",
                "test_command": "pytest -q",
                "coverage_command": "pytest --cov --cov-report=term-missing",
                "lint_command": lint}

    # JavaScript / TypeScript
    if _exists(root, "package.json"):
        runner = ("pnpm" if _exists(root, "pnpm-lock.yaml")
                  else "yarn" if _exists(root, "yarn.lock") else "npm")
        scripts, deps = _package_json(root)
        test = f"{runner} test" if "test" in scripts else f"{runner} test"
        if "vitest" in deps:
            cov = "npx vitest run --coverage"
        else:  # jest is the common default
            cov = f"{test} -- --coverage" if runner == "npm" else f"{runner} test --coverage"
        lint = f"{runner} run lint" if "lint" in scripts else ""
        return {**d, "stack": "javascript",
                "test_command": test, "coverage_command": cov, "lint_command": lint}

    # Go
    if _exists(root, "go.mod"):
        return {**d, "stack": "go",
                "test_command": "go test ./...",
                "coverage_command": "go test ./... -coverprofile=coverage.out && go tool cover -func=coverage.out",
                "lint_command": "go vet ./..."}

    # Rust
    if _exists(root, "Cargo.toml"):
        return {**d, "stack": "rust",
                "test_command": "cargo test",
                "coverage_command": "cargo tarpaulin --out Stdout",
                "lint_command": "cargo clippy -- -D warnings"}

    # Java / JVM
    if _exists(root, "pom.xml"):
        return {**d, "stack": "java-maven",
                "test_command": "mvn -q test",
                "coverage_command": "mvn -q test jacoco:report",
                "lint_command": ""}
    if _exists(root, "build.gradle", "build.gradle.kts"):
        return {**d, "stack": "java-gradle",
                "test_command": "./gradlew test",
                "coverage_command": "./gradlew test jacocoTestReport",
                "lint_command": ""}

    # .NET / C#
    if list(root.glob("*.sln")) or list(root.glob("*.csproj")) or list(root.glob("*/*.csproj")):
        return {**d, "stack": "dotnet",
                "test_command": "dotnet test",
                "coverage_command": 'dotnet test --collect:"XPlat Code Coverage"',
                "lint_command": "dotnet format --verify-no-changes"}

    # Ruby
    if _exists(root, "Gemfile", ".ruby-version") or list(root.glob("*.gemspec")):
        uses_rspec = _exists(root, ".rspec") or (root / "spec").is_dir()
        test = "bundle exec rspec" if uses_rspec else "bundle exec rake test"
        return {**d, "stack": "ruby",
                "test_command": test,
                "coverage_command": test,          # SimpleCov writes coverage/ when configured
                "lint_command": "bundle exec rubocop" if _exists(root, ".rubocop.yml") else ""}

    # C / C++ (CMake)
    if _exists(root, "CMakeLists.txt"):
        return {**d, "stack": "cpp-cmake",
                "test_command": "ctest --output-on-failure",
                "coverage_command": "ctest -T Coverage",
                "lint_command": ""}

    # Fallback
    return {**d, "stack": "unknown",
            "test_command": "", "coverage_command": "", "lint_command": ""}


def _pyproject_has(root: Path, tool: str) -> bool:
    p = root / "pyproject.toml"
    return p.exists() and f"[tool.{tool}" in p.read_text(encoding="utf-8", errors="ignore")


def _cfg_has(root: Path, section: str) -> bool:
    for name in ("setup.cfg", "tox.ini"):
        p = root / name
        if p.exists() and f"[{section}]" in p.read_text(encoding="utf-8", errors="ignore"):
            return True
    return False


def _package_json(root: Path) -> tuple[dict, set]:
    try:
        data = json.loads((root / "package.json").read_text(encoding="utf-8"))
    except Exception:
        return {}, set()
    deps = set(data.get("dependencies", {})) | set(data.get("devDependencies", {}))
    blob = json.dumps(data.get("scripts", {}))
    for dep in ("vitest", "jest"):
        if dep in blob:
            deps.add(dep)
    return data.get("scripts", {}), deps


_VCS_SCRIPTS = ("checkin-push.sh", "checkin-push.ps1", "checkin.sh", "commit-push.sh",
                "scripts/checkin-push.sh", "scripts/commit-push.sh")


def detect_vcs(root: Path) -> dict:
    """Detect repos where raw git is unsafe and a repo-supplied script must be used instead.

    Signal 1 - extra git dirs (`.git-*` beside `.git`): an open-core / dual-remote layout.
    A plain `git push` can publish to the wrong remote, and `git worktree` carries ONLY
    `.git`, so an isolated worktree silently loses the second repo. Raw git is denied.
    Signal 2 - a repo-level check-in script: wired as the commit command.
    """
    extra_git = sorted(p.name for p in root.glob(".git-*") if p.is_dir())
    script = next((s for s in _VCS_SCRIPTS if (root / s).exists()), "")
    if not extra_git and not script:
        return {"commit_command": "", "push_command": "", "deny_raw_git": False, "notes": ""}

    invoke = ""
    if script:
        invoke = f"./{script}" if not script.endswith(".ps1") else f"powershell -File ./{script}"
    commit = f'{invoke} "{{message}}"' if invoke else ""

    if extra_git:
        return {"commit_command": commit, "push_command": "", "deny_raw_git": True,
                "notes": ("multiple git dirs in one worktree (" + ", ".join([".git"] + extra_git) +
                          ") - a raw push can reach the wrong remote and `git worktree` carries "
                          "only .git" + ("" if commit else "; NO check-in script was found, so ask "
                                         "the user how to commit before Phase 3"))}
    return {"commit_command": commit, "push_command": "", "deny_raw_git": False,
            "notes": f"repo ships {script}; prefer it over raw git commit"}


