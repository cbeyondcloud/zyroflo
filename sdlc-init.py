# ── the harness-rooted commands the skill teaches (item 242) ─────────────────
#: What every `@@HARNESS@@/...` path in SKILL.md is generated FROM. Their absence is
#: the same Tier 0 signal `LEDGER_EMITTER`'s and `GRAPH_BUILDER`'s is, and it used to
#: be the one signal nothing consumed: `--bundle` emits ONE file, so a bundle install
#: rendered `@@HARNESS@@` to the directory that lone file sits in and taught
#: `<that dir>/tools/sdlc/stage.py` -- measured absent by `ls` in the same run that
#: printed the NOTE about `tools/sdlc/validate.py` missing from that very directory.
#: The producer of that knowledge and its consumer were never composed. They are now.
SKILL_COMMAND_SOURCES = (Path("tools") / "sdlc" / "stage.py", Path("sdlc") / "stages")

#: SKILL.md declares its OWN harness-dependent regions; this module keeps no list of
#: them. The first attempt at item 242 removed one named section and left SEVEN other
#: lines teaching `tools/sdlc/stage.py`, `state.py` and `review/loop.py` -- a
#: hand-maintained list of places to strip is exactly the shape that fails, because the
#: eighth taught command added tomorrow is not on it. So the template marks each region
#: and the renderer reads the marks, which makes the standalone rendering DERIVED from
#: the same question `no_harness_commands_reason` asks. `test_bundle_skill_paths.py`
#: pins the other half: no `tools/...` path may live OUTSIDE a marked region.
SKILL_REGION_OPEN = "<!--harness-only-->"
SKILL_REGION_ELSE = "<!--else-->"
SKILL_REGION_CLOSE = "<!--/harness-only-->"


def no_harness_commands_reason(harness: Path | None = None) -> str | None:
    """Why this install can teach no harness-rooted command, or None when it can.

    Split from the doing of it for `no_ledger_gate_reason`'s reason, and asking the
    same question of the same directory: a skill that names a file the run has
    already measured absent is an instruction to nowhere, and the runner who pastes
    it gets *can't open file* and improvises (item 134).
    """
    harness = Path(harness) if harness is not None else harness_root()
    missing = [p.as_posix() for p in SKILL_COMMAND_SOURCES
               if not (harness / p).exists()]
    if not missing:
        return None
    return (f"this is a standalone sdlc-init.py with no {', '.join(missing)} beside "
            f"it, and every command the skill teaches is rooted there")


def resolve_skill_regions(body: str, harness_present: bool) -> str:
    """Keep one branch of every `<!--harness-only-->` region and drop the markers.

    Scanned rather than matched with one regex so an UNCLOSED region is a loud
    ValueError here, in the harness's own tests, instead of a marker shipped literal
    into an adopter's skill -- the class of failure this whole item is about.

    A marker is honoured only ALONE on its line and OUTSIDE a ``` fenced block. The
    three inputs that were once accepted silently are now loud or literal: a marker
    written mid-line is refused by name (it would otherwise ship literal), a second
    `<!--else-->` in one region is refused (it would otherwise merge both tails), and
    a marker inside a fence is left LITERAL so a skill can document its own region
    syntax. This resolver is the single source the whole standalone rendering derives
    from, so a silent wrong answer here is wrong on every surface at once.
    """
    out: list[str] = []
    keeping = True          # outside any region
    in_region = False
    in_fence = False        # inside a ``` code fence: lines are literal, not markers
    seen_else = False       # an <!--else--> already closed the open branch of this region
    for line in body.splitlines(keepends=True):
        token = line.strip()
        if token.startswith("```"):
            in_fence = not in_fence
            if keeping:
                out.append(line)
            continue
        if in_fence:
            if keeping:
                out.append(line)
            continue
        if token == SKILL_REGION_OPEN:
            if in_region:
                raise ValueError("nested <!--harness-only--> region in SKILL.md")
            in_region, keeping, seen_else = True, harness_present, False
            continue
        if token == SKILL_REGION_ELSE:
            if not in_region:
                raise ValueError("<!--else--> outside a <!--harness-only--> region")
            if seen_else:
                raise ValueError(
                    "second <!--else--> in one <!--harness-only--> region in SKILL.md")
            keeping, seen_else = not harness_present, True
            continue
        if token == SKILL_REGION_CLOSE:
            if not in_region:
                raise ValueError("unopened <!--/harness-only--> in SKILL.md")
            in_region, keeping = False, True
            continue
        for marker in (SKILL_REGION_OPEN, SKILL_REGION_ELSE, SKILL_REGION_CLOSE):
            if marker in line:
                raise ValueError(
                    f"{marker} is not alone on its line in SKILL.md -- a region marker "
                    f"must be on its own line, or inside a ``` fence to be documented")
        if keeping:
            out.append(line)
    if in_fence:
        raise ValueError("unclosed ``` code fence in SKILL.md")
    if in_region:
        raise ValueError("unclosed <!--harness-only--> region in SKILL.md")
    return "".join(out)


def render_skill_body(body: str, harness: Path | None = None) -> tuple[str, str | None]:
    """(rendered SKILL.md body, why commands were omitted or None).

    Called ONCE, above the six-tool fan-out, so every surface that carries this body
    carries the same decision -- the alternative is six surfaces disagreeing about
    whether a command exists. The decision itself is ONE boolean, asked once, and both
    the region resolution and the printed NOTE are derived from it.
    """
    harness = Path(harness) if harness is not None else harness_root()
    reason = no_harness_commands_reason(harness)
    body = resolve_skill_regions(body, harness_present=reason is None)
    if reason is not None:
        # Deliberately NOT filled. Every `@@HARNESS@@` lives inside a region, so one
        # surviving here means the template grew a harness path outside them -- and
        # filling it would write this machine's layout into somebody else's repository,
        # which is the defect. Left literal so install()'s check refuses the run.
        return body, reason
    return body.replace("@@HARNESS@@", harness.as_posix()), None


# ── the CI ledger gate (item 44) ──────────────────────────────────────────────
#: The emitter of the self-contained ledger check, relative to this script inside a
#: harness clone. Its ABSENCE is the same Tier 0 signal `GRAPH_BUILDER`'s is: a standalone
#: sdlc-init.py has no `tools/` to generate from, and must say so rather than install a
#: workflow that runs a file it could not produce.
LEDGER_EMITTER = Path("tools") / "sdlc" / "validate.py"
LEDGER_CHECK_REL = ".sdlc/ledger_check.py"
LEDGER_WORKFLOW_REL = ".github/workflows/sdlc-ledger.yml"


def no_ledger_gate_reason(root: Path, harness: Path | None = None) -> str | None:
    """Why this install ships no CI ledger gate, or None when it does.

    Split from the doing of it for `no_chain_reason`'s reason: a dry run has to be able
    to report the same decision, and a gate that silently fails to install is the exact
    shape of failure this repository keeps finding in its own tools.
    """
    harness = Path(harness) if harness is not None else harness_root()
    if not (harness / LEDGER_EMITTER).is_file():
        return (f"this is a standalone sdlc-init.py with no {LEDGER_EMITTER.as_posix()} "
                f"beside it, and the check is generated from that source")
    if not (root / ".github").is_dir():
        return f"{root} has no .github/ - the gate is a GitHub Actions workflow"
    return None


def ledger_gate_ops(root: Path, harness: Path | None = None) -> list[dict]:
    """The two files that make a tampered ledger unmergeable: the self-contained check,
    and the workflow that runs it on every pull request.

    The check is produced by SPAWNING the harness's own emitter, never by re-implementing
    it here. This file may not import `tools/` — that is the constraint keeping Tier 0
    dependency-free — but it may ask `tools/` to speak for itself, and one owner of the
    bundle format is the only version of this that cannot drift.
    """
    harness = Path(harness) if harness is not None else harness_root()
    emitter = harness / LEDGER_EMITTER

    def blocked(reason: str) -> list[dict]:
        return [{"rel": LEDGER_CHECK_REL, "status": "blocked",
                 "path": root / LEDGER_CHECK_REL, "content": None,
                 "cause": BLOCKED_NO_CHECK_GENERATOR, "reason": reason}]

    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "ledger_check.py"
        try:
            proc = subprocess.run([sys.executable, str(emitter), "--emit-check", str(out)],
                                  capture_output=True, text=True, encoding="utf-8",
                                  errors="replace", timeout=120)
        except (OSError, subprocess.TimeoutExpired) as exc:
            return blocked(f"could not run {emitter}: {exc}")
        if proc.returncode != 0 or not out.is_file():
            detail = (proc.stderr or proc.stdout or "").strip().splitlines()
            return blocked(f"{emitter.name} --emit-check exited {proc.returncode}"
                           + (f": {detail[-1]}" if detail else ""))
        body = out.read_text(encoding="utf-8")
    return [plan_op(root, LEDGER_CHECK_REL, body),
            plan_op(root, LEDGER_WORKFLOW_REL, load_template("ledger-check.yml"))]


