#: The committed picture of the pipeline this install resolves to, and the harness
#: tool that draws it. Generated by SPAWNING `stage.py --diagram mermaid`, for the
#: ledger emitter's reason: this file may not import `tools/`, and one renderer is
#: the only version of the picture that cannot drift from `stage.py --list`.
PIPELINE_DIAGRAM_REL = ".sdlc/pipeline.md"
PIPELINE_RENDERER = Path("tools") / "sdlc" / "stage.py"


def no_pipeline_diagram_reason(harness: Path | None = None) -> str | None:
    """Why this install writes no pipeline diagram, or None when it does."""
    harness = Path(harness) if harness is not None else harness_root()
    if not (harness / PIPELINE_RENDERER).is_file():
        return (f"this is a standalone sdlc-init.py with no "
                f"{PIPELINE_RENDERER.as_posix()} beside it, and the diagram is drawn "
                f"by that tool")
    return None


def write_pipeline_diagram(root: Path, harness: Path | None = None) -> str:
    """Draw `.sdlc/pipeline.md` for the installed repository; the line to print.

    Run LAST - after every file is written and the graph build has had its turn -
    because the pipeline depends on both: `profile.yml` selects the steps, and a
    graph that now exists turns `scoping` on. A diagram planned before the build
    would be stale the moment the build succeeded, and `--check` would say so.
    Never fatal: the install is usable without the picture, and a failure is
    printed with its reason rather than swallowed.
    """
    harness = Path(harness) if harness is not None else harness_root()
    if reason := no_pipeline_diagram_reason(harness):
        return f"    {'- skipped':<38} {PIPELINE_DIAGRAM_REL} ({reason})"
    path = root / PIPELINE_DIAGRAM_REL
    try:
        before = path.read_bytes() if path.is_file() else None
    except OSError:
        before = b""
    try:
        proc = subprocess.run(
            [sys.executable, str(harness / PIPELINE_RENDERER), "--target", str(root),
             "--diagram", "mermaid"],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
            timeout=120)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return (f"    {'x BLOCKED (diagram could not be drawn)':<38} "
                f"{PIPELINE_DIAGRAM_REL}: {exc}")
    if proc.returncode != 0:
        detail = (proc.stdout or proc.stderr or "").strip().splitlines()
        return (f"    {'x BLOCKED (diagram could not be drawn)':<38} "
                f"{PIPELINE_DIAGRAM_REL}: {PIPELINE_RENDERER.name} exited "
                f"{proc.returncode}" + (f": {detail[-1]}" if detail else ""))
    # Read back as guardedly as before it was drawn (T568): the renderer writes in
    # place, so a file that can be written but not read stays that way, and an
    # unguarded read was a traceback at exit 1 after everything else was installed.
    try:
        after = path.read_bytes() if path.is_file() else None
    except OSError as exc:
        return (f"    {'! drawn, not read back':<38} {PIPELINE_DIAGRAM_REL}: written, "
                f"but it could not be read back ({exc.strerror or exc}), so whether it "
                f"changed is unknown")
    # The file list's own vocabulary, so the diagram reads like every other file.
    mark = ("+ create" if before is None
            else "= unchanged" if before == after else "~ update")
    return f"    {mark:<38} {PIPELINE_DIAGRAM_REL}"


