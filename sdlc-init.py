def do_bundle(out: Path) -> int:
    """Emit a single self-contained script with templates base64-embedded."""
    src = Path(__file__).resolve().read_text(encoding="utf-8")
    names = _loaded_template_names(src)
    emb = {name: base64.b64encode(load_template(name).encode("utf-8")).decode("ascii")
           for name in names}
    literal = "_EMBEDDED: dict[str, str] = " + json.dumps(emb, indent=0) + "\n"
    new_src, n = re.subn(r"^_EMBEDDED: dict\[str, str\] = \{\}\s*$", literal, src, count=1, flags=re.M)
    if n != 1:
        sys.exit("error: could not locate _EMBEDDED placeholder to bundle")
    write_lf(out, new_src)
    print(f"Wrote self-contained bundle -> {out} ({len(names)} templates embedded).")
    return 0


def do_dump_templates(dest: Path) -> int:
    names = _loaded_template_names()
    for name in names:
        write_lf(dest / name, load_template(name))
    print(f"Wrote {len(names)} templates -> {dest}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Install the portable SDLC harness into a repo.",
        epilog="exit status: 0 = scaffold written (graph built, skipped, or honestly "
               "absent); 3 = scaffold written but the chained graph build failed; "
               "4 = the scaffold is incomplete: a file could not be written after "
               "others were, and each is named; 1 = nothing was installed (bad input, "
               "or a file it must write cannot be written); 2 = bad command line.")
    ap.add_argument("--target", default=".", help="target repo root (default: current dir)")
    ap.add_argument("--workspace", metavar="TOML",
                    help="install for a multi-component workspace described by a filled-in "
                         "sdlc-workspace.toml (see sdlc_templates/workspace.example.toml). "
                         "Supplies WHICH components exist; --target still says where the "
                         "harness config is written")
    ap.add_argument("--tools", default="auto",
                    help="comma list of tools, 'auto' (detect), or 'all'")
    ap.add_argument("--force", action="store_true", help="overwrite an edited .sdlc/profile.yml")
    ap.add_argument("--single-component", action="store_true",
                    help="install a repository built from several units as ONE "
                         "component anyway; the assertion is recorded in the profile")
    ap.add_argument("--claude-extras", action="store_true",
                    help="also install the Claude Code layer: reviewer subagents, a scoped "
                         "permission allowlist, and automation hooks")
    ap.add_argument("--estate", action="store_true",
                    help="with --workspace: verify vendored binaries, report Neo4j "
                         "readiness and the attach census, and chain the workspace "
                         "graph build into <target>/.sdlc/graph (item 15). The "
                         "single-repo path is untouched")
    ap.add_argument("--from-snapshot", action="store_true",
                    help="with --estate: load the components' published snapshot "
                         "shards instead of building from source; the builder rules "
                         "on shard completeness")
    ap.add_argument(FLAG_SNAPSHOT_CADENCE, action="store_true",
                    help="write a weekly graph-snapshot workflow; without it none "
                         "is written, because a scheduled build on a repository "
                         "that cannot build one reddens every week")
    ap.add_argument(FLAG_CORPUS_REPLAY, action="store_true",
                    help="write a nightly corpus-replay workflow; without it "
                         "none is written, because a scheduled job on a "
                         "repository with no corpus reddens every night")
    ap.add_argument("--no-graph", action="store_true",
                    help="scaffold only. Without it, an install at a repository root also "
                         "builds that repository's graph into .sdlc/graph when the harness "
                         "environment is present")
    ap.add_argument("--dry-run", action="store_true", help="show planned writes, change nothing")
    ap.add_argument("--bundle", metavar="OUT", help="emit a single self-contained script and exit")
    ap.add_argument("--dump-templates", metavar="DIR", help="write embedded templates to DIR and exit")
    args = ap.parse_args(argv)

    if args.bundle:
        return do_bundle(Path(args.bundle))
    if args.dump_templates:
        return do_dump_templates(Path(args.dump_templates))

    root = Path(args.target).resolve()
    if not root.is_dir():
        sys.exit(f"error: target is not a directory: {root}")
    if not (root / ".git").exists() and not args.workspace:
        print(f"warning: {root} has no .git - per-row commits & rollback will be unavailable.")

    if args.estate and not args.workspace:
        sys.exit("error: --estate needs --workspace <toml> - estate mode is ABOUT a "
                 "declared workspace; for one repository the default path already "
                 "chains its build.")
    if args.from_snapshot and not args.estate:
        sys.exit("error: --from-snapshot only means something with --estate (it picks "
                 "how the chained workspace build gets its facts).")

    workspace = None
    if args.workspace:
        # A workspace config that cannot be trusted must not produce a half-right
        # component list, so every failure in here is fatal and prints as a message
        # rather than a traceback — the developer wrote this file, and a stack trace
        # blames the harness for their typo.
        try:
            workspace = read_workspace(Path(args.workspace))
        except WorkspaceError as exc:
            sys.exit(f"error: {exc}")

    if args.tools == "auto":
        tools = detect_tools(root)
    elif args.tools == "all":
        tools = ALL_TOOLS
    else:
        tools = [t.strip() for t in args.tools.split(",") if t.strip()]
        # Refuse an explicitly empty list BY NAME. An empty/whitespace/all-separator
        # --tools ("", " ", ",,,") parsed to [] and the `claude` insert below then
        # REPAIRED it to ["claude"] at exit 0 - so a caller who asked for no tools was
        # silently handed one. Naming the flag and defaulting nothing is the honest
        # answer: 'auto' detects, 'all' installs everything, and a list must list.
        if not tools:
            sys.exit(f"error: --tools {args.tools!r} names no tools - pass a comma list "
                     f"of {', '.join(ALL_TOOLS)}, or 'auto' to detect / 'all' for every "
                     f"one. An empty list is refused, not defaulted to claude.")
        if "claude" not in tools:
            tools.insert(0, "claude")
        # T516: a name given twice means that tool once. Two entries planned two ops
        # on one file, and the fan-out's own guard against that reached the person
        # as a traceback at exit 1.
        tools = list(dict.fromkeys(tools))
        bad = [t for t in tools if t not in ALL_TOOLS]
        if bad:
            sys.exit(f"error: unknown tool(s): {', '.join(bad)} (valid: {', '.join(ALL_TOOLS)})")

    try:
        return install(root, tools, force=args.force, dry_run=args.dry_run,
                       claude_extras=args.claude_extras, workspace=workspace,
                       graph=not args.no_graph, estate=args.estate,
                       workspace_path=Path(args.workspace) if args.workspace else None,
                       from_snapshot=args.from_snapshot,
                       single_component=args.single_component,
                       corpus_replay=args.corpus_replay,
                       snapshot_cadence=args.snapshot_cadence)
    except WorkspaceError as exc:
        sys.exit(f"error: {exc}")


if __name__ == "__main__":
    raise SystemExit(main())
