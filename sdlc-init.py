#!/usr/bin/env python3
"""
sdlc-init.py — Drop-in installer for the portable SDLC harness.

Run at the root of ANY repository and it scaffolds a generic, provider-agnostic,
tool-agnostic SDLC workflow: a Claude Code /sdlc skill plus tool-native rule files
for every AI coding tool it detects, all driven by an auto-detected .sdlc/profile.yml.

    python /path/to/sdlc-init.py                 # install into the current directory
    python /path/to/sdlc-init.py --target ../app # install into another repo
    python /path/to/sdlc-init.py --dry-run       # show what would be written
    python /path/to/sdlc-init.py --tools claude,cursor
    python /path/to/sdlc-init.py --force         # overwrite an edited profile.yml
    python /path/to/sdlc-init.py --bundle sdlc-init.bundled.py   # emit a single self-contained file

Stdlib only. No network. No API keys. Free and OSS.
Templates are read from the sibling ./sdlc_templates/ dir; a bundled copy falls back
to base64 templates embedded at the bottom of the file.
"""
from __future__ import annotations

import argparse
import base64
import json
import re
import sys
from datetime import date
from pathlib import Path

# Console output stays ASCII, but reconfigure to UTF-8 anyway so paths with
# non-ASCII characters never crash on a Windows cp1252 terminal.
for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[union-attr]
    except Exception:
        pass

TEMPLATE_FILES = ["SKILL.md", "review-rubric.md", "plan-template.md", "profile.yml"]
# Optional Claude Code power layer (installed only with --claude-extras).
EXTRA_TEMPLATE_FILES = ["agents/sdlc-reviewer.md", "agents/sdlc-security.md",
                        "hooks/sdlc-autolint.py", "hooks/sdlc-session-start.py"]
ALL_TOOLS = ["claude", "cursor", "windsurf", "copilot", "gemini", "aider"]

BLOCK_BEGIN = "<!-- BEGIN SDLC-HARNESS (auto-generated by sdlc-init.py — do not edit inside) -->"
BLOCK_END = "<!-- END SDLC-HARNESS -->"

# Populated only in a bundled copy (see --bundle). Maps template filename -> base64 body.
_EMBEDDED: dict[str, str] = {}


# ── template loading ──────────────────────────────────────────────────────────
def _template_dir() -> Path:
    return Path(__file__).resolve().parent / "sdlc_templates"


def load_template(name: str) -> str:
    """Prefer the editable sibling file; fall back to an embedded (bundled) copy."""
    p = _template_dir() / name
    if p.exists():
        return p.read_text(encoding="utf-8")
    if name in _EMBEDDED:
        return base64.b64decode(_EMBEDDED[name]).decode("utf-8")
    sys.exit(f"error: template '{name}' not found (no sdlc_templates/ dir and no embedded copy)")


def parse_frontmatter(text: str) -> tuple[dict, str]:
    """Split a leading '---' YAML frontmatter block from the body. Minimal parser."""
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    raw = text[3:end].strip()
    body = text[end + 4:].lstrip("\n")
    meta: dict[str, str] = {}
    for line in raw.splitlines():
        if ":" in line:
            k, _, v = line.partition(":")
            meta[k.strip()] = v.strip()
    return meta, body


# ── detection ─────────────────────────────────────────────────────────────────
def _exists(root: Path, *names: str) -> bool:
    return any((root / n).exists() for n in names)


def detect_stack(root: Path) -> dict:
    """Return profile values inferred from files in the repo root."""
    d = {"coverage_threshold": 90, "build_command": "", "deploy_command": ""}

    # Python
    if _exists(root, "pytest.ini", "pyproject.toml", "setup.cfg", "tox.ini", "requirements.txt", "conftest.py") \
            or list(root.glob("**/test_*.py"))[:1] or (root / "tests").is_dir():
        lint = ""
        if _exists(root, "ruff.toml", ".ruff.toml") or _pyproject_has(root, "ruff"):
            lint = "ruff check ."
        elif _exists(root, ".flake8") or _cfg_has(root, "flake8"):
            lint = "flake8"
        return {**d, "stack": "python",
                "test_command": "pytest -q",
                "coverage_command": "pytest --cov --cov-report=term-missing",
                "lint_command": lint}

    # JavaScript / TypeScript
    if _exists(root, "package.json"):
        runner = ("pnpm" if _exists(root, "pnpm-lock.yaml")
                  else "yarn" if _exists(root, "yarn.lock") else "npm")
        scripts, deps = _package_json(root)
        test = f"{runner} test" if "test" in scripts else f"{runner} test"
        if "vitest" in deps:
            cov = "npx vitest run --coverage"
        else:  # jest is the common default
            cov = f"{test} -- --coverage" if runner == "npm" else f"{runner} test --coverage"
        lint = f"{runner} run lint" if "lint" in scripts else ""
        return {**d, "stack": "javascript",
                "test_command": test, "coverage_command": cov, "lint_command": lint}

    # Go
    if _exists(root, "go.mod"):
        return {**d, "stack": "go",
                "test_command": "go test ./...",
                "coverage_command": "go test ./... -coverprofile=coverage.out && go tool cover -func=coverage.out",
                "lint_command": "go vet ./..."}

    # Rust
    if _exists(root, "Cargo.toml"):
        return {**d, "stack": "rust",
                "test_command": "cargo test",
                "coverage_command": "cargo tarpaulin --out Stdout",
                "lint_command": "cargo clippy -- -D warnings"}

    # Java / JVM
    if _exists(root, "pom.xml"):
        return {**d, "stack": "java-maven",
                "test_command": "mvn -q test",
                "coverage_command": "mvn -q test jacoco:report",
                "lint_command": ""}
    if _exists(root, "build.gradle", "build.gradle.kts"):
        return {**d, "stack": "java-gradle",
                "test_command": "./gradlew test",
                "coverage_command": "./gradlew test jacocoTestReport",
                "lint_command": ""}

    # .NET / C#
    if list(root.glob("*.sln")) or list(root.glob("*.csproj")) or list(root.glob("*/*.csproj")):
        return {**d, "stack": "dotnet",
                "test_command": "dotnet test",
                "coverage_command": 'dotnet test --collect:"XPlat Code Coverage"',
                "lint_command": "dotnet format --verify-no-changes"}

    # Ruby
    if _exists(root, "Gemfile", ".ruby-version") or list(root.glob("*.gemspec")):
        uses_rspec = _exists(root, ".rspec") or (root / "spec").is_dir()
        test = "bundle exec rspec" if uses_rspec else "bundle exec rake test"
        return {**d, "stack": "ruby",
                "test_command": test,
                "coverage_command": test,          # SimpleCov writes coverage/ when configured
                "lint_command": "bundle exec rubocop" if _exists(root, ".rubocop.yml") else ""}

    # C / C++ (CMake)
    if _exists(root, "CMakeLists.txt"):
        return {**d, "stack": "cpp-cmake",
                "test_command": "ctest --output-on-failure",
                "coverage_command": "ctest -T Coverage",
                "lint_command": ""}

    # Fallback
    return {**d, "stack": "unknown",
            "test_command": "", "coverage_command": "", "lint_command": ""}


def _pyproject_has(root: Path, tool: str) -> bool:
    p = root / "pyproject.toml"
    return p.exists() and f"[tool.{tool}" in p.read_text(encoding="utf-8", errors="ignore")


def _cfg_has(root: Path, section: str) -> bool:
    for name in ("setup.cfg", "tox.ini"):
        p = root / name
        if p.exists() and f"[{section}]" in p.read_text(encoding="utf-8", errors="ignore"):
            return True
    return False


def _package_json(root: Path) -> tuple[dict, set]:
    try:
        data = json.loads((root / "package.json").read_text(encoding="utf-8"))
    except Exception:
        return {}, set()
    deps = set(data.get("dependencies", {})) | set(data.get("devDependencies", {}))
    blob = json.dumps(data.get("scripts", {}))
    for dep in ("vitest", "jest"):
        if dep in blob:
            deps.add(dep)
    return data.get("scripts", {}), deps


def detect_tools(root: Path) -> list[str]:
    tools = ["claude"]  # baseline — Claude Code is always wired
    if (root / ".cursor").exists():
        tools.append("cursor")
    if (root / ".windsurf").exists():
        tools.append("windsurf")
    if (root / ".github").exists():
        tools.append("copilot")
    if (root / "GEMINI.md").exists():
        tools.append("gemini")
    if (root / "CONVENTIONS.md").exists() or list(root.glob(".aider*")):
        tools.append("aider")
    return tools


# ── rendering ─────────────────────────────────────────────────────────────────
def _yaml_dq(v: str) -> str:
    """Escape a value for a double-quoted YAML scalar (commands may contain quotes)."""
    return v.replace("\\", "\\\\").replace('"', '\\"')


def render_profile(profile: dict, tools: list[str]) -> str:
    tpl = load_template("profile.yml")
    # Command values land inside double-quoted YAML slots -> must be escaped so a
    # value like  dotnet test --collect:"XPlat Code Coverage"  stays valid YAML.
    repl = {
        "@@GENERATED_AT@@": date.today().isoformat(),
        "@@STACK@@": profile["stack"],
        "@@TEST_COMMAND@@": _yaml_dq(profile["test_command"]),
        "@@COVERAGE_COMMAND@@": _yaml_dq(profile["coverage_command"]),
        "@@COVERAGE_THRESHOLD@@": str(profile["coverage_threshold"]),
        "@@LINT_COMMAND@@": _yaml_dq(profile["lint_command"]),
        "@@BUILD_COMMAND@@": _yaml_dq(profile["build_command"]),
        "@@DEPLOY_COMMAND@@": _yaml_dq(profile["deploy_command"]),
        "@@TOOLS@@": ", ".join(tools),
    }
    for k, v in repl.items():
        tpl = tpl.replace(k, v)
    return tpl


def tool_files(tool: str, skill_body: str, description: str) -> list[tuple[str, str, str]]:
    """Return [(relative_path, content, kind)] for one tool. kind: 'file' or 'block'."""
    if tool == "claude":
        full = f"---\nname: sdlc\ndescription: {description}\n---\n\n{skill_body}"
        return [(".claude/skills/sdlc/SKILL.md", full, "file")]
    if tool == "cursor":
        fm = f"---\ndescription: {description}\nalwaysApply: false\n---\n\n"
        return [(".cursor/rules/sdlc.mdc", fm + skill_body, "file")]
    if tool == "windsurf":
        fm = f"---\ndescription: {description}\n---\n\n"
        return [(".windsurf/rules/sdlc.md", fm + skill_body, "file")]
    if tool == "copilot":
        return [(".github/copilot-instructions.md", skill_body, "block")]
    if tool == "gemini":
        return [("GEMINI.md", skill_body, "block")]
    if tool == "aider":
        return [("CONVENTIONS.md", skill_body, "block")]
    return []


# ── file ops ──────────────────────────────────────────────────────────────────
def _read(path: Path) -> str | None:
    if not path.exists():
        return None
    return path.read_text(encoding="utf-8")


def _norm(s: str) -> str:
    return s.replace("\r\n", "\n").strip("\n")


def merge_block(existing: str | None, block_body: str) -> str:
    block = f"{BLOCK_BEGIN}\n\n{block_body}\n\n{BLOCK_END}\n"
    if existing is None:
        return block
    if BLOCK_BEGIN in existing and BLOCK_END in existing:
        pre = existing[: existing.index(BLOCK_BEGIN)]
        post = existing[existing.index(BLOCK_END) + len(BLOCK_END):]
        return pre + block + post.lstrip("\n")
    sep = "" if existing.endswith("\n") else "\n"
    return existing + sep + "\n" + block


def plan_op(root: Path, rel: str, new_content: str, *, kind: str = "file", preserve: bool = False):
    """Compute a pending write. Returns dict(path, rel, status, content) or None if unchanged."""
    path = root / rel
    existing = _read(path)
    if kind == "block":
        final = merge_block(existing, new_content)
    elif preserve and existing is not None:
        if _norm(existing) == _norm(new_content):
            return {"rel": rel, "status": "unchanged", "path": path, "content": None}
        # user-edited profile: never clobber — stage alongside
        return {"rel": rel + ".new", "status": "preserved", "path": root / (rel + ".new"), "content": new_content}
    else:
        final = new_content
    if existing is None:
        status = "create"
    elif _norm(existing) == _norm(final):
        return {"rel": rel, "status": "unchanged", "path": path, "content": None}
    else:
        status = "update"
    return {"rel": rel, "status": status, "path": path, "content": final}


def write_lf(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


# ── optional Claude Code power layer (--claude-extras) ─────────────────────────
def build_settings(profile: dict, existing: dict | None) -> dict:
    """Merge a conservative permission allowlist + harness hooks into settings.json.

    Allows exactly the profile's test/coverage/lint/build binaries and the safe, local git
    the harness needs; denies destructive ops. Never clobbers existing settings keys.
    """
    allow = set()
    for key in ("test_command", "coverage_command", "lint_command", "build_command"):
        cmd = profile.get(key, "").strip()
        if cmd:
            allow.add(f"Bash({cmd.split()[0]}:*)")
    for g in ("git status", "git diff", "git log", "git show", "git branch", "git rev-parse",
              "git add", "git commit", "git checkout -b", "git switch", "git worktree", "git stash"):
        allow.add(f"Bash({g}:*)")
    deny = {"Bash(git push --force:*)", "Bash(git push --force-with-lease:*)",
            "Bash(git reset --hard:*)", "Bash(git clean -f:*)", "Bash(rm -rf:*)"}

    settings = dict(existing or {})
    perms = dict(settings.get("permissions", {}))
    perms["allow"] = sorted(set(perms.get("allow", [])) | allow)
    perms["deny"] = sorted(set(perms.get("deny", [])) | deny)
    settings["permissions"] = perms

    hooks = dict(settings.get("hooks", {}))
    autolint = {"matcher": "Edit|Write", "hooks": [{"type": "command",
                "command": 'python "$CLAUDE_PROJECT_DIR/.claude/hooks/sdlc-autolint.py"'}]}
    session = {"hooks": [{"type": "command",
               "command": 'python "$CLAUDE_PROJECT_DIR/.claude/hooks/sdlc-session-start.py"'}]}
    post = list(hooks.get("PostToolUse", []))
    if not any("sdlc-autolint" in json.dumps(h) for h in post):
        post.append(autolint)
    hooks["PostToolUse"] = post
    start = list(hooks.get("SessionStart", []))
    if not any("sdlc-session-start" in json.dumps(h) for h in start):
        start.append(session)
    hooks["SessionStart"] = start
    settings["hooks"] = hooks
    return settings


def claude_extras_ops(root: Path, profile: dict) -> list[dict]:
    """plan_ops for the optional Claude layer: subagents, hook scripts, settings.json, pointer."""
    ops = [plan_op(root, f".claude/{name}", load_template(name)) for name in EXTRA_TEMPLATE_FILES]

    existing = None
    sp = root / ".claude" / "settings.json"
    if sp.exists():
        try:
            existing = json.loads(sp.read_text(encoding="utf-8"))
        except Exception:
            existing = None  # unparseable -> overwrite with a clean merged file
    merged = build_settings(profile, existing)
    ops.append(plan_op(root, ".claude/settings.json", json.dumps(merged, indent=2) + "\n"))

    pointer = ("## SDLC workflow (harness)\n\n"
               "For any bug fix or feature, run the SDLC harness rather than ad-hoc edits:\n"
               "`/sdlc <task>` (or \"follow the sdlc workflow for: <task>\"). It reads "
               "`.sdlc/profile.yml` and walks 10 phases with two human approval gates; resume an "
               "interrupted run with `/sdlc resume`.")
    ops.append(plan_op(root, "CLAUDE.md", pointer, kind="block"))
    if (root / "AGENTS.md").exists():
        ops.append(plan_op(root, "AGENTS.md", pointer, kind="block"))
    return ops


# ── main install ──────────────────────────────────────────────────────────────
def install(root: Path, tools: list[str], force: bool, dry_run: bool,
            claude_extras: bool = False) -> int:
    skill_meta, skill_body = parse_frontmatter(load_template("SKILL.md"))
    description = skill_meta.get("description", "Run the full SDLC for a bug fix or feature.")
    profile = detect_stack(root)

    ops: list[dict] = []
    # Shared harness data (.sdlc/)
    ops.append(plan_op(root, ".sdlc/profile.yml", render_profile(profile, tools),
                       preserve=not force))
    ops.append(plan_op(root, ".sdlc/review-rubric.md", load_template("review-rubric.md")))
    ops.append(plan_op(root, ".sdlc/plan-template.md", load_template("plan-template.md")))
    ops.append(plan_op(root, ".sdlc/plans/.gitkeep", ""))
    # Per-tool entry points
    for tool in tools:
        for rel, content, kind in tool_files(tool, skill_body, description):
            ops.append(plan_op(root, rel, content, kind=kind))
    # Optional Claude Code power layer
    extras_skipped = claude_extras and "claude" not in tools
    if claude_extras and "claude" in tools:
        ops.extend(claude_extras_ops(root, profile))

    # Report + execute
    print(f"SDLC harness -> {root}")
    print(f"  stack detected : {profile['stack']}")
    print(f"  test command   : {profile['test_command'] or '(none - edit .sdlc/profile.yml)'}")
    print(f"  tools          : {', '.join(tools)}")
    print(f"  claude extras  : {'on' if (claude_extras and not extras_skipped) else 'off'}")
    print("  files:")
    changed = 0
    for op in ops:
        mark = {"create": "+ create", "update": "~ update", "unchanged": "= unchanged",
                "preserved": "! preserved (edited -> wrote .new)"}[op["status"]]
        print(f"    {mark:<38} {op['rel']}")
        if op["status"] != "unchanged":
            changed += 1
            if not dry_run:
                write_lf(op["path"], op["content"])

    if profile["stack"] == "unknown":
        print("\n  NOTE: stack not recognised - .sdlc/profile.yml has blank commands; fill them in before running /sdlc.")
    if any(op["status"] == "preserved" for op in ops):
        print("\n  NOTE: your edited .sdlc/profile.yml was kept; the new version is at .sdlc/profile.yml.new (diff & merge, or re-run with --force).")
    if extras_skipped:
        print("\n  NOTE: --claude-extras ignored (Claude Code is not in the tool set).")

    if dry_run:
        print(f"\n[dry-run] {changed} file(s) would change. Nothing written.")
        return 0

    print(f"\nDone. {changed} file(s) written.")
    if claude_extras and not extras_skipped:
        print("Claude extras: subagents + auto-lint/session hooks + a scoped permission allowlist"
              " were installed (settings.json merged, not clobbered).")
    elif "claude" in tools:
        print("Tip: add --claude-extras for reviewer subagents, a no-prompt permission allowlist,"
              " and automation hooks (Claude Code only).")
    print("Next: open this repo in an AI coding tool and run  /sdlc <your bug or feature>")
    print("      (or 'follow the sdlc workflow for: <task>' in tools without slash commands).")
    return 0


# ── extras ────────────────────────────────────────────────────────────────────
def do_bundle(out: Path) -> int:
    """Emit a single self-contained script with templates base64-embedded."""
    src = Path(__file__).resolve().read_text(encoding="utf-8")
    names = TEMPLATE_FILES + EXTRA_TEMPLATE_FILES
    emb = {name: base64.b64encode(load_template(name).encode("utf-8")).decode("ascii")
           for name in names}
    literal = "_EMBEDDED: dict[str, str] = " + json.dumps(emb, indent=0) + "\n"
    new_src, n = re.subn(r"^_EMBEDDED: dict\[str, str\] = \{\}\s*$", literal, src, count=1, flags=re.M)
    if n != 1:
        sys.exit("error: could not locate _EMBEDDED placeholder to bundle")
    write_lf(out, new_src)
    print(f"Wrote self-contained bundle -> {out} ({len(names)} templates embedded).")
    return 0


def do_dump_templates(dest: Path) -> int:
    names = TEMPLATE_FILES + EXTRA_TEMPLATE_FILES
    for name in names:
        write_lf(dest / name, load_template(name))
    print(f"Wrote {len(names)} templates -> {dest}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Install the portable SDLC harness into a repo.")
    ap.add_argument("--target", default=".", help="target repo root (default: current dir)")
    ap.add_argument("--tools", default="auto",
                    help="comma list of tools, 'auto' (detect), or 'all'")
    ap.add_argument("--force", action="store_true", help="overwrite an edited .sdlc/profile.yml")
    ap.add_argument("--claude-extras", action="store_true",
                    help="also install the Claude Code layer: reviewer subagents, a scoped "
                         "permission allowlist, and automation hooks")
    ap.add_argument("--dry-run", action="store_true", help="show planned writes, change nothing")
    ap.add_argument("--bundle", metavar="OUT", help="emit a single self-contained script and exit")
    ap.add_argument("--dump-templates", metavar="DIR", help="write embedded templates to DIR and exit")
    args = ap.parse_args(argv)

    if args.bundle:
        return do_bundle(Path(args.bundle))
    if args.dump_templates:
        return do_dump_templates(Path(args.dump_templates))

    root = Path(args.target).resolve()
    if not root.is_dir():
        sys.exit(f"error: target is not a directory: {root}")
    if not (root / ".git").exists():
        print(f"warning: {root} has no .git - per-row commits & rollback will be unavailable.")

    if args.tools == "auto":
        tools = detect_tools(root)
    elif args.tools == "all":
        tools = ALL_TOOLS
    else:
        tools = [t.strip() for t in args.tools.split(",") if t.strip()]
        if "claude" not in tools:
            tools.insert(0, "claude")
        bad = [t for t in tools if t not in ALL_TOOLS]
        if bad:
            sys.exit(f"error: unknown tool(s): {', '.join(bad)} (valid: {', '.join(ALL_TOOLS)})")

    return install(root, tools, force=args.force, dry_run=args.dry_run,
                   claude_extras=args.claude_extras)


if __name__ == "__main__":
    raise SystemExit(main())
