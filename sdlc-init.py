#!/usr/bin/env python3
"""
sdlc-init.py — Drop-in installer for the portable SDLC harness.

Run at the root of ANY repository and it scaffolds a generic, provider-agnostic,
tool-agnostic SDLC workflow: a Claude Code /sdlc skill plus tool-native rule files
for every AI coding tool it detects, all driven by an auto-detected .sdlc/profile.yml.

    python /path/to/sdlc-init.py                 # install into the current directory
    python /path/to/sdlc-init.py --target ../app # install into another repo
    python /path/to/sdlc-init.py --dry-run       # show what would be written
    python /path/to/sdlc-init.py --tools claude,cursor
    python /path/to/sdlc-init.py --force         # overwrite an edited profile.yml
    python sdlc-init.py --workspace sdlc-workspace.toml   # multi-component workspace
    python /path/to/sdlc-init.py --bundle sdlc-init.bundled.py   # emit a single self-contained file

Stdlib only. No network. No API keys. Free and OSS.
Templates are read from the sibling ./sdlc_templates/ dir; a bundled copy falls back
to base64 templates embedded at the bottom of the file.
"""
