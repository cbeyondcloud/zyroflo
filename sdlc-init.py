def _strip_profile_comment(line: str) -> str:
    """A profile line without its trailing `#` comment, as `policy._strip_comment` drops
    it: a `#` at the start or after a space or a TAB, outside quotes, and inside double
    quotes a backslash escapes the next character. Ported, not imported - this script is
    stdlib-only and bundles into one file - and held equal by the spelling table in
    `test_install_target_is_not_the_root.py`."""
    quote = ""
    i = 0
    while i < len(line):
        ch = line[i]
        if quote:
            if ch == "\\" and quote == '"' and i + 1 < len(line):
                i += 2
                continue
            if ch == quote:
                quote = ""
        elif ch in "\"'":
            quote = ch
        elif ch == "#" and (i == 0 or line[i - 1] in " \t"):
            return line[:i]
        i += 1
    return line


def _profile_scalar_text(raw: str) -> str:
    """A profile value as `policy.workspace_root` reads it, `str(policy._scalar(raw) or
    "").strip()`: quoted text taken verbatim (a double-quoted one with its `\\"` and
    `\\\\` escapes decoded, a single-quoted one with `''`), and an unquoted word coerced
    as YAML would - `~`, `null` and an empty value to nothing, `true` to `True`, `false`
    to nothing, a number to its normal spelling. Ported; see `_strip_profile_comment`."""
    text = raw.strip()
    if text[:1] in ('"', "'") and text[-1:] == text[:1] and len(text) >= 2:
        body = text[1:-1]
        value: object = (body.replace('\\"', '"').replace("\\\\", "\\") if text[0] == '"'
                         else body.replace("''", "'"))
    elif text in ("", "~", "null", "Null", "NULL"):
        value = None
    elif text in ("true", "True"):
        value = True
    elif text in ("false", "False"):
        value = False
    else:
        try:
            value = int(text)
        except ValueError:
            try:
                value = float(text)
            except ValueError:
                value = text
    return str(value or "").strip()


def kept_workspace_root(profile: Path) -> str | None:
    """The top-level `workspace_root` a kept profile states, read as its consumers read it
    (`policy.workspace_root`) - None when it states none (B9-7).

    The line is the consumers' own: comment-stripped as they strip it, then read as they
    read a value, through the two ports above (T583, review B12-9). A raw pattern took
    `'repos'` or a trailing comment for a missing line and told an install that works to
    add a line it already had; a hand-written mirror still read spaces inside quotes, a
    TAB before a comment, a value that is only a comment, `null`, `~` and `true`
    differently, and each was a spurious "change that line" NOTE. Since T604 the consumers
    refuse a line holding a tab outside quotes and outside a comment - a TAB before a
    comment among them - before reading any value, so for such a line there is none to
    mirror: every run step names it.
    """
    try:
        lines = profile.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError):
        return None
    for line in lines:
        line = _strip_profile_comment(line)
        if not line.startswith("workspace_root:"):
            continue
        value = _profile_scalar_text(line.split(":", 1)[1])
        return value.replace("\\", "/") or "."
    return None


def kept_workspace_root_unreachable(profile: Path) -> bool:
    """Whether a kept profile carries the line that withholds its run steps (T582), read as
    `policy.workspace_root` reads it: a `workspace_root_unreachable:` line at the top level,
    whatever its value. False for a profile that cannot be read, as `kept_workspace_root`
    answers None for one."""
    try:
        lines = profile.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError):
        return False
    return any(line.startswith(WORKSPACE_ROOT_UNREACHABLE + ":") for line in lines)


def _read_recorded_single_component(root: Path) -> tuple[bool, int] | None:
    """The structured `single_component:` block from an existing `.sdlc/profile.yml`,
    if any: `(asserted, units)`, or `None`.

    T244 round 2 (review W376 BLOCKED round 1 over exactly this). The round-1 guard
    grepped the WHOLE document for the substring `--single-component`, so an
    adopter's comment saying they chose NOT to use the flag ("we did NOT use
    --single-component here") read as an assertion and silently disabled the
    refusal it exists to override. This matches ONLY the structured key
    `render_profile` writes — never a substring of free text — so a prose mention,
    in a comment or in an older install's `stack_note`, records nothing this
    function will honour.

    `None` covers three different read states the same way: no file, a file that
    cannot be decoded, and a file with no such block. Each is "no assertion is on
    record", not evidence the flag was never used — absent is not zero.
    """
    path = root / ".sdlc" / "profile.yml"
    try:
        if not path.is_file():
            return None
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None  # unreadable profile is not evidence of absence
    # `[^\n]*` after each value: the shipped template trails a `#` comment on
    # both lines (see sdlc_templates/profile.yml), and `\s*` alone does not
    # cross a non-whitespace comment to reach the newline it is anchored on.
    m = re.search(
        r"(?m)^single_component:[ \t]*\n"
        r"[ \t]+asserted:\s*(true|false)[^\n]*\n"
        r"[ \t]+units:\s*(\d+)",
        text)
    if not m:
        return None
    return (m.group(1) == "true", int(m.group(2)))


