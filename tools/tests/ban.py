"""Maintain the leak guard's ban list — digests in, plaintext never.

    python tools/tests/ban.py --list
    python tools/tests/ban.py --add "acme-corp" --add "widget core"
    python tools/tests/ban.py --from-workspace sdlc-workspace.toml
    python tools/tests/ban.py --from-corpus sdlc-corpus.toml
    python tools/tests/ban.py --check "acme-corp"

The list is generated rather than typed, and it is generated from the SAME files that tell the
harness which repositories it is pointed at — the workspace it installs into, and the field
corpus its gates are checked against. That closes a loop worth stating plainly: the files
describing somebody's repositories are the files telling the guard what must never leak out of
them. Nothing else has to be kept in sync by hand, which is the only reason a guard like this
stays current.

Two refusals keep the list from becoming useless:

* **Stoplist** — generic words that would fire on half the tree.
* **Already present in the harness's own tracked files** — you cannot ban a token this product
  legitimately uses. This is what makes `digit` un-bannable as a 1-gram without anyone having
  to remember the rule: it occurs in a comment about parsing numerals, so the check refuses it
  and tells you to use a 2-gram instead. Ban lists that cry wolf get switched off, and a guard
  that is switched off is worse than no guard because it still looks like protection.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(ROOT))

from _scan import MAX_NGRAM, canonical, digest, load_banned, ngrams, tokenize  # noqa: E402
from tools import cli  # noqa: E402

#: This is a CLI an operator runs, and it prints phrases out of whatever file that
#: operator points it at. `test_cli.py`'s two console sweeps derive their roster from
#: `_shipped()`, which excludes everything under a `tests` directory, so this one was
#: never swept and carried no console rule at all.
cli.use_utf8()

BANLIST = Path(__file__).resolve().parent / "banned_tokens.txt"

HEADER = """\
# Leak-guard ban list — SHA-256 digests, one per line. NO PLAINTEXT, EVER.
#
# A committed file naming the workspace coordinates it guards would publish exactly what it
# protects. So this holds hashes: the matcher hashes each candidate phrase from the file being
# scanned and looks it up here, and a failure message quotes the offending text out of that
# file rather than out of this one.
#
# Entries are 1-, 2- or 3-gram phrases, normalised through the tokeniser (so `Acme-Corp`,
# `acme_corp` and `AcmeCorp` are one entry). Rule of thumb, enforced by ban.py:
#   * 1-gram  only for coined tokens that are not ordinary English words
#   * 2-/3-gram for anything ambiguous — a word the product itself might legitimately use
#
# Generated by: python tools/tests/ban.py --from-workspace <your sdlc-workspace.toml>
#               python tools/tests/ban.py --from-corpus <your sdlc-corpus.toml>
# Never hand-edit. To see what is in here, run `ban.py --check "<term>"` locally.
"""

#: Words too generic to ban: they would fire across the whole tree on their first use.
STOPLIST = frozenset({
    "core", "common", "services", "service", "config", "configs", "docs", "doc", "web", "api",
    "test", "tests", "app", "apps", "main", "data", "utils", "util", "lib", "libs", "src",
    "server", "client", "shared", "platform", "tools", "tool", "code", "repo", "repos", "git",
    "dev", "prod", "build", "release", "public", "private", "internal", "default", "local",
    "user", "users", "home", "root", "workspace", "project", "projects", "system", "base",
})

#: Path segments that carry no workspace identity and would be absurd as ban entries.
PATH_NOISE = frozenset({"c", "d", "e", "f", "mnt", "opt", "srv", "var", "tmp", "work", "code"})


def tracked_files() -> list[Path]:
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files"],
                         capture_output=True, text=True, check=True).stdout
    return [ROOT / line for line in out.splitlines() if line]


def tree_phrases() -> set[str]:
    """Every 1..3-gram the harness's own tracked files already contain."""
    present: set[str] = set()
    for path in tracked_files():
        if path == BANLIST or not path.is_file():
            continue
        try:
            raw = path.read_bytes()
        except OSError:
            continue
        if b"\x00" in raw:
            continue
        present.update(ngrams(tokenize(raw.decode("utf-8", errors="replace"))))
    return present


def vet(phrase: str, present: set[str], *, force: bool = False) -> tuple[bool, str]:
    """Should this phrase go in the list? Returns (ok, reason-if-not).

    The "already in the tree" refusal has a deliberate chicken-and-egg: while the tree is
    still being de-coupled, the offending phrases ARE present, and refusing them would make
    the list unseedable. `--force` is the way through, and it is a separate, visible flag
    rather than a silent bypass — the operator is asserting "those occurrences are the
    violations I am about to remove", which is a claim worth making explicitly.

    The stoplist refusal is never forceable, and neither is an over-long phrase: those are
    matcher limits, not judgement calls.
    """
    toks = tokenize(phrase)
    if not toks:
        return False, "empty after tokenisation"
    if len(toks) > MAX_NGRAM:
        return False, f"{len(toks)} tokens — the matcher only compares up to {MAX_NGRAM}"
    if len(toks) == 1 and toks[0] in STOPLIST:
        return False, "too generic (stoplist) — try a 2-gram that includes it"
    if canonical(toks) in present and not force:
        return False, ("the harness's own tracked files already use this. If that usage is "
                       "legitimate, pick a longer phrase; if those occurrences are violations "
                       "you are about to remove, re-run with --force")
    return True, ""


def read_list() -> list[str]:
    return sorted(load_banned(BANLIST)) if BANLIST.exists() else []


def write_list(digests: set[str]) -> None:
    BANLIST.write_text(HEADER + "\n".join(sorted(digests)) + "\n", encoding="utf-8")


def load_toml(flag: str, path: Path) -> dict | None:
    """Read one of the operator's TOML files, or say which one and why not.

    Returns None having printed the refusal; the caller exits 2, the code this CLI
    already owns for *the input could not be read*. Before this, `tomllib` raised
    through `main` and Python exited 1 — a code `main()` never returns, so "your
    file has a typo on line 7" and "this tool is broken" arrived looking identical,
    and the stack frames named the operator's own file. That is the shape item 117
    found in `policy.py --validate`, in the one module whose whole job was refusing
    a document it could not read.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        print(f"!! cannot read {flag}: {path}", file=sys.stderr)
        print(f"   {exc}", file=sys.stderr)
        return None
    try:
        return tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        print(f"!! not valid TOML for {flag}: {path}", file=sys.stderr)
        print(f"   {exc}", file=sys.stderr)
        return None


def from_workspace(ws: dict) -> list[str]:
    """Derive candidate phrases from a filled-in workspace config."""
    phrases: list[str] = []
    if name := ws.get("name", "").strip():
        phrases.append(name)
    for comp in ws.get("component", []):
        if cname := str(comp.get("name", "")).strip():
            phrases.append(cname)
    for seg in Path(str(ws.get("root", ""))).parts:
        seg = seg.strip("\\/:")
        if seg and seg.lower() not in PATH_NOISE:
            phrases.append(seg)
    return phrases


def from_corpus(doc: dict) -> list[str]:
    """Derive candidate phrases from a filled-in field-corpus manifest.

    The same loop as `from_workspace`, closed around the other file that names
    somebody's repositories: item 96's corpus lists the repositories the gates
    are checked against, and those names have exactly as much business in this
    tree as a workspace's do — none. A name is only guarded if the guard is
    told about it, so the tool that reads the corpus is the tool that seeds it.
    """
    phrases: list[str] = []
    for entry in doc.get("repo", []):
        if not isinstance(entry, dict):
            continue
        if name := str(entry.get("name", "")).strip():
            phrases.append(name)
        # The path's segments, for the same reason `from_workspace` takes them:
        # a checkout's directory is usually the product's name.
        for seg in Path(str(entry.get("path", ""))).parts:
            seg = seg.strip("\\/:")
            if seg and seg.lower() not in PATH_NOISE:
                phrases.append(seg)
    return phrases


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--add", action="append", default=[], metavar="PHRASE")
    ap.add_argument("--from-workspace", type=Path, metavar="TOML")
    ap.add_argument("--from-corpus", type=Path, metavar="TOML",
                    help="a filled-in sdlc-corpus.toml (item 96)")
    ap.add_argument("--check", metavar="PHRASE", help="is this phrase banned? (prints yes/no)")
    ap.add_argument("--list", action="store_true", help="digest count only — never plaintext")
    ap.add_argument("--force", action="store_true",
                    help="add phrases the tree still contains — for seeding during de-coupling, "
                         "when those occurrences are the violations being removed")
    args = ap.parse_args(argv)

    try:
        current = set(read_list())
    except (OSError, ValueError) as exc:
        # ABSENT, EMPTY and COULD-NOT-LOOK are three different facts. `read_list`
        # answers the first with an empty list and raises on the third, and that
        # raise must stay a refusal: folding it into the empty case would make the
        # next `--add` rewrite the file from one digest and silently disarm the
        # guard for every term already in it.
        print(f"!! cannot read {BANLIST.name}: {exc}", file=sys.stderr)
        print("   refusing to touch it — rewriting a list that could not be read "
              "would drop every digest in it.", file=sys.stderr)
        return 2

    if args.check:
        print("banned" if digest(args.check) in current else "not banned")
        return 0

    if args.list or not (args.add or args.from_workspace or args.from_corpus):
        rel = BANLIST.relative_to(ROOT) if BANLIST.is_relative_to(ROOT) else BANLIST
        if not BANLIST.exists():
            # Not "0 digest(s)": a count of zero says the guard is armed and nothing
            # is banned, which is the opposite of nobody having seeded it.
            print(f"{rel}: not created yet — nothing is guarded until it is seeded")
            print("(seed it with --from-workspace or --from-corpus)")
            return 0
        print(f"{rel}: {len(current)} digest(s)")
        print("(contents are hashes by design — use --check '<term>' to test one)")
        return 0

    candidates = list(args.add)
    for flag, path, reader in (("--from-workspace", args.from_workspace, from_workspace),
                               ("--from-corpus", args.from_corpus, from_corpus)):
        if path is None:
            continue
        if not path.is_file():
            print(f"!! no such file for {flag}: {path}", file=sys.stderr)
            return 2
        doc = load_toml(flag, path)
        if doc is None:
            return 2
        candidates += reader(doc)

    present = tree_phrases()
    added = refused = 0
    still_dirty: list[str] = []
    for phrase in candidates:
        ok, why = vet(phrase, present, force=args.force)
        shown = " ".join(tokenize(phrase)) or phrase
        if not ok:
            print(f"  refused {shown!r}: {why}")
            refused += 1
            continue
        d = digest(phrase)
        if d in current:
            print(f"  already present: {shown!r}")
            continue
        current.add(d)
        added += 1
        note = ""
        if canonical(tokenize(phrase)) in present:
            still_dirty.append(shown)
            note = "  <-- STILL IN THE TREE"
        print(f"  added {shown!r} -> {d[:12]}...{note}")

    if added:
        write_list(current)
    print(f"\n{added} added, {refused} refused; {len(current)} digest(s) total")
    if still_dirty:
        print(f"\n{len(still_dirty)} forced entr{'y' if len(still_dirty) == 1 else 'ies'} the tree "
              f"still contains. The guard WILL fail until those occurrences are removed — that "
              f"is the point, not a bug.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
